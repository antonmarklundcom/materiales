<h2>Para qué se usa</h2>
<p>
  La <strong>pintura para piso</strong> se usa sobre todo como <strong>pintura para pisos de
  cemento</strong>: carpetas alisadas, contrapisos terminados, garajes, galerías, quinchos,
  patios y veredas internas. Cubre el gris del cemento, lo protege del desgaste y hace que el
  piso se limpie más fácil y largue menos polvo. Se la pide también como <strong>pintura para
  garaje</strong> cuando lo que va a circular son autos, y como <strong>pintura para
  cancha</strong> o de demarcación cuando se pintan líneas en un patio o una cancha de
  cemento. Para tránsito pesado o para pisos que reciben aceite y químicos se usa la
  <strong>pintura epoxi</strong>, que forma una película más dura y resistente que la común;
  entre las dos hay productos de <strong>alto tránsito</strong> pensados para comercios y
  galerías. No es la solución para un piso de cerámica o porcelanato esmaltado, donde la
  pintura no agarra igual: si lo que buscás es cambiar el aspecto de un piso cerámico, mirá las
  opciones de revestimiento como el <a href="/materiales/piso-vinilico/">piso vinílico</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>lata o balde</strong>, en los litrajes de cada producto; la epoxi suele
  venir en dos componentes que se mezclan en obra, y conviene confirmar si la cotización los
  incluye a los dos. La cantidad sale de los m² de piso por las manos que pide el envase,
  dividido por el rendimiento que figura en el envase. Para pedir bien, pasá los m² a pintar,
  qué va a circular por encima —gente, autos, carga—, si el piso está bajo techo o a la
  intemperie y si el cemento es nuevo o ya estuvo pintado. Sumá en el mismo pedido el
  imprimante o la primera mano diluida si el producto la pide, los rodillos de pelo corto y el
  diluyente. El precio depende del tipo de pintura, del color, del litraje, de la cantidad de
  manos, de los m² y del flete hasta tu zona.
</p>
<p>
  Un ejemplo: un garaje de 3 × 6 m son 18 m² y una galería de 2,5 × 8 m, 20 m². Pasalos en dos
  líneas y no como 38 m² juntos: por el garaje circulan autos y por la galería gente, y si una
  está bajo techo y la otra a la intemperie, puede que no corresponda el mismo producto. Las
  manos y el rendimiento de cada uno figuran en su envase.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Lo primero es el piso, no la pintura. Tiene que estar seco, limpio, sin grasa, sin polvo
  suelto y, si es un contrapiso o una carpeta nueva, bien curado: pintar cemento fresco es
  garantía de que la película se ampolle. Una carpeta alisada muy lisa a veces necesita abrir
  el poro antes de pintar, y un piso con humedad que sube desde abajo va a levantar cualquier
  pintura. Elegí el producto por el tránsito real y no por el nombre: una pintura para
  tránsito peatonal no aguanta las ruedas de un auto al girar. Preguntá si la terminación es
  antideslizante o si conviene agregarle carga, sobre todo en galerías y bordes de pileta que
  se mojan. Y respetá el tiempo de secado antes de habilitar el paso, que figura en el envase.
</p>

