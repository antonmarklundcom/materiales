<h2>Para qué se usa</h2>
<p>
  Los puntales son la pieza que sostiene el encofrado de una losa o una viga mientras el
  hormigón toma resistencia: van apoyados en el piso de abajo, en vertical, aguantando el peso
  de la <a href="/materiales/tabla-de-encofrado/">tabla de encofrado</a> o la terciada, más el
  hormigón fresco que se vuelca encima. Se los pide también como <strong>puntal para
  encofrado</strong>, y el trabajo en conjunto de colocarlos y calcular cuántos van se conoce
  como <strong>apuntalamiento</strong>. En obra chica lo habitual es el puntal de madera; en
  obras más grandes se suele complementar con puntales metálicos regulables, que se alquilan
  aparte.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>pieza</strong>. Para pedir bien contá la <strong>superficie a
  apuntalar</strong> (los metros cuadrados de losa) y el <strong>espesor de la losa</strong>,
  porque de ahí sale cuántos puntales necesitás y qué tan seguido hay que colocarlos; también
  hace falta la <strong>altura</strong> entre el piso de apoyo y el fondo del encofrado, para
  saber el largo de puntal que corresponde. El precio depende del largo de la pieza, el tipo
  de madera, la cantidad total y el flete hasta la obra, y conviene tenerlo en cuenta junto
  con el resto del encofrado para no duplicar el viaje del flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el largo de puntal que te ofrecen corresponda a la altura real de tu entrepiso,
  con margen para la cuña o el ajuste final. Preguntá si las piezas ya vinieron de otra obra:
  un puntal reutilizado varias veces puede tener rajaduras o nudos que lo debilitan, y conviene
  revisarlos uno por uno antes de colocarlos. Calculá la cantidad con margen, porque un
  apuntalamiento corto de piezas obliga a espaciarlos más de lo recomendable y eso compromete
  la losa mientras fragua. Si el sistema es de reutilización entre etapas de la obra, planificá
  los tiempos de desencofrado antes de definir cuántos puntales comprar en total.
</p>

