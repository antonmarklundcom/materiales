<h2>Para qué se usa</h2>
<p>
  Las maderas duras paraguayas —<strong>curupay</strong>, <strong>lapacho</strong>, yvyraró y
  otras especies nativas, agrupadas muchas veces bajo <strong>madera nativa</strong>— se eligen
  para piezas que quedan expuestas al sol y a la lluvia, o simplemente a la vista, donde una
  madera blanda se deterioraría rápido o no daría la terminación buscada. Se usan en
  estructuras de techo que van a quedar sin revestir, en decks exteriores, en aberturas y en
  muebles de obra. El <strong>eucalipto</strong> aparece en la misma familia para usos más
  utilitarios y de menor exigencia, como estructuras que van a quedar cubiertas.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>pieza o por metro lineal</strong>. Para pedir bien necesitás definir la
  <strong>especie</strong> según el uso y la exposición, la <strong>escuadría</strong> y el
  <strong>largo</strong> de cada pieza, y aclarar si la querés <strong>cepillada o en
  bruto</strong>. Si es para estructura, contá también la luz que tiene que cubrir. El precio
  depende sobre todo de la especie elegida, de la escuadría y el largo, de si viene cepillada o
  en bruto, del estado de secado y de la cantidad de piezas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá siempre si la madera viene <strong>estacionada</strong> o recién aserrada: una
  pieza verde se mueve y se abre al secar, y en madera dura eso es más notorio porque las
  piezas suelen quedar a la vista. Elegí la especie según la exposición real de la pieza —no es
  lo mismo una viga bajo techo que un deck que recibe sol y lluvia todo el año— y no sólo por
  el precio, porque una especie mal elegida para el ambiente se deteriora antes de lo esperado.
  Como referencia general de uso:
