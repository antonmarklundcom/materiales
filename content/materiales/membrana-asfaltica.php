<h2>Para qué se usa</h2>
<p>
  La membrana asfáltica —también conocida como <strong>membrana aluminizada</strong> cuando
  lleva foil metálico en la cara expuesta— es la solución de referencia para
  <strong>losas y azoteas</strong> grandes: una losa expuesta a la que no le sigue una
  construcción encima, un techo de losa transitable o no, cualquier superficie horizontal que
  tiene que quedar estanca antes de la temporada de lluvias. Viene en <strong>rollo</strong>,
  se coloca con soplete adherida a la superficie, y por eso cubre metros cuadrados grandes en
  poco tiempo, a diferencia de un producto que se aplica mano por mano. Si el techo tiene
  muchos quiebres, bajadas y detalles donde el rollo no entra cómodo, ahí conviene mirar la
  <a href="/materiales/membrana-liquida/">membrana líquida</a> en su lugar, o como
  complemento en los remates.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>rollo de membrana</strong>, y cada rollo cubre una cantidad de metros
  cuadrados que depende del espesor elegido: a mayor espesor, menos metros por rollo pero más
  vida útil y más tolerancia al sol directo. Para pedir bien conviene calcular los m² reales
  de la superficie más el solape entre paños —la membrana se superpone en los bordes, no se
  coloca a tope— y pasar ese número junto con el espesor que buscás. El precio final depende
  del espesor, de la cantidad de rollos que salen con el solape incluido, y del flete hasta tu
  obra, así que conviene pedir los m² exactos en vez de una cantidad de rollos estimada a ojo.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de colocar cualquier rollo, revisá que la superficie esté seca, limpia, sin partes
  flojas y con pendiente hacia el desagüe: si el agua queda estancada, ninguna membrana dura
  lo que debería, por buena que sea. Fijate también si la losa va a quedar transitable —en
  ese caso conviene un espesor mayor y protección adicional— o si sólo queda expuesta al sol y
  la lluvia. La colocación con soplete pide mano de obra con experiencia, porque una pasada mal
  hecha deja puntos débiles que se filtran con el tiempo. Y si el desagüe pluvial no está
  resuelto, conviene revisar las <a href="/materiales/canaletas/">canaletas</a> en la misma
  obra, porque una membrana perfecta no compensa una bajada de agua que no funciona.
</p>

