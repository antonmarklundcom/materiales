<h2>Para qué se usa</h2>
<p>
  La varilla de hierro —lo que en la mayoría de las obras se pide directo como
  <strong>fierro de construcción</strong> o <strong>hierro de construcción</strong>— es el
  armado que va dentro del hormigón: columnas, vigas, losas, zapatas y los estribos que
  encierran esas piezas. Es la que en Paraguay casi todos conocen como <strong>hierro
  nervurado</strong> o <strong>varilla conformada</strong>, por las nervaduras que le dan mejor
  adherencia al hormigón que una barra lisa. Se pide por diámetro —hierro de 8, de 10, de 12,
  según la pieza que vayas a armar— y ese diámetro no lo elige el gusto sino el cálculo
  estructural: una losa liviana no lleva la misma <strong>barra de hierro</strong> que una
  columna que carga varios pisos. Cuando la pieza es chica y no exige mucho armado —una
  vereda, un contrapiso sin carga— suele alcanzar con la
  <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a> en lugar de varilla
  cortada y atada a mano.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>barra de 12 metros</strong>, y también por <strong>kilo</strong> o por
  <strong>tonelada</strong> cuando el volumen es grande: en obra chica se compra por barra, en
  estructura completa conviene pedir las dos formas y comparar, porque el precio por kilo suele
  mejorar con la cantidad. Para que te coticen bien necesitás decir el <strong>diámetro</strong>
  de cada varilla, la <strong>cantidad de barras</strong> por diámetro y tu <strong>zona</strong>
  de entrega. Si el plano pide barras dobladas a medida o cortadas a un largo específico, eso se
  cotiza como servicio aparte del material, igual que el flete. El precio final se mueve según
  el diámetro, el volumen total en kilos o toneladas, si comprás por barra suelta o por lote
  completo, y la distancia hasta la obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de pedir, confirmá que el diámetro que vas a llevar es el que indica el plano o el
  calculista: usar un diámetro menor "para ahorrar" es el error más común y el más caro de
  corregir después. Fijate también que las barras vengan derechas, sin óxido avanzado ni
  dobleces previos, y que las nervaduras estén marcadas de forma pareja en toda la longitud.
  La tabla siguiente es una referencia general de para qué se usa cada diámetro habitual en
  obra de vivienda; el cálculo estructural de tu proyecto puede pedir otra combinación.
</p>
