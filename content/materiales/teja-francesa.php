<h2>Para qué se usa</h2>
<p>
  La teja francesa —también llamada <strong>teja marsellesa</strong> o
  <strong>teja plana</strong>— se distingue de la teja colonial por su perfil recto y su
  sistema de encastre: cada pieza traba con la de al lado por un borde, en vez de apoyarse por
  superposición curva. Esa unión más ajustada la hace buena opción para techos con líneas
  rectas y una terminación más prolija y pareja a la vista, típica de construcciones de estilo
  más moderno o de influencia europea. Se usa en vivienda, en techos con pendientes marcadas y
  en obras donde se busca una <strong>teja cerámica francesa</strong> sin la curvatura de la
  teja colonial. Si el estilo que buscás es el techo colonial o de campo tradicional, la
  <a href="/materiales/teja-espanola/">teja española</a> es la que corresponde.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad o por millar</strong>. Para pedir bien necesitás la
  <strong>superficie de techo a cubrir</strong>, la cantidad de piezas por m² según el sistema
  de encastre del fabricante (varía entre marcas, a diferencia de la superposición más libre de
  la teja colonial) y la <strong>pendiente</strong> proyectada. El tirantillo de apoyo y las
  piezas especiales de remate, cumbrera y limahoya se cotizan aparte del cuerpo de teja. El
  precio final depende de la cantidad de piezas, del acabado (natural o esmaltado) y del flete
  hasta tu zona.
</p>
<p>
  Los m² que se pasan son los del techo sobre la pendiente, no los de la planta. Un ejemplo: un
  techo a 2 aguas con faldones de <strong>4 m</strong> de cumbrera a alero y <strong>9 m</strong>
  de largo son 4 × 9 × 2 = <strong>72 m²</strong>, la misma superficie que te da la
  <a href="/calculadoras/chapas-para-techo/">calculadora de chapas para techo</a> con esas
  medidas. Esos 72 m² multiplicados por las piezas por m² que indica el fabricante del modelo
  que elijas dan las tejas del cuerpo; las de remate y cumbrera se cuentan aparte.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Como el encastre es más ajustado que en la teja colonial, revisá que las piezas de un mismo
  lote calcen bien entre sí sin forzar, porque una pequeña diferencia de tamaño entre tejas de
  distinta partida puede dejar juntas irregulares. Fijate en la cocción pareja de la arcilla —
  color uniforme, sin manchas de subcocción— y en que los bordes de encastre no vengan
  astillados, porque ahí es donde se traba la pieza siguiente. Pedí siempre algunas piezas de
  más sobre el cálculo teórico, para tener repuesto del mismo lote ante alguna rotura durante
  la colocación.
</p>

