<h2>Para qué se usa</h2>
<p>
  El adhesivo para cerámica —que en la mayoría de las obras se pide simplemente como
  <strong>pegamento para cerámica</strong> o <strong>cola para cerámica</strong>— es el que reemplaza a la
  mezcla de cemento y arena para fijar piso y revestimiento cuando se busca un agarre más parejo y menos
  peso sobre la superficie. Se usa tanto en piso interior como en pared de baño y cocina, y en su versión
  reforzada funciona como <strong>adhesivo para porcelanato</strong>, porque esa pieza pesa más y absorbe
  menos que la cerámica común, así que necesita un agarre distinto para no despegarse con el tiempo. Una
  vez colocada la pieza, la <strong>pastina</strong> es la que toma la junta entre placa y placa,
  cerrando el trabajo y evitando que se filtre humedad por esas líneas. Cubre desde el baño chico hasta el
  living entero, siempre que la base esté firme y nivelada antes de aplicar.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>bolsa</strong>, generalmente como <strong>adhesivo en polvo</strong> que se mezcla
  con agua en el momento de usar. Para pedirlo bien conviene decir los metros cuadrados a cubrir y si la
  pieza es cerámica común o porcelanato, porque el tipo de adhesivo cambia según el peso y la absorción de
  la pieza. La pastina para tomar juntas se cotiza como ítem aparte del adhesivo, y conviene pedirla en la
  misma consulta indicando el color que buscás, porque no siempre está disponible en todos los tonos. El
  precio depende de la cantidad de bolsas, del tipo de adhesivo —común o reforzado para porcelanato— y del
  flete hasta tu obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el adhesivo que elegís esté pensado para el tipo de pieza que vas a colocar: usar un adhesivo
  común en porcelanato es uno de los errores más frecuentes, y con el tiempo el peso de la placa termina
  despegándola. Revisá también dónde va la instalación: baño, exterior o zona con humedad constante piden
  un adhesivo con mejor resistencia al agua que el de uso interior general. Antes de comprar, calculá bien
  la cantidad según el tamaño de la pieza y el espesor de la capa que vas a aplicar, porque quedarte corto
  a mitad de colocación te obliga a mezclar dos lotes distintos y eso puede notarse en el color final del
  adhesivo bajo piezas translúcidas.
</p>

