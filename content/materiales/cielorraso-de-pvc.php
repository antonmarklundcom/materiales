<h2>Para qué se usa</h2>
<p>
  El PVC para techos se usa para armar un <strong>cielorraso de PVC</strong> —también llamado
  <strong>cielo raso de PVC</strong> o simplemente "cielorraso"— que cierra por dentro un
  ambiente debajo de una chapa o losa, tapando la estructura y mejorando la terminación
  interior. Se instala en dormitorios, salas, corredores y galerías, y también en exteriores
  cubiertos como aleros, porque a diferencia de un cielorraso de madera no se pudre con la
  humedad. Se vende en tablillas o láminas conocidas como <strong>tablilla de PVC</strong> o
  <strong>machimbre de PVC</strong>, que encastran entre sí igual que un machimbre de madera
  pero sin el mantenimiento que pide la madera. Si el techo de arriba no tiene aislación, un
  cielorraso de PVC ayuda a tapar la vista de la estructura pero no reemplaza a una
  <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a> cuando lo que hace falta
  es cortar calor.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cuadrado o por tablilla</strong>, según el proveedor. Para pedir
  bien necesitás la <strong>superficie del ambiente</strong> a cubrir, el
  <strong>ancho de tablilla</strong> que preferís (afecta cuántas uniones quedan a la vista) y
  si necesitás <strong>perfil U de arranque</strong> y perfiles de terminación en los bordes,
  que se cotizan aparte de las tablillas. El precio final depende de la cantidad de m², del
  ancho de tablilla elegido y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en el <strong>espesor de la tablilla</strong>: una tablilla muy fina se puede curvar o
  marcar con el tiempo, sobre todo en tramos largos sin apoyo intermedio. Revisá que el color
  sea uniforme entre tablillas de una misma partida, porque el PVC de distintos lotes puede
  variar levemente de tono bajo luz directa. Comprobá que el sistema de encastre calce sin
  forzar y que la estructura de soporte (perfilería metálica o listones) esté bien nivelada
  antes de instalar, porque el PVC no perdona una base torcida como sí lo disimula algo más un
  cielorraso de otro material. Pedí siempre los perfiles de arranque y terminación en el mismo
  pedido para no tener que salir a buscar un color que ya no coincide.
</p>

