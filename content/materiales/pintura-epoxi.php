<h2>Para qué se usa</h2>
<p>
  La <strong>pintura epoxi</strong> —también pedida como <strong>pintura epóxica</strong>— se
  usa cuando una pintura común no alcanza: forma una película más dura y resistente al desgaste,
  a la limpieza frecuente y al roce. Su uso más pedido es como <strong>pintura epóxica para
  piso</strong> o <strong>epoxi para pisos</strong>: garajes, talleres, depósitos, galerías y
  locales donde el piso se maltrata. Cuando lo que se quiere es un acabado continuo y prolijo, se
  habla de <strong>pisos epoxi</strong>, y en el mostrador también aparece como
  <strong>resina epóxica</strong> cuando se trata de recubrir el piso. Para <strong>metal</strong>
  se pide la <strong>pintura epóxica para metal</strong>, y a veces se la nombra como
  <strong>hidroesmalte epoxi</strong>: sirve para estructuras, portones y piezas de hierro que
  necesitan más protección que un esmalte común. Para retoques y piezas chicas existe además el
  <strong>epoxi en aerosol</strong>. Si tu piso es de cemento y el tránsito es liviano, puede
  alcanzarte con la <a href="/materiales/pintura-para-piso/">pintura para piso</a>; el epoxi es
  el paso siguiente cuando hay autos, aceite o limpieza pesada.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende en <strong>balde o kit</strong>, según el producto. Preguntá si viene en kit de dos
  componentes (producto base y endurecedor), si la cotización incluye los dos y cómo se
  mezclan. Para que el proveedor te cotice bien, pasale los m² del piso o de las piezas, qué va a
  circular por encima o a qué esfuerzo se somete la superficie, si es bajo techo o a la
  intemperie, si el cemento es nuevo o ya tiene pintura y el color que querés: la
  <strong>pintura epoxi para piso en colores</strong> se pide por muestra, no de memoria. En el
  mismo pedido sumá el imprimante o fondo que indique el producto, los rodillos y el diluyente o
  limpiador que recomiende el fabricante. El rendimiento, las manos y los tiempos de secado
  figuran en el envase: pedí que te los confirmen para tu superficie. El precio depende del
  tipo de epoxi, del color, de la cantidad, de la superficie a cubrir y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El éxito del epoxi está en la preparación, más que en el producto. El piso tiene que estar
  seco, limpio, sin grasa ni polvo suelto y, si el cemento es nuevo, bien curado. Si hay humedad
  que sube desde abajo, resolvela primero con quien dirige la obra, porque el epoxi no la
  corrige; para paredes con humedad mirá la
  <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>. En metal, hay que sacar el óxido y limpiar
  la pieza antes de pintar; si ya la protegiste con un
  <a href="/materiales/esmalte-sintetico/">esmalte sintético</a>, preguntá si el epoxi es
  compatible. Una superficie porosa o muy absorbente puede pedir un
  <a href="/materiales/sellador-para-pared/">sellador</a> o un fondo antes de la primera mano.
  Y si lo que buscás es un acabado continuo de aspecto distinto, mirá también el
  <a href="/materiales/microcemento/">microcemento</a>.
</p>
