<h2>Para qué se usa</h2>
<p>
  El bloque de hormigón —también llamado <strong>bloque de cemento</strong>,
  <strong>bloque vibrado</strong> o <strong>bloquete</strong>— se usa para levantar paredes más
  rápido, porque cada pieza cubre más superficie que un ladrillo y avanza el metro cuadrado de
  obra en menos jornadas. Se usa mucho en muros perimetrales, galpones, depósitos y en obras
  donde el plazo apura, tanto en pared portante como en cerramiento simple. También se usa en
  cimientos de poca altura y en muros de contención livianos, aprovechando que el hueco interior
  se puede rellenar con hormigón y hierro cuando la pared necesita más resistencia. Si en cambio
  la obra busca la mampostería tradicional de siempre, el
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a> sigue siendo la opción más habitual
  para tabiques internos.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad</strong> o por <strong>palet</strong>, según cómo trabaje el
  proveedor, así que conviene confirmar cuál de las dos formas usa antes de comparar precios
  entre cotizaciones distintas. Para pedir bien necesitás el metro cuadrado de pared a cubrir y
  el espesor del bloque —los más comunes rondan los 15 y los 20 centímetros—, porque de ahí sale
  la cantidad de unidades o palets que hacen falta. Si la pared va a ser estructural con relleno
  de hormigón y hierro, avisá eso también porque cambia el tipo de bloque que corresponde pedir.
  El flete se cotiza aparte y pesa bastante por el peso del material, así que la zona de entrega
  influye directo en el total.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que los bloques no tengan fisuras ni los bordes descascarados, porque un bloque golpeado
  en el traslado pierde escuadra y complica el asentado parejo. Revisá que el tamaño sea
  uniforme entre unidades del mismo pedido: una diferencia de pocos milímetros por pieza se
  acumula rápido en una pared larga. Si vas a usar bloque estructural, confirmá que el hueco
  tenga el diámetro adecuado para pasar el hierro vertical sin apretarlo. Un error común es
  comprar bloque de cemento pensando que es lo mismo que un adoquín: son productos distintos,
  con usos distintos, y no se reemplazan entre sí.
</p>

