<h2>Para qué se usa</h2>
<p>
  El ladrillo refractario está hecho para aguantar el fuego directo y las altas temperaturas
  sostenidas, algo que ningún ladrillo común resiste sin rajarse. Se pide sobre todo como
  <strong>ladrillo para parrilla</strong> y <strong>ladrillo para horno</strong>, y también como
  <strong>ladrillo para quincho</strong> cuando se construye el sector completo con hogar a leña.
  Se usa en la cámara de combustión de parrillas y hornos de barro, en chimeneas con contacto
  directo con la llama y en cualquier estructura donde el material esté expuesto a ciclos
  repetidos de calor intenso y enfriamiento. No se usa en pared ni en mampostería general: para
  eso está el <a href="/materiales/ladrillo-comun/">ladrillo común</a>, que es más barato y
  cumple bien donde no hay fuego directo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad</strong> cuando el proyecto es chico —una parrilla o un horno de
  barro— y por <strong>millar</strong> cuando se trata de una obra de mayor escala. Para pedirlo
  bien conviene tener el diseño de la cámara de combustión, porque de ahí sale la cantidad de
  piezas necesarias. El mortero refractario para asentar estas piezas se cotiza aparte del
  ladrillo, y conviene pedirlo en la misma consulta porque un mortero común no resiste la misma
  temperatura y se desarma con el uso. El precio final depende de la cantidad de piezas, del
  tipo de refractario y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el ladrillo sea realmente refractario y no un ladrillo colorado común pintado o
  presentado como tal, porque a simple vista pueden confundirse y el común se raja con el primer
  uso intenso. Revisá que no tenga fisuras visibles antes de asentarlo, porque una grieta previa
  se agranda rápido con el calor. Usá siempre mortero refractario para las juntas, nunca mortero
  de albañilería común, porque este último no soporta la dilatación térmica y se desprende. Un
  error frecuente es comprar ladrillo común para una parrilla pensando que aguanta igual: no es
  así, y la diferencia se nota apenas se prende el primer fuego fuerte.
</p>

