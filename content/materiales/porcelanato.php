<p>
  El <strong>rectificado</strong> es lo que da bordes exactos entre pieza y pieza, lo que
  permite colocar con junta mínima y un resultado más prolijo; una pieza sin rectificar
  necesita junta más ancha para disimular la diferencia de medida entre placas. En zonas
  húmedas o de tránsito con agua, priorizá el acabado mate o con tratamiento antideslizante por
  sobre el pulido, porque el brillo del pulido resbala más al mojarse. Un error frecuente es
  usar adhesivo de cerámica común en porcelanato pensando que da lo mismo: con el tiempo el
  peso de la placa termina despegándola, así que conviene confirmar siempre que el adhesivo sea
  el indicado para esta pieza.
</p>

