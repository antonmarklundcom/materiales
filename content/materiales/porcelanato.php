<h2>Para qué se usa</h2>
<p>
  El porcelanato es la pieza que se elige cuando se busca un piso de mayor dureza y menor
  absorción de agua que la cerámica común, algo clave en <strong>pisos porcelanato</strong>
  para living, cocina y ambientes de tránsito constante. Su cuerpo es más compacto y menos
  poroso que el de la cerámica, por eso resiste mejor golpes, manchas y el paso diario sin
  perder terminación con el tiempo. Es también la elección típica para
  <strong>porcelanato para cocina</strong>, donde se combinan derrames, calor y limpieza
  frecuente. Dentro de la familia está el <strong>porcelanato símil madera</strong>, que
  reproduce la veta y el color de la madera natural pero sin el mantenimiento ni el riesgo de
  humedad de una tabla real, muy pedido para living y dormitorios. Si el presupuesto de la obra
  no da para porcelanato en toda la superficie, la
  <a href="/materiales/ceramica-para-piso/">cerámica para piso</a> cubre ambientes de menor
  exigencia con una inversión menor.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>, en <strong>caja cerrada</strong>, igual que la
  cerámica: el pedido se redondea al múltiplo de caja más cercano por encima de la superficie
  real. Para cotizar necesitás la superficie a cubrir, el <strong>formato</strong> de la pieza
  y si buscás terminación <strong>pulida</strong> o <strong>mate</strong>, porque cada acabado
  cambia tanto el aspecto como el comportamiento al pisarlo mojado. El adhesivo se cotiza
  aparte y tiene que ser el reforzado para porcelanato, no el común de cerámica, porque el peso
  y la baja absorción de la pieza exigen mejor agarre. El precio depende del formato, del
  acabado elegido, de si la pieza es <strong>rectificada</strong> o no, y del volumen total en
  m² pedido.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El formato más pedido hoy es el 60x60, que da pocas juntas y un piso más continuo, aunque
  también se consigue en formatos mayores para ambientes grandes y en piezas rectangulares tipo
  símil madera con proporciones más alargadas.
</p>
