<h2>Para qué se usa</h2>
<p>
  El tejuelón —también conocido como <strong>tejuela</strong> o
  <strong>ladrillo para losa</strong>— no es un ladrillo de pared, sino la pieza cerámica que se
  apoya entre viguetas para armar una losa de piso o de techo. Se usa junto con las viguetas
  premoldeadas y el hormigón de la capa de compresión, formando lo que en obra se conoce como
  <strong>losa de tejuelón</strong> o bovedilla cerámica. Es una de las formas más comunes de
  hacer entrepiso en Paraguay porque aligera la losa respecto de una placa maciza de hormigón,
  reduciendo el peso propio de la estructura sin perder la resistencia que da el conjunto vigueta
  más tejuelón. Se usa tanto en losas de piso entre plantas como en techos que después llevan
  contrapiso e impermeabilización. No hay que confundirlo con el
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a>, que es para pared y no para losa.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>millar</strong>, calculado sobre el metro cuadrado de losa a cubrir y la
  separación entre viguetas del diseño estructural, dato que suele definir el calculista o el
  proveedor de viguetas. Al pedir el tejuelón conviene coordinarlo con el mismo proveedor de
  viguetas para que las medidas sean compatibles, porque no todos los tejuelones calzan igual con
  cualquier separación entre vigas. El flete se cotiza aparte y depende del volumen y la
  distancia hasta la obra. El precio final varía según la cantidad de millares, el tipo de
  tejuelón y si se pide junto con las viguetas o por separado.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que las piezas no vengan rajadas ni con las paredes colapsadas, porque un tejuelón
  débil puede ceder durante el hormigonado de la capa de compresión. Revisá que la medida sea
  compatible con la separación entre viguetas que definió el cálculo estructural, porque un
  tejuelón de medida distinta obliga a rellenos improvisados que debilitan la losa. Confirmá con
  el proveedor la cantidad exacta según los metros cuadrados de losa, dejando un margen para
  roturas propias del traslado y la colocación.
</p>

