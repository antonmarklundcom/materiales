<h2>Para qué se usa</h2>
<p>
  La malla electrosoldada —muchos la piden como <strong>malla de hierro</strong>, otros por su
  nombre comercial más conocido, <strong>malla sima</strong>— reemplaza al armado atado barra
  por barra en piezas donde no hace falta un cálculo tan fino: contrapisos, veredas, patios y
  losas livianas. Viene en paños con la cuadrícula ya soldada, así que en obra se coloca
  directo, se superpone entre paños y se ahorra buena parte de las horas que lleva atar hierro
  a mano. Es la opción típica para <strong>malla para contrapiso</strong>, donde lo que se
  busca es evitar que el hormigón se fisure con el uso, más que resistir una carga estructural
  grande. Cuando la pieza sí es estructural —una columna, una viga, una losa que carga
  varios ambientes— eso se resuelve con <a href="/materiales/varilla-de-hierro/">varilla de
  hierro</a> calculada, no con malla. Y la malla que se fija sobre la pared para que agarre el
  revoque tampoco es ésta: es el <a href="/materiales/metal-desplegado/">metal desplegado</a>,
  una sola chapa cortada y estirada, sin soldaduras.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>paño</strong> y, en algunas medidas, por <strong>rollo</strong>. Para
  pedir bien, lo más práctico es dar los <strong>metros cuadrados</strong> que necesitás cubrir
  y el uso —vereda, contrapiso de vivienda, galpón— y no la cantidad exacta de paños: el
  proveedor calcula cuántos paños hacen falta considerando la superposición que siempre se deja
  entre uno y otro. El diámetro del alambre y la separación de la cuadrícula también entran en
  la cotización, porque no todas las mallas tienen la misma cuadrícula ni el mismo grosor. El
  flete hasta tu zona se cotiza aparte del material. El precio final depende de la medida del
  paño, el diámetro del alambre, la separación de la cuadrícula y los metros cuadrados totales.
</p>
<p>
  Un ejemplo: un patio de 6 × 4 m son 24 m². Pedí la malla por esos 24 m², aclarando que es
  para patio, y el proveedor suma el solape entre paños. El hormigón que va encima lo resolvés
  con la <a href="/calculadoras/bolsas-de-cemento-por-m2/">calculadora de bolsas de cemento por
  m²</a>: para esos 24 m² de contrapiso con 8 cm de espesor (el tuyo lo define tu obra) da
  <strong>11 bolsas de cemento</strong>, 1,06 m³ de arena y 1,8 m³ de ripio, con un 10 % de
  desperdicio. Así cotizás malla y mezcla en la misma consulta.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que el diámetro del alambre y la separación de la cuadrícula correspondan al uso que
  le vas a dar: una malla pensada para vereda no tiene por qué rendir igual en un contrapiso
  con más carga. Contá bien la superficie real, sumando el solape entre paños, porque calcular
  al justo deja huecos sin armar en las uniones. Fijate que los paños lleguen planos, sin
  dobleces que después cuesten acomodar en obra, y que los nudos electrosoldados estén firmes
  en toda la cuadrícula. Si tu obra usa también varilla suelta para reforzar bordes o
  encuentros, coordiná esa compra en el mismo pedido para no duplicar flete.
</p>

