<h2>Para qué se usa</h2>
<p>
  El <strong>sellador para pared</strong> es la mano que va antes de la pintura, y en obra se
  lo pide con varios nombres: <strong>fijador</strong>, <strong>fijador sellador</strong>,
  <strong>fondo para pared</strong> o <strong>imprimación</strong>. Hace tres cosas: fija el
  polvo y los granos sueltos del revoque, empareja la absorción de la superficie para que la
  pintura no se chupe más en unas partes que en otras, y mejora la adherencia de la
  <a href="/materiales/pintura-para-pared/">pintura para pared</a> que va encima. Se usa sobre
  revoque fino nuevo, sobre enlucido de <a href="/materiales/yeso-en-polvo/">yeso</a>, sobre
  paredes viejas que se desgranan al pasar la mano y sobre pintura a la cal que se quiere
  cubrir con látex. El <strong>fondo blanco</strong> es una variante que además cubre: deja la
  pared de un tono parejo y ayuda cuando se pasa de un color oscuro a uno claro. No hay que
  confundirlo con el sellador de juntas en cartucho, que es otro producto y está en
  <a href="/materiales/selladores-y-siliconas/">selladores y siliconas</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>lata o balde</strong>, en los litrajes de cada producto. Algunos
  fijadores vienen concentrados y se diluyen con agua en obra, así que el rendimiento real
  depende de la dilución que indica el envase y de cuánto absorba la pared. Para pedir bien,
  pasá los m² a tratar, si es revoque nuevo, yeso o repintado, y en qué estado está la
  superficie: una pared que se desgrana pide un fijador más cargado que una que sólo está
  porosa. Aclará también si querés un fijador transparente o un fondo blanco. Conviene pedirlo
  en la misma cotización que el látex, junto con los rodillos, la lija y el enduido si hay que
  emparejar fisuras o imperfecciones. El precio depende del tipo de producto, de si viene
  concentrado, del litraje, de los m² y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Hacé la prueba de la mano: si al pasarla por la pared queda polvo o arena, necesitás
  fijador; si queda limpia y la pintura anterior está firme, muchas veces alcanza con lijar y
  limpiar. Sobre revoque nuevo, esperá a que esté bien seco antes de sellar, porque la humedad
  que queda adentro termina levantando la pintura. Si la pared tiene manchas de humedad o
  salitre, el sellador no las resuelve: primero hay que atacar el origen y tratar la
  superficie con <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>. Respetá
  la dilución que indica el envase: un fijador demasiado cargado forma una película que
  después no deja agarrar al látex, y uno demasiado aguado no fija nada.
</p>
