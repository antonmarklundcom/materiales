<h2>Para qué se usa</h2>
<p>
  La <strong>ducha eléctrica</strong> calienta el agua en el propio equipo al momento de
  usarla. Es una solución para el baño cuando el agua caliente no llega desde un calentador
  separado de la vivienda. La ducha con calentador eléctrico reúne la salida de agua y
  el calentamiento, por lo que se elige como un artefacto completo. No cumple la misma
  función que una mezcladora: esa grifería combina agua que ya llega fría y caliente,
  mientras que acá el calor se genera con electricidad. Para reemplazar una ducha eléctrica
  para baño o instalarla en una obra nueva, conviene revisar primero las condiciones del
  lugar. Que exista una toma de agua y haya cables cerca no confirma que la instalación
  sea adecuada para el equipo que querés comprar.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Indicá cuántos equipos necesitás, tu ciudad o barrio
  y si es reemplazo o instalación nueva. Pasá las medidas de la conexión de agua, la
  ubicación disponible y los datos de la instalación que confirme quien va a colocarla.
  Pedí la ficha del modelo para que el electricista revise su compatibilidad antes de
  cerrar la compra. El presupuesto debe detallar el equipo, su soporte y los accesorios
  incluidos; las conexiones que falten, el flete y la colocación se cotizan aparte.
  También separá cualquier adecuación de la instalación eléctrica o de agua. El precio
  cambia con el modelo, el sistema de regulación y los accesorios del conjunto. Para
  comparar ofertas, usá la misma descripción y distinguí el costo del producto del trabajo
  necesario para dejarlo instalado.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Pedí a un electricista que compruebe que la instalación de la casa, el cableado y la
  llave térmica sean adecuados para el equipo, siguiendo las indicaciones del fabricante.
  Esa revisión se hace antes de elegir y conectar la ducha; no alcanza con conservar la
  conexión de un artefacto anterior. Confirmá también las condiciones de alimentación de
  agua que exige el modelo y el espacio necesario para fijarlo. Revisá cómo se regula y
  qué mantenimiento indica su manual, sin asumir que todos los equipos se usan igual.
  Preguntá por repuestos compatibles y conservá la identificación del modelo para pedirlos.
  Al recibirlo, comprobá que estén el manual y los accesorios detallados en la oferta.
  Coordiná la colocación con personal calificado y dejá definidas las adecuaciones antes
  de poner el equipo en uso.
</p>

