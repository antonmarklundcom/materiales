<h2>Para qué se usa</h2>
<p>
  Las canaletas para techo recolectan el agua de lluvia que baja por el faldón y la conducen
  hacia la bajada, en vez de dejar que caiga directo sobre la vereda, el patio o la pared.
  Cumplen la función de <strong>desagüe pluvial</strong>: la canaleta corre a lo largo del
  alero y entrega el agua a un <strong>caño de bajada</strong>, que la lleva hasta el desagüe o
  el patio; ese desagüe pluvial se arma con <a href="/materiales/cano-de-pvc/">caño de
  desagüe</a> de PVC. Se usan tanto en <strong>canaletas de PVC</strong> —livianas, fáciles de cortar y
  las más difundidas en obra nueva —lo que acá se conoce como canaleta tigre— como en
  <strong>canaleta de chapa galvanizada</strong>, más resistente al sol directo y usada sobre
  todo en canaleta embutida o en techos con mucha exposición. También forman parte del sistema
  de desagüe el <strong>pecho paloma</strong>, la pieza de salida hacia la bajada, y la
  <strong>limahoya</strong>, el canal que se forma donde se cruzan dos faldones de techo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotizan por <strong>metro lineal</strong>. Para pedir bien necesitás el
  <strong>perímetro de alero</strong> a cubrir, la cantidad de bajadas que vas a necesitar
  según los puntos de desagüe disponibles, y si preferís PVC o chapa galvanizada. Las piezas
  especiales —uniones, ángulos, embudos, pecho paloma, tapas de extremo— se cotizan aparte del
  metro de canaleta y conviene pedirlas juntas para que combinen en color y calce. El precio
  final depende del material elegido, de la cantidad de metros y bajadas, y del flete hasta tu
  zona.
</p>
<p>
  Un ejemplo: un techo a 2 aguas con <strong>10 m</strong> de alero en cada faldón, con
  canaleta en los dos lados, pide <strong>20 metros lineales</strong> de canaleta. A eso se suma
  un pecho paloma por cada bajada que definas, y las uniones, ángulos y tapas de extremo que
  pida el recorrido: pasale al proveedor los metros y un croquis con la ubicación de las
  bajadas, así te arma el pedido con las piezas del mismo sistema.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en el <strong>espesor y rigidez</strong> del perfil: una canaleta de PVC muy fina se
  puede deformar con el peso del agua acumulada después de una lluvia fuerte. Revisá que la
  pendiente hacia la bajada quede bien calculada antes de fijar los soportes, porque una
  canaleta sin caída suficiente acumula agua estancada y hojas. Si optás por chapa galvanizada,
  comprobá que el galvanizado esté parejo, sin puntos de óxido ya visibles de fábrica. Confirmá
  también que las uniones y bocas de salida sean del mismo sistema que la canaleta elegida,
  porque mezclar marcas o perfiles distintos suele dejar filtraciones en los empalmes.
</p>

