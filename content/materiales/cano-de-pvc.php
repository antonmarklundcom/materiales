<h2>Para qué se usa</h2>
<p>
  El caño de PVC es el que arma el desagüe de la casa: junta lo que baja de cada artefacto y lo
  lleva por gravedad hasta la cloaca o hasta el pluvial. Se lo conoce indistintamente como
  <strong>tubos de PVC</strong>, <strong>caño de desagüe</strong> o <strong>caño cloacal</strong>,
  y en muchas obras se pide directamente como lo que acá se conoce o pide como
  <strong>caño amanco</strong>, otra marca que quedó instalada como nombre genérico del rubro.
  No es el mismo caño que lleva el agua con presión hasta la canilla —ese es el
  <a href="/materiales/cano-de-agua/">caño de agua</a>, con otra pared y otro sistema de
  unión—, así que conviene no confundirlos al armar el pedido.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende <strong>por barra y por diámetro</strong>, con largos estándar de fábrica. El
  <strong>caño de 110</strong> es el que va en la cloaca principal y en las bajadas de mayor
  caudal, mientras que el <strong>caño de 100</strong> y los diámetros menores se usan en
  artefactos y ventilaciones. Para pedir bien conviene contar qué instalación estás haciendo
  —cloacal o pluvial— y cuántos artefactos descargan en cada tramo, porque de ahí sale el
  diámetro que corresponde a cada parte. Junto con los caños hay que pedir los accesorios:
  codos, ramales, cuplas, reducciones y la <strong>junta elástica</strong> o el pegamento para
  PVC, todo en la misma consulta para que el flete no se fraccione en varios viajes.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que el diámetro pedido corresponda al uso: un caño de 110 en un tramo que no lo
  necesita encarece de más, y uno de menor diámetro en la cloaca principal puede quedar
  insuficiente. Fijate que las uniones sean con junta elástica o que el pegamento sea el
  indicado para PVC de presión cero (el de desagüe, no el de agua), porque no todos los
  pegamentos sirven para el mismo tipo de caño. Si la instalación es pluvial, confirmá con quien
  instala la pendiente mínima que necesita cada tramo para que el agua corra bien sin
  estancarse.
</p>
