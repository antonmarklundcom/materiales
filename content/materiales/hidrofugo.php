<h2>Para qué se usa</h2>
<p>
  El <strong>hidrófugo</strong> —el aditivo hidrófugo que va mezclado con el mortero o el
  hormigón— es el impermeabilizante que trabaja desde adentro: se usa sobre todo en la
  <strong>capa aisladora</strong> que separa el cimiento de la mampostería, el punto exacto
  donde arranca la humedad ascendente que después se ve como salitre en la pared. También se
  suma a revoques de zonas húmedas, baños, muros de contención y cualquier hormigón que va a
  quedar en contacto directo con tierra o agua. No reemplaza a la membrana ni a la pintura
  antihumedad: la <a href="/materiales/membrana-asfaltica/">membrana</a> resuelve la
  superficie expuesta de una losa o azotea, y el hidrófugo resuelve lo que pasa adentro de la
  mezcla antes de que el problema aparezca en la superficie.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>balde o bidón</strong>, y la proporción que lleva la mezcla la indica el
  fabricante del producto y la confirma el calculista o el albañil a cargo de la obra: no es
  algo que se estime a ojo. Para pedir bien, pasá el volumen de mezcla que vas a preparar —o
  los metros cuadrados de capa aisladora, si es lo que estás por hacer— y con eso te dicen
  cuántos baldes salen. El precio final depende del producto, de la presentación, de la
  proporción que pida esa mezcla puntual y del volumen total de la obra, por lo que conviene
  cerrar primero cuánto vas a impermeabilizar antes de pedir cotización.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Respetá la proporción indicada por el fabricante: de más no impermeabiliza mejor, y de menos
  no cumple su función, así que ni conviene improvisar la dosis ni exagerarla. Confirmá con
  quien dirige la obra si el hidrófugo va en la capa aisladora, en el revoque, en el hormigón,
  o en más de un punto, porque cada uso puede pedir un producto o una dosis distinta. Tené en
  cuenta que es complementario a otras soluciones, no un reemplazo: si además hay una losa o
  azotea expuesta, ese punto se resuelve con
  <a href="/materiales/membrana-asfaltica/">membrana asfáltica</a>, y si ya hay humedad
  visible en la pared, con <a href="/materiales/pintura-antihumedad/">pintura
  antihumedad</a> mientras se corrige el origen.
</p>

