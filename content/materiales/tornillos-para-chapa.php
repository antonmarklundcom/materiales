<h2>Para qué se usa</h2>
<p>
  Los tornillos para chapa son los que fijan la cubierta a la estructura del techo, y de ellos
  depende que la chapa no se levante con el viento ni filtre por los agujeros. Se pide de
  distintas formas: <strong>autoperforante para chapa</strong> (el de punta mecha, que
  perfora y rosca en un solo paso), <strong>autorroscante para chapa</strong> (el de punta
  aguja) y <strong>tirafondo para chapa</strong> cuando la estructura es de madera. Sirven para
  la <a href="/materiales/chapa-trapezoidal/">chapa trapezoidal</a>, para la
  <a href="/materiales/chapa-de-zinc/">chapa de zinc</a> o galvanizada y para el panel sándwich
  de la <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a>. También hay
  tornillos para planchas de <a href="/materiales/policarbonato/">policarbonato</a>, que llevan
  una arandela pensada para ese material. Elegir bien el tipo es lo que evita que la chapa
  quede floja o que el tornillo se pase de rosca.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se venden por <strong>caja, bolsa o kilo</strong>, según el proveedor y el tipo de tornillo.
  Para cotizar bien necesitás decir sobre qué material van (chapa fina, perfil C o madera), qué
  chapa fijás, el largo que necesitás y cuántos metros cuadrados de techo cubrís, porque de eso
  sale la cantidad. Los tornillos de uso más común se piden en medidas como
  <strong>2 pulgadas</strong> o <strong>2 1/2</strong>, pero el largo correcto depende de la
  altura de la onda y de lo que haya debajo, así que confirmalo con el proveedor. Lo más
  práctico es <strong>pedirlos junto con la chapa</strong>: así el proveedor ve el perfil y la
  estructura y te manda los tornillos que corresponden, además de ahorrarte un viaje y repartir
  el flete. El precio cambia con el tipo de tornillo, el largo, el tratamiento contra la
  oxidación, la cantidad y el flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Hay varios <strong>tipos de tornillos para chapa</strong> y no son intercambiables. Esta tabla
  te ayuda a no pedir uno equivocado:
</p>
<table>
  <thead>
    <tr><th>Tipo</th><th>Cuándo se usa</th><th>Qué pedirle al proveedor</th></tr>
  </thead>
  <tbody>
    <tr>
      <td>Autoperforante punta mecha</td>
      <td>Cuando la estructura es metálica, como un perfil C o una correa, y querés fijar sin hacer un agujero previo.</td>
      <td>Largo, cabeza hexagonal, arandela de sellado y el material de la estructura donde va.</td>
    </tr>
    <tr>
      <td>Autorroscante punta aguja</td>
      <td>Cuando se fija sobre chapa fina o una estructura liviana, donde conviene confirmar con el proveedor si hace falta perforar antes.</td>
      <td>Largo, cabeza hexagonal, arandela de sellado y si la estructura es chapa fina o perfil C.</td>
    </tr>
    <tr>
      <td>Tirafondo para madera</td>
      <td>Cuando la chapa se apoya sobre tirantes o listones de madera, como en un tinglado con estructura de madera.</td>
      <td>Largo, cabeza hexagonal, arandela de sellado y el tipo de madera de la estructura.</td>
    </tr>
  </tbody>
</table>
<p>
  Fijate siempre que traigan <strong>arandela de sellado</strong>: es la que tapa el agujero y
  evita las filtraciones. Pedí que sean galvanizados o con tratamiento anticorrosivo, porque un
  tornillo que se oxida mancha la chapa y termina aflojándose. Si tu techo tiene una estructura
  mixta, por ejemplo <a href="/materiales/perfiles-metalicos/">perfiles metálicos</a> en una
  parte y madera en otra, pedí los dos tipos y aclaralo en el pedido. Para calcular cuántos
  metros de chapa necesitás, usá la
  <a href="/calculadoras/chapas-para-techo/">calculadora de chapas para techo</a>.
</p>

