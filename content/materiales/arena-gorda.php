<h2>Para qué se usa</h2>
<p>
  La arena gorda —muchos la piden como <strong>arena gruesa</strong> o
  <strong>arena de construcción</strong>— es la que entra en tareas donde importa más la
  resistencia que la terminación fina: contrapisos de espesor normal, mezclas de hormigón y
  bases donde el grano más grande ayuda a que la mezcla trabe bien y no se agriete al secar. Se
  usa mucho también como <strong>arena para contrapiso</strong> en pisos que después van a
  llevar un piso cerámico o porcelanato encima, porque da más cuerpo a la base que una arena
  fina. Es normal que llegue con algo de tierra o material más grueso mezclado —por eso a veces
  se la llama <strong>arena sucia</strong> en la obra—, cosa que no afecta su uso en estructura
  pero sí la descarta para un revoque visto. Si lo que buscás es una terminación prolija y sin
  impurezas, ahí corresponde la <a href="/materiales/arena-lavada/">arena lavada</a>, no ésta.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cúbico</strong> o por <strong>camionada</strong>. Para cotizar
  bien, el proveedor va a necesitar la <strong>cantidad</strong> que necesitás y la
  <strong>zona</strong> de entrega, porque el flete en volumen de áridos pesa bastante en el
  costo final. El precio depende del volumen pedido, de la distancia hasta la obra y de la
  disponibilidad del material en el momento, así que conviene pedir la cotización con el dato
  exacto de m³ en vez de aproximar de más o de menos. Si en la misma obra vas a usar
  <a href="/materiales/ripio/">ripio</a> o <a href="/materiales/tierra-gorda/">tierra</a> para
  otra etapa, pedilo en la misma consulta para ahorrar en flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá el tamaño del grano: la arena gorda tiene que sentirse claramente más gruesa al tacto
  que una arena fina, porque de eso depende que dé la resistencia esperada en el contrapiso o
  el hormigón. Un error común es aceptar una carga con demasiada tierra mezclada pensando que
  "total va abajo del piso": el exceso de material fino baja la resistencia de la mezcla y
  puede generar fisuras. Fijate también que no venga con piedras grandes sueltas que compliquen
  el mezclado a pala o mezcladora. Si la vas a usar en un hormigón que va a quedar cargado
  (una losa, una columna), pedí que te confirmen que es apta para ese uso y no sólo para relleno
  o contrapiso liviano.
</p>

