<h2>Para qué se usa</h2>
<p>
  Los clavos de obra cubren dos frentes bien distintos: el <strong>clavo para encofrado</strong>,
  que arma y desarma los moldes de madera donde se vuelca el hormigón, y el
  <strong>clavo de punta París</strong> o <strong>clavo de acero</strong> de uso general, para
  carpintería, fijación de listones y trabajos de terminación. El de encofrado suele elegirse
  más corto o con cabeza distinta porque después hay que sacarlo sin arruinar la tabla, mientras
  que el de uso general busca sujeción definitiva. Se usan junto con las
  <a href="/materiales/tabla-de-encofrado/">tablas de encofrado</a> y los
  <a href="/materiales/tirantes/">tirantes</a> que arman la estructura de madera, y con el
  <a href="/materiales/alambre-negro/">alambre negro</a> en los puntos donde el clavo solo no
  alcanza para fijar bien la armadura al encofrado.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se venden por <strong>kilo</strong> o por <strong>caja</strong>, según cuánto dure la obra: el
  kilo suelto rinde para reposición puntual, la caja conviene cuando el consumo es continuo. Para
  pedir bien hay que indicar la <strong>medida del clavo</strong> y los <strong>kilos</strong>
  que necesitás; si es para encofrado, decir el espesor de la tabla ayuda a que te sugieran la
  medida correcta, porque el clavo tiene que penetrar bien la segunda pieza sin atravesarla de
  más. El flete se cotiza aparte y normalmente es menor que el de materiales más pesados como el
  hierro, aunque igual conviene sumarlo si el pedido va combinado con otros materiales de obra.
  El precio final depende de la medida, la cantidad de kilos, si es por kilo suelto o por caja, y
  la zona de entrega.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí la medida según el espesor de la madera que vas a clavar: un clavo muy largo para una
  tabla fina la raja o sale del otro lado, y uno muy corto no sujeta. Fijate que el clavo tenga
  buen temple —que no se doble ni se parta al primer martillazo sobre madera dura— porque un
  lote de mala calidad se nota recién en obra, cuando ya se perdió tiempo. Si es para encofrado,
  conviene que la cabeza permita sacarlo sin destrozar la tabla, porque buena parte del
  encofrado se reutiliza. Calculá la cantidad con algo de margen: en obra siempre se pierden
  algunos clavos doblados o caídos entre el material.
</p>

