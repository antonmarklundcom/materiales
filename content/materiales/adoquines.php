<h2>Para qué se usa</h2>
<p>
  Los adoquines —también llamados <strong>adoquín de hormigón</strong>, o
  <strong>adopasto</strong> cuando llevan aberturas para pasto entre pieza y pieza— se usan para
  pisos exteriores que van a recibir tránsito de personas o vehículos sin necesitar una losa de
  hormigón continua. Se usan en veredas, patios, entradas de vehículos, estacionamientos y
  playones, formando lo que en obra se conoce como <strong>adoquinado</strong>. Una de sus
  ventajas frente al contrapiso tradicional es que el <strong>adoquín ecológico</strong> permite
  que el agua de lluvia se filtre entre las juntas en vez de escurrir toda hacia la calle, algo
  valorado en patios y accesos donde se busca reducir el agua acumulada en superficie. No se
  confunde con el <a href="/materiales/bloque-de-hormigon/">bloque de hormigón</a>, que es para
  pared y no para piso.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cuadrado</strong> de superficie a cubrir, así que el dato principal
  que necesita el proveedor es el área exacta del patio, la vereda o el playón, contando también
  los cortes en los bordes irregulares. Conviene aclarar el tipo de adoquinado que buscás —de
  hormigón tradicional o ecológico con espacio para pasto— porque cambia tanto el rendimiento por
  metro cuadrado como la base que hay que preparar debajo. La arena y la piedra triturada para la
  base compactada se cotizan aparte del adoquín, y conviene pedirlas en la misma consulta para
  no duplicar el flete. El precio final depende del tipo de adoquín, de la cantidad de metros
  cuadrados y de la distancia de entrega.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que las piezas tengan un espesor uniforme, porque un adoquín más fino que el resto queda
  hundido en el piso terminado y genera un desnivel incómodo. Revisá que el color sea parejo
  entre las piezas del mismo pedido, sobre todo en superficies grandes donde cualquier diferencia
  de tono se nota a la distancia. Un error común es no preparar bien la base compactada antes de
  colocar el adoquinado: sin una base firme de arena y piedra triturada, las piezas se mueven y
  el piso pierde nivel con el tiempo. Pedí también los adoquines de borde o remate si tu diseño
  los necesita, porque suelen tener una forma distinta a la pieza central.
</p>

