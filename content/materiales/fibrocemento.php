<h2>Para qué se usa</h2>
<p>
  El fibrocemento —lo que acá se conoce como <strong>eternit</strong>— es una placa rígida a
  base de cemento y fibras, liviana comparada con la teja y muy resistente a la intemperie. Se
  usa como <strong>chapa de fibrocemento</strong> en techos de vivienda, galpones y
  ampliaciones, y como <strong>placa cementicia</strong> plana en cerramientos, medianeras y
  revestimientos donde se busca un material incombustible y que no se oxida como la chapa
  metálica. La versión ondulada, la <strong>placa ondulada de fibrocemento</strong>, es la más
  común para techo; la placa plana se usa más en pared y en tabiquería. Frente a la
  <a href="/materiales/chapa-de-zinc/">chapa de zinc</a>, el fibrocemento pesa más pero no se
  oxida ni resuena tanto con la lluvia; frente a la <a href="/materiales/teja-espanola/">teja</a>,
  es más liviano y más rápido de montar.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>chapa o por placa</strong>, según el formato que necesites. Para pedir
  bien necesitás el <strong>largo de faldón</strong> o la medida de placa, la
  <strong>cantidad de m²</strong> a cubrir y el <strong>espesor</strong>, porque el
  fibrocemento viene en distintos espesores según si va a techo o a pared. Los accesorios
  —caballetes, tornillería con arandela de sellado, ganchos de fijación— se cotizan aparte y
  conviene sumarlos al mismo pedido. El precio final depende del espesor, de la cantidad de
  placas y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que las placas no tengan fisuras finas ni bordes despostillados, algo común si vinieron
  mal estibadas, porque una fisura chica se abre más con el paso del tiempo y el sol. Revisá
  que el espesor sea el adecuado para la luz entre correas de tu estructura: un espesor
  insuficiente puede flexar o incluso quebrarse con el paso de una persona durante el montaje.
  Usá siempre tornillos con arandela de goma para sellar la perforación, porque el fibrocemento
  es más frágil que la chapa metálica ante un tornillo mal puesto. Si vas a pintarlo, esperá el
  tiempo de estacionamiento que indique el fabricante antes de aplicar la primera mano.
</p>

