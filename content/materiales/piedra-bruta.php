<h2>Para qué se usa</h2>
<p>
  La piedra bruta —pedida también como <strong>piedra de cimiento</strong>,
  <strong>piedra en bruto</strong> o <strong>piedra de basalto</strong> sin procesar— es la que
  se usa directamente en cimientos, sobre todo en construcciones que arrancan con
  <strong>piedra para muro de contención</strong> o zapata corrida de piedra. Al no pasar por
  el proceso de trituración, mantiene su forma irregular tal como sale de la cantera, lo que la
  hace ideal para asentarse con mortero en la base de una obra sin necesitar el traba fino que
  sí requiere el hormigón armado. También se usa en <strong>muros de contención</strong> de
  taludes y desniveles de terreno, donde el peso y la forma irregular de cada piedra ayudan a
  estabilizar el conjunto. Si la obra necesita en cambio hormigón estructural, ahí corresponde
  la <a href="/materiales/piedra-triturada/">piedra triturada</a>, no la piedra bruta.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cúbico</strong> o por <strong>camionada</strong>. Para cotizar,
  el proveedor necesita la <strong>cantidad</strong> en m³ (que suele calcularse según el
  largo y la profundidad de la zanja de cimiento) y la <strong>zona</strong> de entrega. El
  precio depende del volumen pedido, de la distancia de traslado y de la disponibilidad en la
  cantera, así que conviene tener el cálculo de la zanja o el muro antes de pedir la
  cotización. Si en la misma obra vas a necesitar <a href="/materiales/cemento/">cemento</a> o
  <a href="/materiales/arena-gorda/">arena</a> para el mortero de asiento, pedilo todo junto
  para ahorrar en flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que las piedras tengan un tamaño relativamente parejo, porque piedras demasiado
  desparejas complican el armado prolijo de la hilada de cimiento. Revisá también que no
  vengan con exceso de tierra pegada, ya que eso dificulta el agarre del mortero. Un error
  común es pedir piedra triturada pensando que sirve igual para cimiento: para esa tarea
  puntual, la piedra bruta suele alcanzar y resulta más simple de conseguir en el volumen
  necesario. Si es para muro de contención, pedí piedras de mayor tamaño en la base y más
  chicas hacia arriba, porque esa disposición ayuda a la estabilidad del muro.
</p>

