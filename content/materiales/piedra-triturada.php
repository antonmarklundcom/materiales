<h2>Para qué se usa</h2>
<p>
  La piedra triturada es la que se pide cuando la obra necesita resistencia estructural real:
  hormigón para losas y columnas, bases de pavimento de tránsito pesado y bases de calles. Se
  obtiene de la trituración de <strong>basalto</strong> (por eso también se la conoce como
  <strong>basalto triturado</strong> o <strong>triturada de basalto</strong>), y a diferencia
  del ripio o canto rodado, sus bordes filosos le dan un traba mecánico mejor dentro del
  hormigón. En Paraguay se pide por número de granulometría —<strong>piedra 4ta</strong>,
  <strong>piedra 5ta</strong> o <strong>piedra 6ta</strong> (esta última también llamada
  <strong>sexta</strong> o <strong>piedra partida</strong> fina)— según el tamaño de grano que
  requiere cada uso: cuanto más chico el número de la escala, más grueso suele ser el grano
  usado. Si en cambio la tarea es una base compactada sin gran exigencia estructural, el
  <a href="/materiales/ripio/">ripio</a> alcanza y sale más simple de manejar.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cúbico</strong> o por <strong>camionada</strong>. Al pedirla,
  además de la <strong>cantidad</strong> necesaria, hay que especificar la
  <strong>granulometría</strong> (4ta, 5ta o 6ta) según el uso que le vas a dar, y la
  <strong>zona</strong> de entrega para calcular el flete. El precio depende del volumen
  pedido, de la granulometría elegida y de la distancia hasta tu obra, así que conviene tener
  claro antes de pedir para qué la vas a usar. Si el hormigón lo vas a preparar en obra,
  conviene cotizar junto <a href="/materiales/cemento/">cemento</a> y arena en la misma
  consulta para optimizar el flete; si preferís que te llegue la mezcla lista, mirá
  <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a>.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá siempre la granulometría antes de pedir, porque usar la piedra equivocada afecta
  directamente la resistencia de la mezcla:
</p>
<table>
  <thead>
    <tr><th>Granulometría</th><th>Uso típico</th></tr>
  </thead>
  <tbody>
    <tr><td>Piedra 4ta</td><td>Hormigón estructural de losas y columnas, piezas de mayor espesor</td></tr>
    <tr><td>Piedra 5ta</td><td>Hormigón general, contrapisos armados, bases de pavimento</td></tr>
    <tr><td>Piedra 6ta (sexta)</td><td>Hormigones de menor espesor, terminaciones y mezclas más finas</td></tr>
  </tbody>
</table>
<p>
  Más allá del número, fijate que el material sea realmente triturado y no una mezcla con
  canto rodado colado —los bordes filosos son lo que le da el traba dentro del hormigón—. Un
  error común es pedir piedra triturada para cimiento cuando en realidad conviene la
  <a href="/materiales/piedra-bruta/">piedra bruta</a>, que es más económica para ese uso
  puntual. Revisá también que no traiga exceso de polvo o finos, porque eso resta resistencia
  a la mezcla final.
</p>

