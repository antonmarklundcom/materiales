<h2>Para qué se usa</h2>
<p>
  El machimbre es la tabla angosta con macho y hembra en los cantos que encastra pieza con
  pieza para formar una superficie continua, sin dejar ver los clavos. Se usa sobre todo en
  <strong>cielorrasos</strong> —lo que muchos piden puntualmente como <strong>machimbre para
  techo</strong>— y en revestimientos de techos a la vista, donde el <strong>machimbre de
  pino</strong> es la opción más habitual por precio y disponibilidad. También se lo conoce
  como <strong>entablonado</strong> cuando se habla del conjunto ya instalado. Se distingue del
  machimbre de PVC, que es otro material y otra categoría dentro de cielorrasos: acá se trata
  puntualmente de la tabla de madera.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>, según el espesor y el ancho de tabla que
  elijas. Para pedir bien contá los <strong>metros cuadrados a cubrir</strong> del cielorraso o
  el techo, y si es posible aclará el ambiente (interior seco, galería, techo con exposición
  directa), porque de eso depende si conviene sumar un tratamiento o una manta de aislación
  por debajo. El precio varía con el tipo de madera, el espesor y el ancho de la tablilla, los
  metros cuadrados totales y el flete hasta la obra.
</p>
<p>
  Si el machimbre va a la vista bajo el techo, siguiendo la pendiente, los m² son los del
  faldón medido sobre la pendiente, no los de la planta. Un ejemplo: un techo a 2 aguas con
  faldones de <strong>5 m</strong> de cumbrera a alero y <strong>9 m</strong> de largo son
  <strong>90 m²</strong>, que es la superficie de techo que te da la
  <a href="/calculadoras/chapas-para-techo/">calculadora de chapas para techo</a> con esas
  medidas. Esa cuenta incluye el vuelo del alero: si el alero no lleva machimbre, descontalo
  antes de pedir.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que el ancho de tabla sea uniforme entre piezas, porque las diferencias se notan
  apenas se arma el conjunto, sobre todo en cielorrasos vistos desde abajo con luz rasante.
  Preguntá si conviene sumar una manta o film aislante bajo la cubierta antes de instalar el
  machimbre, en particular si el techo es de chapa: eso mejora el confort y no se puede agregar
  después sin desarmar. Si el machimbre va a quedar expuesto al exterior o a un ambiente
  húmedo, consultá qué tratamiento o <a href="/materiales/barniz/">barniz</a> recomiendan, porque la madera sin proteger se
  reseca y se abre con el sol paraguayo. Y calculá la cantidad de clavaderas —listones— que vas
  a necesitar para fijarlo, porque van aparte del machimbre mismo.
</p>

