<h2>Para qué se usa</h2>
<p>
  El caño de agua es el que lleva agua fría y caliente con presión desde el tanque hasta cada
  canilla, ducha y artefacto de la casa. Es una <strong>cañería de agua</strong> bien distinta
  del caño de desagüe: trabaja empujada por presión, no por gravedad, así que tiene otra pared y
  otro sistema de unión. Se arma de dos maneras: por <strong>termofusión</strong>, que suelda
  caño y accesorio en una sola pieza sin junta que pueda perder con el tiempo, o por
  <strong>caño roscado</strong>, que se arma y desarma con llave y es más habitual en
  reparaciones o ampliaciones sobre una instalación ya existente. Ambos sistemas alimentan tanto
  <strong>agua fría y caliente</strong>, aunque conviene confirmar con quien instala si el caño
  elegido soporta bien la temperatura del agua caliente en el tramo que corresponde.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende <strong>por barra y por diámetro</strong>, igual que el caño de desagüe, pero acá el
  diámetro se define distinto porque depende de la presión y de cuántos artefactos alimenta el
  tramo. Los diámetros más pedidos en vivienda son ½ y ¾ pulgada, pero conviene pasar el plano
  de la instalación o contar qué baños y qué cocina alimenta cada tramo para que te confirmen la
  medida exacta. Junto con el caño hay que pedir los accesorios de unión —codos, tees, uniones—
  y la <strong>llave de paso</strong> de cada sector, porque sin ella no se puede cortar el agua
  de una parte de la casa sin cortarla de toda la instalación. Pedilo todo en la misma consulta
  para no fraccionar el flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Definí primero si vas a instalar por termofusión o por caño roscado, porque cada sistema pide
  su propio caño y sus propios accesorios, y no se mezclan entre sí en el mismo tramo. Si es
  termofusión, confirmá que el proveedor te pase también los accesorios del mismo sistema, ya
  que una unión mal combinada puede perder. Revisá que el diámetro corresponda a la cantidad de
  artefactos que alimenta cada tramo, sobre todo en el tramo de agua caliente, y no te olvides
  de pedir las llaves de paso de cada sector para poder cortar el agua sin afectar toda la casa.
</p>

