<h2>Para qué se usa</h2>
<p>
  Los perfiles para durlock son el esqueleto sobre el que se atornilla la placa de yeso: sin
  ellos no hay tabique ni cielorraso en seco que se sostenga. El sistema combina dos piezas
  principales, el <strong>perfil montante</strong>, que va vertical y forma la estructura del
  tabique, y la <strong>solera</strong>, que se fija arriba y abajo (o en el perímetro del
  cielorraso) y recibe a los montantes. A esto se suman las <strong>soleras para durlock</strong>
  de refuerzo en vanos de puertas y el <strong>ángulo de ajuste</strong>, que remata el
  encuentro entre el cielorraso y la pared. La separación entre montantes —habitualmente cada
  40 o 60 cm— es lo que define cuán firme queda el tabique terminado: perfiles muy separados
  dejan una pared que suena hueca y flexa al apoyarse. No son perfiles estructurales: si la
  obra necesita perfilería para soportar cargas, esa es otra familia de producto, disponible en
  <a href="/materiales/perfiles-metalicos/">perfiles metálicos</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se venden por <strong>barra</strong>, en largos estándar. Para pedir bien pasá los
  <strong>metros cuadrados</strong> de tabique o cielorraso y la <strong>altura</strong> (o el
  perímetro, si es cielorraso), porque con eso el proveedor calcula cuántas barras de montante
  y de solera salen y en qué proporción. Si el tabique lleva vanos de puertas, conviene avisarlo
  aparte porque ahí van soleras de refuerzo adicionales. El precio final depende de la cantidad
  de barras, del ancho de perfil elegido (hay más de un ancho de montante según la altura y el
  uso del tabique) y del flete hasta la obra.
</p>
<p>
  Un ejemplo: un tabique de <strong>3 m de largo por 2,70 m de alto</strong>, con barras de
  2,60 m (largo de ejemplo: confirmá el de tu proveedor). Con montantes cada 40 cm, la
  <a href="/calculadoras/durlock-por-m2/">calculadora de placas de yeso y perfiles</a> da
  <strong>9 montantes</strong>; como el alto pasa el largo de la barra, cada uno lleva dos
  barras empalmadas: <strong>18 barras de montante</strong>, más <strong>4 barras de
  solera</strong> para arriba y abajo. Cada 60 cm quedan 6 montantes y 12 barras. Si tu
  proveedor tiene una barra que alcance el alto, cada montante va de una pieza y son 9 barras.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el perfil sea <strong>galvanizado</strong> y del espesor pensado para construcción
  en seco: un perfil de hierro común, sin ese tratamiento ni ese espesor, no es el mismo
  producto aunque parezca similar a simple vista, y con el tiempo puede oxidarse dentro del
  tabique. Revisá que el ancho de montante coincida con el que calculaste para la altura del
  tabique, porque un perfil más angosto que lo necesario flexa más de la cuenta. Contá que
  vengan derechos, sin torceduras ni golpes en los bordes, porque un montante torcido arruina la
  planitud de toda la placa que se atornilla encima. Y confirmá que la cantidad de solera
  incluya lo necesario para los vanos de puertas, no solo el perímetro corrido.
</p>

