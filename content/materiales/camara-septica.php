<h2>Para qué se usa</h2>
<p>
  La cámara séptica es parte del sistema que recibe el agua del baño cuando la casa no está
  conectada a una red cloacal. Funciona en dos pasos: primero el agua del inodoro y de los
  desagües llega a la <strong>cámara séptica</strong>, donde los sólidos se separan y se
  descomponen; después el agua ya tratada pasa al <strong>pozo ciego</strong> (también llamado
  pozo de absorción), que la deja filtrarse en la tierra. Por eso se habla de la
  <strong>cámara séptica y pozo ciego</strong> como un conjunto. Quien pregunta por la
  <strong>cámara séptica para baño</strong> o la <strong>cámara séptica de baño</strong> busca
  justamente esa solución para el desagüe de un baño o de toda la casa. El
  <a href="/materiales/inodoro/">inodoro</a> y los desagües llegan a la cámara a través de
  <a href="/materiales/cano-de-pvc/">caños de PVC</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  La cámara séptica se vende por <strong>unidad</strong> cuando es prefabricada. Cuando se arma en
  obra, la <strong>cámara séptica de ladrillos</strong> se calcula con
  <a href="/materiales/ladrillo-comun/">ladrillo común</a>, <a href="/materiales/cemento/">cemento</a>
  y arena, y se pide por millar y por bolsa, no como una pieza. Para cotizar, el proveedor
  necesita saber para cuántas personas es, cuántos baños descargan en ella y cómo es el terreno,
  porque de eso depende cuánto tiene que tratar el sistema. Los caños de conexión, las tapas y
  los accesorios se cotizan aparte. El precio cambia con la opción que elijas, el tamaño, la
  cantidad, el flete y la mano de obra, que tampoco es la misma para una cámara prefabricada que
  para una de ladrillo.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de elegir, confirmá con quien dirige la obra o con la municipalidad qué tamaño de cámara
  corresponde a tu casa y qué requisitos hay en tu zona, porque el dimensionamiento y la
  habilitación dependen del terreno, de la cantidad de gente y de la normativa local. No es algo
  para decidir solo con un presupuesto. Pedile al proveedor que te explique cómo es la
  <strong>cámara séptica y cómo funciona</strong> el modelo que te ofrece, qué tapa trae y cómo
  se hace el mantenimiento. Preguntá también cómo se conecta con el pozo ciego, porque la
  cámara sola no resuelve el desagüe. En cuanto a los materiales, mirá que el hormigón o el
  ladrillo estén bien cerrados y sellados para que no haya filtraciones fuera del sistema.
</p>
