<h2>Para qué se usa</h2>
<p>
  El piso vinílico es la opción que se elige cuando se quiere renovar un piso existente sin
  romper contrapiso ni levantar la cerámica vieja, algo que ningún revestimiento cerámico
  permite hacer. Se pide de varias formas según el formato: <strong>vinílicos adhesivos</strong>
  cuando son placas que se pegan directo sobre el piso actual, <strong>piso flotante</strong>
  cuando el sistema encastra sin pegamento, y <strong>vinílico en rollo</strong> para cubrir
  superficies grandes en una sola pieza continua, muy usado en locales comerciales y
  consultorios. Dentro del piso flotante está también el <strong>piso SPC</strong>, una
  variante más rígida y resistente al agua que el vinílico tradicional, pensada para ambientes
  donde el flotante común no aguantaría bien la humedad. Si en cambio la obra es nueva y el
  contrapiso todavía no tiene terminación, conviene evaluar directo
  <a href="/materiales/porcelanato/">porcelanato</a> o
  <a href="/materiales/ceramica-para-piso/">cerámica</a> antes de definirse por vinílico.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado o por caja</strong>, según el formato: rollo se cotiza
  por m² lineal de ancho de rollo, mientras que placas adhesivas o piso click vienen en caja
  cerrada como la cerámica. Para pedir bien necesitás la superficie total a cubrir, el sistema
  que preferís —adhesivo, click o rollo— y el espesor de la pieza, porque un espesor mayor
  resiste mejor el tránsito diario pero también cuesta distinto. Si el piso base tiene
  desniveles marcados, puede hacer falta una <strong>base niveladora</strong> antes de colocar,
  y ese material se cotiza aparte del vinílico. El precio depende del sistema elegido, del
  espesor, del diseño y del volumen total de m².
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate primero en el estado del piso existente: aunque el vinílico no exige romper la base,
  sí necesita una superficie limpia, seca y razonablemente nivelada, porque cualquier
  irregularidad del piso de abajo se termina marcando en la superficie del vinílico una vez
  colocado. Revisá el espesor en milímetros, generalmente entre 4 y 8 mm según el sistema:
  cuanto más grueso, mejor absorbe pequeñas imperfecciones y más dura frente al uso diario.
  Comparado con un piso laminado flotante de base MDF, el vinílico y el SPC resisten mejor la
  humedad, así que son la opción más segura para cocina o zonas con algo de agua ocasional. Un
  error común es elegir el sistema por el diseño sin preguntar por la resistencia al agua de
  ese modelo puntual, porque no todos los vinílicos toleran igual la humedad constante.
</p>

