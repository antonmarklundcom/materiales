<h2>Para qué se usa</h2>
<p>
  El <strong>ladrillo visto</strong> —el ladrillo prensado, como también se lo conoce, aunque en
  obra se pide más como "ladrillo a la vista" o "ladrillo de máquina"— es el que se coloca sin
  revoque, con la junta de mortero como terminación final. Se usa en fachadas, cercos
  perimetrales, columnas decorativas y en interiores donde se busca ese acabado rústico expuesto.
  A diferencia del ladrillo común, acá la cara del ladrillo es parte del diseño, así que la
  prolijidad del asentado importa tanto como el material en sí. Se usa también en parrillas
  exteriores de baja exigencia y en detalles de jardín donde el ladrillo queda permanentemente a
  la vista. Si lo que buscás es un ladrillo rústico para revocar, no para dejar expuesto, el
  <a href="/materiales/ladrillo-comun/">ladrillo común</a> o de campo es la opción correcta, no
  el prensado.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>millar</strong>, y conviene pedir siempre un poco más del cálculo exacto
  porque en obra vista los cortes y roturas se notan más que en pared revocada. Al proveedor hay
  que darle el metro cuadrado de fachada o cerco a cubrir y aclarar que es para uso visto, porque
  eso puede cambiar la selección de piezas dentro del lote. El flete se cotiza aparte según
  volumen y zona. El precio final depende de la cantidad de millares, del color y textura
  elegidos y de la distancia de entrega, así que conviene pedir la cotización con el metraje
  real ya calculado.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el color y la textura sean parejos entre las piezas del mismo pedido, porque en una
  pared vista cualquier diferencia de tono se nota a simple vista. Revisá los bordes y las
  esquinas: un ladrillo prensado con cantos rotos arruina la línea prolija que se busca en este
  tipo de terminación. Pedí ver una muestra física antes de comprar el volumen completo, porque
  el color en foto o catálogo no siempre coincide con el real. Evitá confundirlo con el ladrillo
  rústico o de campo pensado para revocar: ese no tiene la terminación pareja que necesita una
  obra vista.
</p>

