<h2>Para qué se usa</h2>
<p>
  Las <strong>ventanas de aluminio</strong> son la carpintería de aluminio más usada en obra
  nueva en Paraguay: no se hinchan con la humedad, no se pudren ni necesitan pintura de
  mantenimiento como la madera, y se fabrican en distintas líneas de perfiles según el uso y el
  presupuesto. La ventana corrediza es la más elegida porque no invade el ambiente al abrirse, y
  conviven bien con las de abrir, que cierran más hermético para ambientes que necesitan mejor
  aislación. Cuando la obra pide una pieza de vidrio sola, sin marco de aluminio —una mampara, un
  frente entero de vidrio— ya no es esto sino <a href="/materiales/vidrio-templado/">vidrio templado</a>,
  que es un producto distinto aunque comparta el material transparente.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad, según la medida del vano</strong>. Cada ventana se arma sobre el
  <strong>ancho y el alto real del vano</strong> tomados en obra, así que ese dato es el punto de
  partida de cualquier cotización. Además conviene indicar la <strong>línea de perfil</strong>
  que buscás, el <strong>tipo de apertura</strong> —corrediza o de abrir—, el color del aluminio
  y si necesitás mosquitero. Cuando son varias ventanas para una obra completa, conviene armar
  una lista por ambiente con esos datos, así el proveedor cotiza todo junto. El precio depende de
  la medida de cada vano, la línea de perfil elegida, el tipo de apertura, el color, el vidrio
  que lleva y si se suma mosquitero y colocación.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí la <strong>línea de perfil</strong> pensando en el uso del ambiente: una línea más
  robusta rinde mejor en aberturas grandes o muy expuestas al viento. Definí corrediza o de abrir
  según si el ambiente da a la calle o a un patio y si necesitás mejor cierre o no perder espacio
  interior. Confirmá qué vidrio trae —no todos los proveedores usan el mismo espesor por
  defecto— y si el mosquitero y la colocación están incluidos en el presupuesto, porque son los
  puntos donde más difieren dos cotizaciones que a primera vista parecen iguales.
</p>

