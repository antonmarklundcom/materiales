<h2>Para qué se usa</h2>
<p>
  La cal hidratada —la que la mayoría pide como <strong>cal apagada</strong> o simplemente
  <strong>cal en bolsa</strong>— es la que se usa directo, sin proceso previo en obra, para
  <strong>cal para revoque</strong> fino y para la clásica pintura a la cal de paredes exteriores e
  interiores. Se mezcla con arena fina para lograr un revoque más trabajable y con menos fisuras que uno
  hecho solo con cemento, y por eso aparece tanto en terminaciones tradicionales como en obras nuevas que
  buscan esa textura. También se usa como aditivo en morteros de asentado para darles más plasticidad,
  algo que facilita el trabajo del albañil en días de calor cuando la mezcla tiende a secarse rápido. Para
  terminaciones más finas todavía, algunos maestros piden puntualmente <strong>cal fina</strong> tamizada,
  que deja menos grano visible en la última mano.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>bolsa</strong>, y para armar el pedido alcanza con la cantidad que necesitás según
  los metros cuadrados de revoque o pintura a la cal que vas a cubrir. Es un dato útil aclarar si la vas a
  usar para revoque grueso, para la mano final o para pintura, porque cambia la proporción con la que se
  mezcla y a veces conviene pedir junto con arena lavada para no hacer un viaje aparte. El precio depende
  de la cantidad de bolsas pedidas y del flete hasta tu zona, como con el resto de los aglomerantes.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que la bolsa esté bien sellada y que el contenido no tenga grumos duros al tacto, porque la cal
  que absorbió humedad en depósito pierde parte de su capacidad de unión y da un revoque que fisura más
  fácil. Si buscás la mano final de un revoque visto, fijate que te vendan cal fina y no la de uso general,
  porque la diferencia de grano se nota en la terminación. Un error común es usar cal hidratada pensando
  que rinde igual que la cal viva apagada en obra: al ser un producto ya procesado, la proporción de mezcla
  cambia, así que conviene confirmar la dosificación con quien te vende antes de calcular cuánta bolsa
  necesitás.
</p>

