<h2>Para qué se usa</h2>
<p>
  La bomba de agua es la que mueve el agua cuando sola no llega: sube el agua de un pozo hasta la
  casa, la lleva hasta el <a href="/materiales/tanque-de-agua/">tanque de agua</a> o saca agua
  de donde no tiene que estar. En obra y en casa se la pide con distintos nombres: <strong>motor
  de agua para pozo</strong>, <strong>motor para agua</strong>, <strong>motobomba</strong> o
  <strong>electrobomba</strong>, y a veces simplemente <strong>bombas de agua</strong> en plural,
  según el uso. Para un pozo se busca la <strong>bomba sumergible para pozo</strong>, que trabaja
  metida en el agua. Para tomar agua de una cisterna o de un tanque a nivel del suelo se usa una
  <strong>bomba periférica</strong> o una <strong>bomba centrífuga</strong>, que quedan fuera
  del agua. También existen la <strong>bomba de achique</strong> y la <strong>bomba de
  desagote</strong>, pensadas para vaciar sótanos, zanjas o piletas, la <strong>bomba para
  riego</strong>, la <strong>bomba manual</strong> y la <strong>bomba solar</strong> para
  lugares sin red eléctrica, además de la <strong>bomba de agua de 12 V</strong> que va con
  batería.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong> y se pide por <strong>potencia en HP</strong>: las más
  nombradas son las de <strong>1/2 HP</strong>, <strong>1 HP</strong> y <strong>2 HP</strong>.
  Para que el proveedor te cotice bien, contale qué vas a hacer con la bomba (pozo, tanque,
  riego, desagote), qué profundidad tiene el pozo si es el caso, y si la conexión eléctrica es la
  de tu casa o una instalación aparte. Con esos datos te recomiendan la potencia en vez de
  adivinarla. Lo que se cotiza aparte son los accesorios: el cable para la bajada, los caños y
  uniones, el tablero o protección y, si hace falta, el
  <a href="/materiales/presurizador-de-agua/">presurizador de agua</a> o el tanque. Para el
  tendido eléctrico de la bomba mirá el <a href="/materiales/cable-electrico/">cable
  eléctrico</a>, y para las conexiones hacia la casa el
  <a href="/materiales/cano-de-agua/">caño de agua</a>. El precio final cambia con el tipo de
  bomba, los HP, la cantidad y el flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El error más común es comprar por el HP sin haber definido el uso: una bomba de pozo y una
  bomba para trasvasar agua entre tanques no se reemplazan una por la otra. Antes de pedir,
  anotá si va a trabajar sumergida o en superficie, la profundidad del pozo, la altura del
  tanque y qué tipo de agua va a mover, porque la bomba de achique y la de desagote están
  preparadas para agua sucia y las otras no. Fijate también que la tensión de la bomba coincida
  con la de tu instalación y pedile al proveedor que confirme qué cable y qué protección
  necesita. La instalación eléctrica y la profundidad de colocación en el pozo confirmalas con
  un electricista o con quien hace la instalación. Si estás armando todo el sistema de agua,
  mirá la categoría <a href="/materiales/canos-y-plomeria/">caños y plomería</a>.
</p>
