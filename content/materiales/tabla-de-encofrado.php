<h2>Para qué se usa</h2>
<p>
  La tabla de encofrado —también llamada <strong>tabla de obra</strong> o
  <strong>madera para encofrado</strong>— es la que arma el molde donde se vuelca el
  hormigón de vigas, columnas y losas. Se clava formando el cajón o el fondo de losa, apoyada
  sobre <a href="/materiales/puntales/">puntales</a>, y se retira una vez que el hormigón
  fraguó lo suficiente. A diferencia de la <a href="/materiales/terciada/">terciada</a>, que
  da una cara lisa y continua, la tabla se adapta mejor a formas irregulares o a encofrados
  que no van a quedar vistos, y suele salir más a cuenta cuando el número de reutilizaciones
  previstas es bajo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>pieza o por metro cuadrado</strong> de encofrado a cubrir, según cómo
  cotice el proveedor. Para pedir bien contá si vas a comprar por escuadría, largo y cantidad
  de piezas sueltas, o si preferís pasar directamente los <strong>metros cuadrados de
  encofrado</strong> que necesitás armar (vigas, columnas, losa) para que te calculen la
  cantidad. El precio depende del espesor y el largo de la tabla, el tipo de madera, la
  cantidad total y el flete hasta la obra; también influye si la vas a comprar nueva o si el
  proveedor te ofrece tabla ya usada en otra obra, más económica pero con menos vida útil por
  delante.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Pensá cuántos usos le vas a dar antes de elegir entre tabla nueva y usada: una tabla que ya
  pasó por varios desencofrados rinde menos y puede filtrar lechada por las juntas abiertas.
  Revisá que el ancho de tabla sea parejo entre piezas, porque las diferencias se notan en la
  cara del hormigón cuando se desencofra. Si el elemento va a quedar visto —una columna sin
  revoque, por ejemplo— evaluá si conviene la terciada en lugar de la tabla, ya que deja una
  superficie más lisa y con menos marcas de junta. Y calculá siempre la cantidad de clavos que
  vas a necesitar junto con la tabla, para no tener que parar la obra por eso.
</p>

