<h2>Para qué se usa</h2>
<p>
  La <strong>canilla de lavatorio</strong> lleva el agua a la bacha del baño para el lavado
  de manos y el aseo diario. La grifería de lavatorio se elige según la forma y la altura
  de esa bacha, además del lugar donde se fija: sobre el artefacto, en la mesada o en la
  pared. Una bacha apoyada puede necesitar un pico más alto que otra embutida, pero la
  medida se confirma con el conjunto real. El <strong>monocomando de lavatorio</strong>
  mezcla agua fría y caliente mediante una palanca; una canilla para lavatorio de agua fría
  cumple otra necesidad. Aunque algunos modelos se parezcan a los de cocina, el espacio
  de uso y el alcance del pico son distintos. Conviene definirlos pensando en el baño que
  estás armando, no solamente en el color de los accesorios.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Para pedir cotización, pasá la cantidad, el tipo de
  bacha y las medidas del montaje: altura del borde, ubicación de la perforación y espesor
  del apoyo. Si va en pared, indicá la posición de las tomas respecto del lavatorio.
  Contá si hay suministro de agua caliente y qué terminación buscás. Sumá tu ciudad o
  barrio para incluir el flete. Pedí que la oferta detalle flexibles, juntas y fijaciones;
  la válvula de desagüe y el sifón no se deben dar por incluidos con la canilla. Esos
  accesorios y la colocación se cotizan aparte cuando no forman parte del conjunto.
  El precio depende de la altura, el material del cuerpo, el mecanismo, el montaje y el
  acabado. Compará modelos con el mismo alcance y contenido para evaluar el presupuesto.
</p>
