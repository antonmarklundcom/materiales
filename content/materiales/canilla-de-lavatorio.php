<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá dónde va a caer el chorro y cuánto espacio queda para las manos. Un pico que
  termina demasiado cerca del borde puede resultar incómodo aunque la base entre en la
  perforación. Comprobá que la palanca abra sin tocar el espejo, la pared o un estante.
  Debajo de la mesada tiene que haber acceso para fijar la grifería y conectar los
  flexibles sin forzarlos. Preguntá por repuestos del mecanismo y confirmá las condiciones
  de alimentación de agua que pide el modelo. Si renovás solamente la canilla, revisá con
  el instalador las conexiones existentes antes de comprar adaptadores. Al recibir el
  producto, verificá la terminación, los accesorios y las medidas contra lo cotizado para
  resolver cualquier diferencia antes de la colocación.
</p>

