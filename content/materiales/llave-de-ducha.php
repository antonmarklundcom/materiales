<h2>Para qué se usa</h2>
<p>
  La <strong>llave de ducha</strong> abre, cierra y regula el paso del agua en la zona de
  baño. Cuando se pide como <strong>mezcladora de ducha</strong>, combina el agua fría y
  caliente que llegan por cañerías separadas; no produce calor por sí misma. El monocomando
  de ducha concentra ese manejo en una palanca, mientras que otros conjuntos tienen mandos
  separados. La llave para ducha puede formar parte de una instalación empotrada o de un
  conjunto exterior, y esa elección cambia qué queda dentro de la pared. La ducha de mano
  se puede sumar como accesorio para dirigir el agua, con su manguera y soporte. Conviene
  pedirla junto con la grifería para que las salidas y el sistema que desvía el agua
  correspondan al uso que querés darle.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>, pero la cotización debe aclarar qué compone el
  conjunto. Indicá cantidad, montaje, medidas de las conexiones y si se trata de obra nueva
  o reemplazo. En una renovación, pasá los datos del cuerpo existente y confirmá si querés
  conservarlo o cambiar todo. Pedí que separen cuerpo de empotrar, mandos, terminación,
  salida, brazo y rociador cuando corresponda. Si agregás ducha de mano, incluí manguera,
  soporte y desviador compatible en el listado. Los accesorios que falten, el flete hasta
  tu zona y la colocación se cotizan aparte. El precio depende del mecanismo, el montaje,
  el material del cuerpo, el acabado y el contenido del juego. Una terminación visible
  sola no se compara directamente con una grifería que incluye la parte empotrada.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá con el instalador que el modelo corresponda al suministro de agua y a las
  conexiones de la obra. Si todavía no cerraste la pared, definí la posición y la
  profundidad del cuerpo considerando el revestimiento terminado. Si la pared ya está
  revestida, revisá qué trabajo requiere el reemplazo antes de pedir una pieza distinta.
  Las tapas y las palancas no son intercambiables por su apariencia: tienen que corresponder
  al mecanismo instalado. Preguntá por repuestos y por el acceso para mantenimiento.
  Para una ducha de mano, comprobá el lugar del soporte y el recorrido de la manguera.
  También pedí las condiciones de presión del modelo; ese dato ayuda al instalador a
  verificar que el conjunto pueda trabajar con la alimentación de tu baño.
</p>
