<h2>Para qué se usa</h2>
<p>
  La babeta es la pieza de chapa, en forma de tira doblada, que sella la unión entre el techo y
  una pared o una chimenea para que el agua de lluvia no se meta por esa juntura. Es la que
  cubre el encuentro entre la chapa y el muro, y se fija arriba en la pared y abajo sobre la
  cubierta. La <strong>limahoya</strong> es otra pieza distinta: es la canal metálica que va en
  el valle donde se encuentran dos faldones del techo, y lleva el agua hasta el alero o la
  <a href="/materiales/canaletas/">canaleta</a>. Ambas se hacen de <strong>chapa</strong> y
  funcionan como terminaciones, junto con la <a href="/materiales/chapa-trapezoidal/">chapa
  trapezoidal</a> o la <a href="/materiales/chapa-de-zinc/">chapa de zinc</a> del techo.
  Muchas filtraciones de un techo de chapa no vienen de la chapa, sino de una babeta mal puesta
  o de una limahoya que quedó angosta.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se piden por <strong>metro o por tira</strong>. La limahoya se suele pedir también como
  <strong>limahoya de zinc</strong> o limahoya metálica, y la babeta se fabrica doblando la
  chapa a la medida que necesites. Para cotizar tenés que pasar el <strong>largo total</strong>
  de la pieza, el <strong>desarrollo o ancho</strong> de la chapa desplegada, el material y el
  espesor que querés, y sobre qué techo va, porque tiene que coincidir con la chapa de la
  cubierta. Los tornillos, selladores y remates se cotizan aparte; pedilos junto con los
  <a href="/materiales/tornillos-para-chapa/">tornillos para chapa</a> para que el proveedor
  los haga calzar. El precio cambia con el material, el espesor, el desarrollo, el largo y el
  flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Medí bien cada tramo antes de pedir. Esta tabla separa las dos piezas y lo que tenés que
  consultar en cada una:
</p>
<table>
  <thead>
    <tr><th>Pieza</th><th>Dónde va</th><th>Qué pedirle al proveedor</th></tr>
  </thead>
  <tbody>
    <tr>
      <td>Babeta contra pared</td>
      <td>En el encuentro del techo con una pared o muro, para que el agua no se meta por la junta.</td>
      <td>Material y espesor (consultá cuál conviene), desarrollo o ancho, largo de tira y que coincida con la chapa.</td>
    </tr>
    <tr>
      <td>Babeta de chimenea</td>
      <td>Alrededor de una chimenea o un conducto que atraviesa el techo.</td>
      <td>Material y espesor, desarrollo o ancho, largo de cada tramo y que coincida con la chapa.</td>
    </tr>
    <tr>
      <td>Limahoya</td>
      <td>En el valle entre dos faldones, donde se juntan las aguas del techo.</td>
      <td>Material y espesor, desarrollo o ancho suficiente para el caudal, largo de tira y que coincida con la chapa.</td>
    </tr>
  </tbody>
</table>
<p>
  Preguntale al proveedor qué <strong>material y espesor</strong> recomienda para tu techo y que
  sea el mismo tipo de metal que la chapa, para evitar problemas de corrosión entre piezas
  distintas. Revisá que los dobleces estén parejos y que los tramos tengan el largo que
  necesitás sin muchos empalmes, porque cada empalme es un punto más donde puede filtrar. Si la
  pared donde apoya la babeta ya tiene humedad, la
  <a href="/materiales/membrana-liquida/">membrana líquida</a> puede servir de refuerzo en esa
  unión; consultalo con quien dirige la obra.
</p>

