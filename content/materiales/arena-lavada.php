<h2>Para qué se usa</h2>
<p>
  La arena lavada —conocida también como <strong>arena fina</strong> o <strong>arena de
  río</strong>— es la que se pide cuando el trabajo necesita una terminación prolija: revoques,
  enlucidos, morteros de asentamiento de mampostería y contrapisos finos donde no puede quedar
  ni una piedrita ni un grumo de barro. Al pasar por el lavado, esta <strong>arena
  limpia</strong> queda sin arcilla ni materia orgánica, algo clave para que el revoque no se
  fisure ni el mortero pierda resistencia con el tiempo. También se usa como <strong>arena
  cernida</strong> en trabajos de albañilería fina, pisos de asiento para contrapisos livianos
  y en mezclas donde el grano grueso de otra arena arruinaría el acabado. Si en cambio la obra
  necesita resistencia estructural —un contrapiso grueso o un hormigón— la
  <a href="/materiales/arena-gorda/">arena gorda</a> es la que corresponde, no ésta.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cúbico</strong> o por <strong>camionada</strong>, según el volumen
  que necesites. Para armar la cotización hace falta la <strong>cantidad</strong> en m³ (o el
  ambiente que vas a cubrir, si todavía no lo calculaste), y la <strong>zona de entrega</strong>,
  porque el flete cambia según distancia y acceso a la obra. El precio final depende del
  volumen total, de la distancia desde el lugar de extracción hasta tu obra y de la
  disponibilidad en la zona en ese momento, así que no hay una cifra fija válida para todos los
  casos. Si además vas a comprar cemento o piedra triturada para la misma tarea, pedilo todo
  junto: se ahorra un viaje de flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que la arena esté realmente lavada y no simplemente cernida en seco: si al tacto sentís
  barro o al mojarla se pone pegajosa, todavía tiene arcilla y eso va a afectar el revoque.
  Mirá también el color y la uniformidad del grano —una arena pareja rinde mejor en la mezcla
  que una con piedras sueltas o restos de otro material—. Un error común es pedir arena fina
  pensando que sirve para contrapiso grueso: ahí el grano chico no da la resistencia que se
  necesita, y conviene usar arena gorda en su lugar. Antes de recibir la camionada, chequeá que
  el volumen cargado corresponda a lo pedido, porque un volquete mal medido es fácil de detectar
  a simple vista si sabés cuánto pediste.
</p>

