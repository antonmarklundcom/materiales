<h2>Para qué se usa</h2>
<p>
  La chapa termoacústica —acá casi todo el mundo la pide como <strong>isopanel</strong> o
  <strong>panel sándwich</strong>— es la que va cuando abajo del techo hay un ambiente
  habitable: dormitorio, oficina, comedor, un local con gente adentro todo el día. Entre las
  dos caras metálicas lleva un núcleo aislante que corta el calor que baja al mediodía y el
  ruido de la lluvia contra la chapa, algo que la chapa simple no resuelve por más gruesa que
  sea. Se usa mucho también como <strong>chapa con aislación</strong> para cerramiento de
  paredes en cámaras frigoríficas, depósitos y locales comerciales, no sólo en techo. Si en
  cambio el ambiente de abajo es un galpón, un depósito sin uso constante o una cochera, la
  <a href="/materiales/chapa-trapezoidal/">chapa trapezoidal</a> suele alcanzar y sale más
  económica.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>panel o por metro lineal</strong>, según el largo de faldón que
  necesites: el proveedor corta a medida, así que cuanto más exacto el dato, menos desperdicio
  pagás. Para pedir bien necesitás el <strong>largo del faldón</strong> (de cumbrera a alero,
  sin empalmes si podés evitarlos), el <strong>ancho útil</strong> que vas a cubrir y el
  <strong>espesor del panel</strong> que buscás, porque no todos los espesores aíslan igual ni
  cuestan igual. Los accesorios —cumbreras, babetas, tornillería autoperforante— se cotizan
  aparte del panel, y conviene pedirlos en la misma consulta para no duplicar flete. El precio
  final depende del espesor, del largo total, de la cantidad de m² y del flete hasta tu zona;
  por eso no hay una cifra única que sirva para toda obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en el <strong>espesor real del núcleo</strong> (no todos los "sándwich" del mercado
  aíslan lo mismo) y en el tipo de núcleo: poliuretano inyectado aísla más que otros rellenos
  con el mismo espesor. Revisá que la chapa exterior tenga el galvanizado y la pintura
  adecuados para exposición directa al sol paraguayo, porque un panel mal terminado se
  deteriora rápido en la cara expuesta. Pedí que te confirmen la pendiente mínima que soporta
  la estructura para ese ancho de panel, y calculá bien la estructura de apoyo: un panel más
  pesado que la chapa simple necesita correas dimensionadas para el peso. Si vas a usarlo en
  pared, preguntá por el sistema de fijación oculta, que deja una terminación más prolija que
  el tornillo visto.
</p>

