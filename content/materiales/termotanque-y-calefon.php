<h2>Para qué se usa</h2>
<p>
  El <strong>termotanque eléctrico</strong> y el <strong>calefón eléctrico</strong> sirven para
  tener agua caliente en la casa sin depender de la ducha eléctrica de cada baño. En Paraguay se
  los pide con varios nombres: <strong>termotanque</strong> o <strong>termotanques</strong>,
  <strong>calefones</strong>, <strong>termo calefón</strong> o, cuando lo que se quiere es la
  ducha caliente, <strong>ducha calefón eléctrico</strong>. Un equipo único puede abastecer la
  cocina, el lavatorio y la ducha, y desde él sale la cañería de agua caliente hacia cada
  punto, así que se lo decide al planificar la instalación sanitaria y no cuando la obra ya está
  terminada. Si solamente necesitás calentar el agua de una ducha, tal vez te alcance con una
  <a href="/materiales/ducha-electrica/">ducha eléctrica</a>; si querés agua caliente en varios
  puntos, lo normal es un termotanque o un calefón con su
  <a href="/materiales/llave-de-ducha/">llave de ducha</a> mezcladora. El equipo se alimenta del
  <a href="/materiales/tanque-de-agua/">tanque de agua</a> de la casa o de la red.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>, y se pide por capacidad en litros: los más pedidos son
  el <strong>termo calefón de 20 litros</strong>, el <strong>termotanque de 50 litros</strong> y
  el <strong>termotanque de 80 litros</strong>. Para cotizar, pasale al proveedor la cantidad
  de personas de la casa, cuántos puntos de agua caliente querés abastecer (ducha, cocina,
  lavatorio), si lo vas a instalar adentro o a la intemperie y dónde queda el tablero. Los
  accesorios se cotizan aparte: preguntá si el pedido incluye los flexibles, la válvula de
  seguridad, el soporte de pared y, si hace falta, las <a href="/materiales/llave-de-paso/">llaves
  de paso</a> para aislar el equipo. El flete va por separado. El precio cambia con la capacidad,
  el tipo de equipo, la terminación y la cantidad de unidades.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí la capacidad por cuánta gente usa agua caliente a la vez, y no por el equipo más
  chico: un termotanque de poca capacidad en una casa grande obliga a esperar entre baño y baño. Pedí
  siempre la <strong>potencia</strong> y los datos eléctricos del equipo, porque de eso depende
  el cable, la protección y el tablero que le tocan. La conexión eléctrica y la de agua tienen
  que hacerlas profesionales: confirmá con tu electricista que la instalación existente lo
  soporta, y con tu plomero cómo se resuelve el empalme con los
  <a href="/materiales/cano-de-agua/">caños de agua</a> fría y caliente. Revisá también el lugar
  donde va, porque hace falta una pared que aguante el peso del equipo lleno y un desagüe a mano
  por si hay que vaciarlo.
</p>
