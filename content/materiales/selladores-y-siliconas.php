<h2>Para qué se usa</h2>
<p>
  No hay un único sellador para todo: cada junta pide el suyo. La <strong>silicona</strong>
  común —también llamada <strong>silicona fría</strong> o <strong>silicona para vidrio</strong>—
  va en vidrios, sanitarios y juntas que no se van a pintar encima. El <strong>sellador de
  juntas</strong> acrílico se usa donde la junta queda a la vista pero pintada, porque a
  diferencia de la silicona sí toma pintura. Y para encuentros con movimiento o exposición
  directa a la intemperie —dilatación entre placas, juntas de chapa, remates de techo— entra el
  <strong>sellador poliuretánico</strong>, lo que acá se pide como sikaflex, que resiste
  mejor el trabajo de la junta cuando el material se dilata y contrae. Para reparaciones
  puntuales de filtración, cualquiera de estos sirve; para un techo entero, la solución es una
  <a href="/materiales/membrana-liquida/">membrana líquida</a>, porque sellar filtración por
  filtración termina saliendo más caro que resolver la superficie completa.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>cartucho o pomo</strong>, y para pedir bien conviene aclarar qué vas a
  sellar —vidrio, sanitario, junta de dilatación, remate de techo— y en qué material, porque de
  ahí sale si corresponde silicona común, acrílico o poliuretánico. También ayuda calcular los
  metros de junta a cubrir, porque el rendimiento de un cartucho varía según el ancho y la
  profundidad del cordón que necesita esa junta en particular. El precio final depende del tipo
  de sellador, de la marca, del tamaño del cartucho y de la cantidad que pidas, así que conviene
  cerrar primero el uso antes de comparar precios entre productos que no son intercambiables.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá si la junta va a quedar pintada o a la vista: la silicona común no toma pintura, y
  aplicarla donde después hay que pintar arruina la terminación. Fijate también si la junta
  tiene movimiento —dilatación, exposición al sol y la lluvia— porque ahí el poliuretánico
  aguanta más que un acrílico común. Para vidrios y sanitarios, priorizá una silicona
  específica para ese uso y no una de uso general. Y si lo que tenés son varias filtraciones
  repartidas por el techo, conviene evaluar si conviene seguir selladas por sellador o pasar a
  una <a href="/materiales/membrana-liquida/">membrana líquida</a> que cubra todo de una vez.
</p>

