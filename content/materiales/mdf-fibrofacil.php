<h2>Para qué se usa</h2>
<p>
  El MDF —lo que en Paraguay casi todo el mundo pide como <strong>fibrofácil</strong>, o
  directamente como <strong>madera MDF</strong>— es una placa hecha de fibras de madera
  prensadas, sin las vetas ni los nudos de una tabla natural. Esa superficie lisa y pareja lo
  hace la opción de referencia para <strong>muebles</strong>, placares, puertas de mueble y
  revestimientos que después se pintan o se laminan, donde una terminación uniforme importa
  más que la resistencia estructural. Se consigue <strong>crudo</strong> —sin recubrimiento,
  para pintar o laquear en obra— o ya laminado de fábrica. No es el material para encofrado ni
  para estructura: para eso están la <a href="/materiales/terciada/">terciada</a> y la madera
  de escuadría.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>placa</strong>. Para pedir bien definí el <strong>espesor</strong> que
  necesitás —los finos rinden para fondos de cajón y respaldos, los gruesos para estantes y
  laterales de mueble— y si la buscás <strong>cruda o laminada</strong>. El precio depende del
  espesor, de la medida de la placa, de si es cruda o laminada, de la cantidad de placas y del
  flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de nada, confirmá que el ambiente de destino sea compatible: el MDF crudo no resiste
  la humedad, se hincha en las caras y en los cantos y no vuelve a su forma original, así que
  no conviene para baños, cocinas cerca de pileta o cualquier exterior. Definí el espesor según
  la pieza de mueble que vayas a armar, porque un estante subdimensionado se curva con el peso
  con el tiempo. Si vas a pintar o laquear, pedí la versión cruda y lijada; si buscás terminar
  rápido sin pintura, la laminada ya viene con el acabado de fábrica. Revisá también los cantos
  de la placa al recibirla, porque un golpe en el canto de MDF no se repara tan fácil como en
  una tabla maciza.
</p>

