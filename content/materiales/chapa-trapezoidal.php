<h2>Para qué se usa</h2>
<p>
  La chapa trapezoidal —muchas veces pedida directamente como <strong>chapa T101</strong> o
  <strong>chapa trapezoidal galvanizada</strong>— se distingue de la chapa de zinc común por su
  perfil: nervios más altos y rígidos en forma de trapecio, que le dan mucha más resistencia a
  la flexión con menos apoyos. Por eso es la elegida para <strong>chapa para galpón</strong>,
  naves industriales, depósitos grandes y cualquier techo donde la luz entre correas es amplia
  y no conviene multiplicar la estructura de apoyo. También se usa en cerramientos verticales
  de galpones, donde su rigidez permite paneles más largos sin ondulaciones. Para un techo de
  vivienda con estructura más liviana, la <a href="/materiales/chapa-de-zinc/">chapa de zinc</a>
  acanalada suele bastar y sale más simple de instalar; si además necesitás aislación, ahí
  entra la <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>chapa o por metro lineal</strong>. Para pedir bien necesitás el
  <strong>largo de faldón</strong>, la <strong>cantidad de metros cuadrados</strong> a cubrir,
  el <strong>perfil trapezoidal</strong> (la altura de onda) y el calibre de chapa que buscás,
  porque la combinación de perfil y calibre es la que define cuánta luz entre correas soporta
  sin flexar. Los accesorios de terminación —cumbreras, babetas, tornillería
  autoperforante— se cotizan aparte del metro de chapa y conviene pedirlos juntos para no
  fraccionar el flete. El precio final depende del perfil, del calibre, del largo total y del
  flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de definir el perfil, pasale al proveedor la <strong>luz entre correas</strong> que
  vas a tener en tu estructura: de eso depende qué medida de chapa trapezoidal aguanta sin
  necesitar más apoyos. Como referencia general:
</p>
<table>
  <thead>
    <tr><th>Medida / perfil</th><th>Uso típico</th></tr>
  </thead>
  <tbody>
    <tr><td>Ancho útil angosto, onda baja</td><td>Techos con correas más juntas, luces cortas</td></tr>
    <tr><td>Ancho útil mayor, onda alta (tipo T101)</td><td>Galpones industriales, luces largas entre correas</td></tr>
  </tbody>
</table>
<p>
  Revisá también el galvanizado de la chapa, que las nervaduras vengan derechas y sin
  aplastamientos por mal estibado, y que el largo pedido no obligue a hacer empalmes
  innecesarios en el faldón, porque cada empalme es un punto más de filtración a futuro.
</p>

