<h2>Para qué se usa</h2>
<p>
  El <strong>canto rodado</strong> —que en la obra se pide simplemente como
  <strong>ripio</strong>, o a veces como <strong>grava</strong>— es la piedra redondeada que se
  usa para bases compactadas de caminos internos, pisos de garaje y patios, drenajes al pie de
  muros y como parte del hormigón cuando no se necesita la resistencia de una piedra triturada.
  Se pide como <strong>ripio para hormigón</strong> en mezclas de menor exigencia estructural,
  y también se usa suelto como terminación decorativa en jardines o como base de asiento antes
  de una capa de hormigón o adoquín. A diferencia de la piedra triturada, que tiene bordes
  filosos por el proceso de trituración, el canto rodado es de origen natural y su forma
  redondeada lo hace más fácil de compactar en capas de base. Si tu obra necesita mayor
  resistencia estructural —una losa cargada o un pavimento de tránsito pesado— ahí conviene la
  <a href="/materiales/piedra-triturada/">piedra triturada</a> en lugar de ripio.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cúbico</strong> o por <strong>camionada</strong>, igual que el
  resto de los áridos. Para pedirlo bien, el proveedor necesita saber la
  <strong>cantidad</strong> en m³ y la <strong>zona</strong> de entrega, ya que el flete
  representa una parte importante del costo total en materiales de este volumen. El precio
  final varía según el volumen pedido, la distancia de traslado y la disponibilidad del
  material en la cantera más cercana a tu zona, por lo que no corresponde dar una cifra fija.
  Si en la misma obra vas a necesitar <a href="/materiales/cemento/">cemento</a> o
  <a href="/materiales/arena-lavada/">arena</a> para el mismo hormigón, conviene pedir todo
  junto y ahorrar en el flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en el tamaño del canto: para base compactada conviene un tamaño más uniforme que
  facilite el apisonado, mientras que para drenaje sirve mejor una granulometría más variada
  que deje pasar el agua. Revisá que no venga mezclado con demasiada tierra o arena, porque eso
  reduce la capacidad drenante que es justamente la ventaja de este material. Un error común es
  confundir el ripio con la piedra triturada al momento de pedir: si necesitás hormigón
  estructural para una losa, el canto rodado redondeado no traba igual que la piedra partida, y
  ahí conviene pasarse a <a href="/materiales/piedra-triturada/">piedra triturada</a>. Antes de
  recibir la carga, chequeá visualmente el volumen contra lo pedido.
</p>

