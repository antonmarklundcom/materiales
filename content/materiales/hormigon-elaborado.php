<h2>Para qué se usa</h2>
<p>
  El hormigón elaborado —lo que en obra se pide como <strong>hormigón premezclado</strong> u
  <strong>hormigón listo</strong>— es la opción para cuando no querés dosificar cemento, arena y ripio a
  mano en el sitio. Llega en un <strong>mixer de hormigón</strong> ya mezclado y en punto para volcar, así
  que se usa mucho en losas, contrapisos grandes y zapatas donde el volumen necesario sería lento y poco
  parejo de preparar en obra. También se pide para columnas y estructuras donde conviene un hormigón de
  calidad uniforme de principio a fin del volcado, algo difícil de garantizar mezclando en varias tandas
  con hormigonera chica. No cubre hormigón armado con cálculo estructural específico, encofrado especial ni
  losas con detalle de ingeniería —eso es un capítulo aparte que depende del proyecto—, pero sí resuelve el
  material en bruto listo para esas etapas.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>metro cúbico</strong>, y para pedirlo bien necesitás el volumen total que vas a
  volcar, el tipo de elemento (losa, contrapiso, zapata, columna) porque cada uno pide una resistencia
  distinta, y si el volcado va a ser directo desde el mixer o necesita <strong>bombeado</strong> para
  llegar a un punto alto o de difícil acceso. El bombeo se cotiza aparte del hormigón en sí, así que
  conviene pedirlo en la misma consulta si tu obra lo necesita. El precio depende del volumen pedido, de la
  resistencia requerida y de la distancia hasta tu obra, porque el hormigón tiene un tiempo de
  trabajabilidad limitado desde que sale de planta y eso condiciona la logística del viaje.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá con el proveedor la resistencia que corresponde a tu elemento estructural antes de cerrar el
  pedido, porque no toda losa ni todo contrapiso necesitan la misma dosificación. Coordiná bien el acceso
  del mixer hasta el punto de volcado: si la obra tiene entrada angosta o el punto de vuelco está lejos del
  camión, vas a necesitar bombeado y eso hay que preverlo antes de que llegue el camión, no cuando ya está
  en el sitio. Tené el encofrado y la superficie de recepción totalmente listos antes de que llegue el
  hormigón, porque una vez cargado el mixer el material no espera: cada minuto de demora en obra juega en
  contra de la trabajabilidad y la terminación final.
</p>

