<h2>Para qué se usa</h2>
<p>
  El ladrillo sapo es un <strong>bloque de relleno para losa alivianada</strong> que se usa
  junto con viguetas. Forma parte del sistema de vigueta y ladrillo, también llamado vigueta
  y bovedilla, habitual en la construcción de losas de piso y techo en Paraguay. Si estás
  preparando el pedido de materiales para una losa de este tipo, identificá el relleno que
  figura en tu proyecto antes de pedir una cotización.
</p>
<p>
  Hay una variante <strong>cerámica, de arcilla</strong>, y otra más liviana hecha de
  <strong>poliestireno expandido o telgopor</strong>. Al consultar, aclará el material de la
  pieza: pedir solamente ladrillo sapo puede dejar esa elección sin definir. El tejuelón se
  usa en el mismo sistema constructivo, pero es un producto distinto y se vende por separado.
  Compartir el uso en una losa con viguetas no convierte a estos nombres en sinónimos ni
  alcanza para decidir un reemplazo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Pedí la cotización por <strong>unidad</strong> y confirmá con el proveedor cómo presenta
  la cantidad total del pedido. Indicá si necesitás la versión cerámica o la de poliestireno
  expandido, la medida requerida y la zona donde está la obra. Si todavía no tenés el conteo
  de piezas, pasá la superficie de losa y los datos de las viguetas para que puedan revisar
  el pedido con quien definió el proyecto.
</p>
<p>
  Para comparar propuestas, pedí que detallen el mismo producto, la misma medida y la misma
  cantidad. Consultá el flete y la descarga por separado, y aclarales si también necesitás
  las viguetas u otros materiales de la losa. Confirmá qué incluye cada presupuesto antes de
  compararlo: una cotización del relleno solo no describe el mismo pedido que otra que suma
  las viguetas. El precio depende de la variante, la medida, la cantidad y el traslado hasta
  tu zona; cargá esos datos cuando pidas precio.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que la descripción del presupuesto diga ladrillo sapo y especifique de qué material
  está hecho. Confirmá con quien dirige la obra que la pieza ofrecida corresponde al sistema
  de viguetas previsto. Pedí las medidas al proveedor y contrastalas con el proyecto, sin
  asumir que cualquier bloque de relleno sirve para la misma losa.
</p>
<p>
  Al recibir el pedido, verificá la cantidad, la variante y el estado de las piezas; si ves
  roturas o diferencias con lo acordado, consultá antes de colocarlas. Evitá cambiar de
  cerámica a telgopor, o de ladrillo sapo a tejuelón, solamente por el nombre o por una
  diferencia de precio. Primero confirmá que el cambio corresponde a lo previsto para tu obra.
</p>

