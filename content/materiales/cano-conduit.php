<h2>Para qué se usa</h2>
<p>
  El caño conduit y la canaleta para cable sirven para lo mismo: llevar los cables de la
  instalación eléctrica protegidos, ya sea embutidos en la pared o a la vista. Ojo, que no hay
  que confundirlo con la <a href="/materiales/canaletas/">canaleta del techo</a>, la que junta
  el agua de lluvia: es otro producto. El <strong>caño conduit</strong> rígido va por dentro de
  paredes y losas, o en tramos a la vista. El <strong>caño corrugado</strong> es flexible y es
  el que más se usa para bajar por las paredes antes de revocar. La <strong>canaleta para
  cable</strong> (también se pide como <strong>cable canaleta</strong> o <strong>canaletas para
  cables</strong>) es la que se pega sobre la pared cuando no se puede abrir, y el <strong>cable
  canal para piso</strong> protege el cable donde se pisa. Los cables en sí son otro pedido: el
  <a href="/materiales/cable-electrico/">cable eléctrico</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>tira</strong> o por <strong>metro</strong>, según el proveedor y el
  producto. Para cotizar necesita saber cuál de las opciones querés, el diámetro o el ancho, la
  longitud total que vas a cubrir y los accesorios: codos, uniones, cajas de paso y tapas. Los
  accesorios se piden aparte y es fácil quedarse corto, así que contá cada esquina y cada
  empalme del recorrido. El flete se cotiza aparte, y el precio cambia con el tipo de caño o
  canaleta, el diámetro, los metros y los accesorios. Si tenés dudas sobre cuántos cables van a
  pasar por cada tramo, consultalo con tu electricista antes de pedir.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí el diámetro pensando en los cables que van a pasar y en los que quizás sumes después:
  un caño justo te complica el enhebrado y no deja lugar para ampliar. Fijate que las tiras
  vengan rectas y sin rajaduras, y que los accesorios sean del mismo sistema que el caño, para
  que encastren bien. Para el recorrido, el tablero y la protección de cada circuito, confirmalo
  con tu electricista; el <a href="/materiales/tablero-electrico/">tablero eléctrico</a> es el
  punto de partida. Si además vas a pasar agua o desagüe, eso va con el
  <a href="/materiales/cano-de-pvc/">caño de PVC</a>, no con este. La tabla resume las
  opciones.
</p>
