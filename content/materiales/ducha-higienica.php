<h2>Para qué se usa</h2>
<p>
  La <strong>ducha higiénica</strong> es una ducha de mano que se instala al lado del inodoro
  para la higiene personal después de usarlo. Cumple la función del bidet sin ocupar el lugar
  de otro artefacto, por eso aparece tanto en baños chicos, en baños de servicio y en
  renovaciones donde no hay espacio ni desagüe para sumar un bidet. Se pide de varias formas:
  <strong>ducha higiénica para inodoro</strong>, <strong>ducha de mano para inodoro</strong> o
  directamente <strong>kit de ducha higiénica</strong>, porque casi siempre se compra como
  conjunto. Ese conjunto combina una llave de pared o una mezcladora, un flexible, la ducha
  de mano —que se abre con un pulsador o un gatillo— y el soporte donde queda apoyada. No es
  la misma pieza que la ducha de mano del box: esa va con la
  <a href="/materiales/llave-de-ducha/">llave de ducha</a> y tiene otras salidas y otro
  recorrido de manguera.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad o kit</strong>, y lo primero que tiene que aclarar la
  cotización es qué trae ese kit. Indicá la cantidad, si la llave va embutida en la pared o
  aplicada por fuera, y si querés una sola agua o una mezcladora de fría y caliente. Para
  mezclar tiene que llegar agua caliente por cañería hasta el baño; si no llega, pedí un
  modelo de una sola agua. Contá también de dónde sale el agua: si hay una toma libre cerca
  del inodoro o si hay que derivar de la conexión de la mochila, porque eso cambia las
  piezas de unión que hacen falta. Los accesorios que no vengan en el kit, el flete hasta tu
  zona y la colocación se cotizan aparte. El precio depende del tipo de llave, del material
  del cuerpo y de la ducha de mano, de la terminación, del largo y la calidad del flexible y
  de cuántas piezas trae el conjunto. Un kit completo no se compara directo con una ducha
  de mano suelta.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Definí la posición antes de revestir la pared: la llave y el soporte tienen que quedar al
  alcance de la mano desde el inodoro y el flexible tiene que llegar sin quedar tirante.
  Si la pared ya está terminada, preguntá al instalador qué trabajo implica llevar el agua
  hasta ese punto antes de elegir un modelo embutido. Revisá que las roscas y las medidas
  de conexión del kit coincidan con las de tu instalación; que dos piezas se vean parecidas
  no garantiza que enrosquen. Fijate en el flexible, que es la pieza que más trabaja, y
  preguntá si hay repuesto de flexible y de ducha de mano por separado. Pedí también las
  indicaciones del fabricante sobre presión y sobre si conviene cerrar la llave después de
  cada uso, para no dejar el flexible con presión todo el día. Y si estás renovando el
  baño completo, cotizá la ducha higiénica junto con el <a href="/materiales/inodoro/">inodoro</a>:
  así el instalador puede ubicar las dos cosas de una vez.
</p>

