<h2>Para qué se usa</h2>
<p>
  Los azulejos son la pieza pensada para revestir pared, no para pisar, y en Paraguay se piden
  casi siempre para <strong>azulejos para baño</strong> y <strong>azulejos para cocina</strong>,
  las dos zonas donde una pared necesita superficie lavable y resistente a salpicaduras. A
  diferencia de la cerámica de piso, el azulejo tiene un cuerpo más liviano porque no necesita
  soportar peso ni pisada, y eso permite diseños más variados en color y relieve sobre la cara
  vista. Cubre desde el revestimiento completo de una pared de baño hasta una franja detrás de
  la mesada de cocina, y también se usa como <strong>revestimiento de pared</strong> en
  espacios donde se busca un acento visual sin llegar a cubrir todo el ambiente. Si la idea es
  en cambio revestir piso, ese trabajo corresponde a la
  <a href="/materiales/ceramica-para-piso/">cerámica para piso</a>, no al azulejo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>, en <strong>caja cerrada</strong>. Para cotizar
  necesitás la superficie de pared a cubrir (altura por ancho, descontando aberturas si las
  hay), el formato de la pieza y si buscás un diseño liso o con relieve, porque el relieve
  suele venir en tiradas más cortas y conviene confirmar disponibilidad antes de definir la
  cantidad. El adhesivo para pared y la pastina se cotizan aparte del azulejo, y conviene
  pedirlos en la misma consulta indicando el color de junta que buscás. El precio depende del
  diseño elegido, del formato y del volumen total de m² pedido, así que conviene tener la
  medida exacta de la pared antes de consultar.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el azulejo elegido esté pensado para pared y no para piso: colocar en el suelo una
  pieza de pared es un error frecuente, porque su superficie y su cuerpo no están hechos para
  soportar pisada ni el desgaste del tránsito. Revisá también el lote antes de instalar: como el
  diseño puede variar levemente entre tiradas de fabricación, conviene comprar toda la cantidad
  necesaria de una sola vez para evitar diferencias de tono a mitad de pared. Si el diseño tiene
  relieve, calculá bien los cortes en esquinas y zócalos, porque el relieve complica más el
  corte prolijo que una pieza lisa. Para baño en particular, priorizá diseños con buena
  resistencia a la humedad constante y a la limpieza frecuente con productos fuertes.
</p>

