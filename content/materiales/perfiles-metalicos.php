<h2>Para qué se usa</h2>
<p>
  Los perfiles metálicos son la estructura cuando la obra no es de hormigón sino metálica:
  techos, entrepisos, galpones y correas de galpón que sostienen la chapa. Entran acá el
  <strong>perfil C</strong> y el <strong>perfil U</strong>, más usados como correas y montantes
  livianos; los <strong>perfiles IPN</strong> y <strong>UPN</strong>, de mayor sección, para
  vigas y columnas de estructuras más exigentes; el <strong>ángulo de hierro</strong>, para
  refuerzos, marcos y uniones; y el <strong>caño estructural</strong> o <strong>tubo
  cuadrado</strong>, que arma columnas y pórticos livianos. La <strong>planchuela</strong>
  completa el grupo para refuerzos y piezas de unión. Cuando la estructura de techo va a llevar
  chapa, estos perfiles se combinan directamente con la <a href="/materiales/chapa-trapezoidal/">
  chapa trapezoidal</a> o la <a href="/materiales/chapa-de-zinc/">chapa de zinc</a> según el uso
  del ambiente de abajo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se venden por <strong>barra</strong>, en largos estándar, o por <strong>metro lineal</strong>
  cuando el proveedor corta a medida. Para cotizar bien hace falta indicar el <strong>tipo de
  perfil</strong> —C, U, IPN, UPN, ángulo o caño estructural—, la <strong>medida y el
  espesor</strong>, y la <strong>cantidad de barras</strong> o metros que necesitás. Si la luz a
  cubrir es de techo, contar la separación entre correas ayuda a definir el perfil correcto. La
  fabricación o el montaje de la estructura armada se cotizan aparte del material, así que si
  necesitás eso además de comprar los perfiles, conviene aclararlo desde el pedido. El precio
  final depende del tipo de perfil, la medida y el espesor, la cantidad de barras y el flete
  hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá que el tipo y el espesor de perfil coincidan con el cálculo de la estructura: usar un
  perfil más liviano que el que pide la luz a cubrir compromete el techo entero, no solo esa
  correa. Revisá que las barras vengan rectas, sin golpes que las deformen, y que el
  galvanizado o la pintura de base estén parejos, porque un perfil expuesto a la intemperie sin
  buena protección se oxida rápido en las uniones. Fijate también que la medida declarada
  coincida con la real: una diferencia de milímetros en el ala de un perfil C complica el
  atornillado en obra. La tabla siguiente resume para qué se usa cada tipo habitual.
</p>
