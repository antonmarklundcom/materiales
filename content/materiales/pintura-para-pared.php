<h2>Para qué se usa</h2>
<p>
  La <strong>pintura para pared</strong> que se usa en casi toda obra paraguaya es el
  <strong>látex</strong>: una pintura al agua, fácil de aplicar con rodillo y pincel, que se
  limpia con agua y seca rápido. En el mostrador también se la pide como <strong>pintura
  látex</strong> o <strong>pintura acrílica</strong>, y en la práctica se habla de lo mismo:
  la mayoría de los látex para pared son acrílicos. Lo que sí cambia es dónde va. El
  <strong>látex interior</strong> es para dormitorios, livings, pasillos y cielorrasos; el
  <strong>látex exterior</strong> está formulado para frentes, medianeras y muros que reciben
  sol directo, lluvia y lavado, y por eso también se lo conoce como pintura para frente. Se
  aplica sobre revoque fino, yeso, <a href="/materiales/placa-de-yeso/">placas de yeso</a> ya masilladas o sobre una pintura anterior
  en buen estado. Donde no va es sobre una pared con humedad o salitre: ahí la mancha vuelve, y
  lo que corresponde es tratar primero el problema con
  <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>lata o balde</strong>, en los litrajes que ofrece cada producto. La
  cantidad sale de los metros cuadrados a pintar por la cantidad de manos, dividido por el
  rendimiento que figura en el envase; como una pared de revoque nuevo absorbe más que una ya
  pintada, conviene calcular con margen. Para pedir bien, pasá los m² de pared de cada
  ambiente, si es interior o exterior, la terminación que buscás —mate o satinada— y el color,
  o al menos si es blanco o un color preparado. Pedí en el mismo pedido el sellador, los
  rodillos, los pinceles, la lija y la cinta de enmascarar: son lo que más se olvida. El precio
  depende del tipo de látex, la terminación, el litraje del envase, la cantidad total, si el
  color se prepara a pedido y el flete hasta tu zona.
</p>
<p>
  Un ejemplo de cómo sacar los m²: un living de 4 × 5 m con 2,70 m de alto tiene
  (4 + 5) × 2 = 18 m de perímetro, y 18 × 2,70 = 48,6 m² de pared. Si las aberturas suman
  5,6 m², quedan 43 m² de látex interior; el cielorraso, 4 × 5 = 20 m², va aparte si lo pintás
  con otra terminación. Un frente se mide igual, pero se pide en otra línea, porque lleva látex
  exterior. Con esos m² y las manos y el rendimiento que figuran en el envase del producto que
  elijas, el proveedor te dice cuántas latas o baldes.
</p>

<h2>Qué mirar antes de comprar</h2>
<table>
  <thead>
    <tr>
      <th>Terminación</th>
      <th>Dónde conviene</th>
    </tr>
  </thead>
  <tbody>
    <tr>
      <td>Mate</td>
      <td>Cielorrasos, dormitorios y paredes con imperfecciones que no querés marcar</td>
    </tr>
    <tr>
      <td>Satinada</td>
      <td>Pasillos, cocinas y cuartos de chicos, donde la pared se toca y se lava</td>
    </tr>
    <tr>
      <td>Exterior</td>
      <td>Frentes, medianeras y muros expuestos a sol y lluvia</td>
    </tr>
  </tbody>
</table>
<p>
  Confirmá que el producto sea para el lado de la pared que vas a pintar: un látex interior en
  un frente se lava y se entiza con la primera temporada de lluvias. Revisá la preparación
  antes que la pintura: una pared con polvo, revoque flojo o pintura a la cal vieja necesita
  <a href="/materiales/sellador-para-pared/">sellador para pared</a> antes del látex, o la
  pintura nueva se despega con la vieja. Si vas a preparar un color, pedí todo el color de una
  vez, porque dos tandas preparadas en días distintos pueden no quedar iguales. Y respetá el
  secado entre manos que indica el envase: apurarlo es la causa más común de una pared
  manchada.
</p>

