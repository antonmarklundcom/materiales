<h2>Para qué se usa</h2>
<p>
  El ladrillo común —muchos lo conocen como <strong>ladrillo macizo</strong>,
  <strong>ladrillo de campo</strong> o <strong>ladrillo colorado</strong>— es el que va en la
  mampostería de todos los días: paredes portantes, muros divisorios, cerramientos que después
  se van a revocar. Es el material más usado en obra en Paraguay porque rinde bien en resistencia
  y se adapta a cualquier tipo de pared, desde una vivienda de un piso hasta un muro perimetral.
  Se usa también en tabiques internos donde no hace falta un ladrillo liviano, y en fundaciones
  de poca altura cuando la obra no lleva bloque ni piedra. Si en cambio buscás algo más liviano
  para un tabique divisorio, el <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a> suele
  convenir más; y si el ladrillo va a quedar a la vista sin revoque, ahí entra el
  <a href="/materiales/ladrillo-prensado/">ladrillo prensado</a>, no el común.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>millar</strong>, y ese es el dato que primero te va a pedir cualquier
  proveedor: cuántos millares necesitás según el metro cuadrado de pared de tu obra, calculando
  el espesor del muro y el tipo de aparejo que vas a usar. Conviene fijarte antes si el
  proveedor cotiza el millar puesto en obra o retirado en depósito, porque el flete se cotiza
  aparte y cambia bastante el total. El precio final depende del volumen que pidas, de la
  distancia hasta tu zona y de si la entrega es en un solo viaje o en varias tandas a medida que
  avanza la obra. Si tu obra también necesita cemento o cal para asentar y revocar, pedilo en
  la misma consulta para ordenar mejor el flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que el ladrillo esté bien cocido y sin fisuras: uno mal cocido suena "hueco" al
  golpearlo y se desarma con el tiempo. Revisá que el color sea parejo entre lotes, porque una
  cocción despareja da ladrillos de distinta dureza dentro del mismo pedido. Un error común es
  pedir por metro cuadrado sin contar las juntas de mortero, lo que después deja faltante a mitad
  de pared. Como referencia, estas son las medidas típicas del ladrillo común de obra:
</p>
<table>
  <thead>
    <tr><th>Medida aproximada (cm)</th><th>Uso típico</th></tr>
  </thead>
  <tbody>
    <tr><td>5,5 × 11 × 22</td><td>Pared simple de un pie, tabiques y muros livianos</td></tr>
    <tr><td>6 × 12 × 25</td><td>Pared de mampostería estándar en vivienda</td></tr>
    <tr><td>7 × 14 × 28</td><td>Muros de mayor espesor y cerramientos exteriores</td></tr>
  </tbody>
</table>
<p>
  La medida exacta varía según la olería, así que siempre conviene confirmarla antes de calcular
  cuántos entran por metro cuadrado de tu diseño.
</p>

