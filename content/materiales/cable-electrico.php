<h2>Para qué se usa</h2>
<p>
  El <strong>cable eléctrico</strong> es lo que lleva la corriente desde el tablero hasta cada
  tomacorriente, luz, ducha, bomba o artefacto de la casa. Hay muchos <strong>tipos de cables
  eléctricos</strong> y se piden casi siempre por <strong>sección</strong>, no por el nombre:
  el <strong>cable de 4 mm</strong>, el <strong>cable de 6 mm</strong> o el <strong>cable de 10
  mm</strong>, según el circuito. Para artefactos livianos, lámparas y extensiones se usa el
  <strong>cable cordón 2x1</strong> (o <strong>cable TPR 2x1</strong>); para equipos que
  consumen más —una <a href="/materiales/ducha-electrica/">ducha eléctrica</a>, una
  <a href="/materiales/bomba-de-agua/">bomba de agua</a>— hace falta una sección mayor. El
  <strong>cable de alimentación</strong> es el que lleva la energía hasta el tablero o hasta un
  equipo, el <strong>cable trifásico</strong> es para instalaciones con alimentación trifásica y
  el <strong>cable preensamblado</strong> es el que se usa en la bajada aérea desde la red. El
  <strong>alambre eléctrico</strong> también se pide, y conviene aclarar al mostrador si es
  para una instalación fija o para un uso puntual. El <strong>prolongador eléctrico</strong> es
  un producto aparte: es un cable ya armado con ficha y tomas, para uso móvil.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende <strong>por metro</strong> o en <strong>rollo de 100 metros</strong>, y la sección es
  el dato que más pesa: pedí siempre el largo y la sección, no solamente "cable". Para que el
  proveedor te cotice, pasá la sección, los metros que necesitás (o la cantidad de rollos), si
  es para interior o exterior, si lo vas a pasar por
  <a href="/materiales/cano-conduit/">caño conduit</a> y el tipo de cable. Si el cálculo de
  metros te sale justo, agregá un margen para las curvas y las llegadas al
  <a href="/materiales/tablero-electrico/">tablero eléctrico</a>. El flete se cotiza aparte. El
  precio cambia con la sección, el tipo de cable, la cantidad de metros o rollos y el momento
  en que pidas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  La sección del cable no se elige a ojo: depende de lo que va a alimentar y de la distancia, y
  ahí hay seguridad en juego. <strong>Confirmá la sección con tu electricista</strong> antes de
  pedir, porque un cable de menor sección que la necesaria puede calentarse, y ahí hay riesgo
  para la instalación. Fijate que el cable esté claramente identificado con su sección y que la aislación
  esté pareja, sin cortes ni deformaciones, y evitá los cables sin identificación. Pedí
  el cable del color que corresponde a cada función (fase, neutro, tierra) y comprá todos los
  tramos de un mismo circuito del mismo tipo. La instalación misma —empalmes, protecciones y
  conexión al tablero— tiene que hacerla un profesional matriculado, y los metros de un
  cómputo grande los podés ordenar con la guía
  <a href="/guias/como-hacer-un-computo-metrico/">cómo hacer un cómputo métrico</a>.
</p>
