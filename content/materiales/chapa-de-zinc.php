<p>
  Además del calibre, revisá que el <strong>galvanizado</strong> esté parejo en toda la chapa
  —sin manchas ni zonas opacas, señal de mala protección contra el óxido— y que las chapas
  vengan sin abolladuras ni bordes doblados, porque eso complica el solape entre chapas.
  Confirmá también el ancho útil real (descontando el solape) antes de calcular cuántas chapas
  necesitás, para no quedarte corto en obra.
</p>

