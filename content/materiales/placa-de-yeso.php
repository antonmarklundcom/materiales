<h2>Para qué se usa</h2>
<p>
  La placa de yeso —lo que todo el mundo pide como <strong>durlock</strong>— arma tabiques
  interiores y <strong>cielorraso durlock</strong> sin la humedad de obra ni los tiempos de
  fragüe del ladrillo revocado: se atornilla sobre una estructura de perfiles y en un par de
  días queda lista para masillar y pintar. Como <strong>placas de yeso</strong> genéricas hay
  más de una variante: la común para ambientes secos, la resistente a la humedad (la placa
  verde) para baños y cocinas, y la resistente al fuego (la placa rosa) para donde el
  reglamento la exige, como cajas de escalera o medianeras. El <strong>techo durlock</strong>
  y el tabique divisorio son los usos más pedidos, pero también se arman nichos, cielorrasos
  con desniveles y revestimientos de columnas. La <strong>placa de roca de yeso</strong> no
  reemplaza a la mampostería que soporta peso: es un cerramiento liviano, no un muro de carga.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>placa</strong>, en medidas estándar de 1,20 m de ancho por distintos
  largos. Para pedir bien pasá los <strong>metros cuadrados</strong> de tabique o de cielorraso
  que vas a cubrir, si el destino es una zona húmeda (baño, cocina, lavadero) o si hay
  exigencia de resistencia al fuego, porque de eso depende qué placa corresponde y no todas
  cuestan igual. Con esos datos el proveedor calcula también los <strong>perfiles</strong>,
  la tornillería y la cantidad de placas con el desperdicio típico de corte. El espesor de
  9,5 o 12,5 mm también entra en la cuenta: a mayor espesor, mejor comportamiento acústico y
  mayor resistencia al impacto, pero también más peso para la estructura. El precio final varía
  según la variante de placa, la cantidad de m², el espesor y el flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá que la placa sea la correcta para el destino: la verde en zonas con humedad
  constante y la rosa donde se pide resistencia al fuego, porque usar la común ahí compromete
  la durabilidad o el cumplimiento normativo. Revisá que los bordes vengan sin golpes ni
  aplastamientos, algo común si la placa viajó mal apilada, porque una placa dañada en el borde
  se nota después de masillada. Fijate también en el espesor que estás llevando y que coincida
  con lo que calculaste para la separación de perfiles: una placa fina sobre una estructura
  pensada para otro espesor puede pandear con el tiempo. Y preguntá si el proveedor incluye en
  la cotización la masilla y la cinta de juntas, porque sin eso la placa sola no queda con
  terminación lista para pintar.
</p>

