<h2>Para qué se usa</h2>
<p>
  La <strong>pintura antihumedad</strong> —también pedida como <strong>pintura para
  humedad</strong> o <strong>pintura antisalitre</strong>— se aplica sobre pared interior o
  exterior con manchas de humedad, salitre o revoque que empieza a levantarse. Trabaja en la
  superficie: sella y frena el paso de la humedad hacia el ambiente, pero no resuelve el
  origen del problema. Si la humedad sube desde el cimiento por capilaridad —lo que se conoce
  como humedad de cimiento o salitre en la base de la pared—, la pintura ayuda a convivir con
  el problema mientras el origen sigue ahí; ese origen se corta desde la capa aisladora, con
  <a href="/materiales/hidrofugo/">hidrófugo</a> en la mezcla, no desde la pintura. Si en
  cambio el revoque queda húmedo por una filtración que viene del techo, el punto a tratar es
  la cubierta, no la pared.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>balde</strong>, por litro, y hay productos distintos según sea para
  interior o para exterior: no son intercambiables, así que conviene aclarar de qué lado de la
  pared vas a pintar antes de pedir. Para calcular cuánto necesitás, pasá los metros cuadrados
  a tratar y confirmá el rendimiento por mano que declara el fabricante, porque el revoque con
  salitre suele absorber más que una pared en buen estado. El precio final depende del
  producto, del litraje del balde, del rendimiento por mano y de los m² a cubrir, y conviene
  pedirlo junto con cualquier reparación de revoque que haga falta antes de pintar.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Aplicá siempre sobre pared seca, sin revoque flojo ni pintura descascarada: si está húmeda al
  momento de aplicar, la película nueva se levanta igual que la anterior. Confirmá si el
  producto es para interior o exterior antes de comprar, porque usar el que no corresponde
  arruina el trabajo aunque la aplicación esté bien hecha. Si la mancha vuelve al poco tiempo
  después de pintar, el problema no es la pintura sino el origen de la humedad, y ahí conviene
  revisar la capa aisladora del cimiento con
  <a href="/materiales/hidrofugo/">hidrófugo</a> antes de repetir el trabajo de pintura.
</p>

