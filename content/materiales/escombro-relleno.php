<h2>Para qué se usa</h2>
<p>
  El escombro para relleno —también llamado simplemente <strong>escombro</strong>,
  <strong>cascote</strong> o <strong>material de relleno</strong>— es el que se usa para
  ganar cota en un terreno bajo, tapar pozos o rellenar zanjas donde no hace falta la
  compactación fina que exige una base bajo contrapiso. Está compuesto por restos de
  demolición, ladrillo roto, hormigón partido y material similar, lo que lo hace más económico
  que un árido nuevo para tareas donde el objetivo es simplemente ocupar volumen. Se usa mucho
  en terrenos con desniveles grandes, en la nivelación previa a un patio o vereda, y como base
  para caminos internos de tránsito liviano dentro de la obra. Si el relleno va a quedar debajo
  de una construcción o necesita compactar de forma pareja para soportar peso, ahí conviene la
  <a href="/materiales/tierra-gorda/">tierra colorada</a> en lugar de escombro.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cúbico</strong> o por <strong>camionada</strong>. Para pedirlo,
  el proveedor necesita la <strong>cantidad</strong> aproximada en m³ según el volumen a
  rellenar, y la <strong>zona</strong> de entrega para calcular el flete y el acceso del
  camión al terreno. El precio depende del volumen pedido, de la distancia de traslado y de la
  disponibilidad del material en ese momento, así que conviene tener el cálculo del volumen
  antes de pedir presupuesto. Si además necesitás terminar el relleno con una capa de
  <a href="/materiales/arena-gorda/">arena</a> o <a href="/materiales/ripio/">ripio</a> encima,
  pedilo en la misma consulta para ahorrar en flete.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Pedí que el escombro sea <strong>escombro limpio</strong>: sin bolsas de basura, restos
  orgánicos ni materiales que se descompongan con el tiempo, porque eso genera huecos y
  hundimientos en el relleno más adelante. Fijate también en el tamaño de los trozos —pedazos
  demasiado grandes dejan huecos difíciles de compactar entre sí—. Un error común es usar
  escombro para rellenar una zona que después va a llevar una construcción encima: para esos
  casos conviene la tierra colorada, que compacta de forma más pareja. Si el relleno queda a
  la vista o cerca de la superficie, conviene tapar el escombro con una capa de tierra o arena
  para una terminación más prolija.
</p>

