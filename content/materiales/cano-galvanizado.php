<h2>Para qué se usa</h2>
<p>
  El caño galvanizado es un tubo de hierro con una capa de zinc que lo protege de la
  oxidación, por eso se elige donde va a quedar a la intemperie. El uso más conocido en Paraguay
  es el <strong>caño galvanizado para pilar de luz</strong>, el mástil donde se apoya el
  medidor, y se pide también en versión para <strong>pilar de luz trifásico</strong>. También
  se usa en estructuras livianas, barandas, parantes de cerco y marcos. El <strong>caño
  redondo</strong> y el <strong>caño galvanizado de 2 pulgadas</strong> se piden por medida y espesor, sin
  rodeos. Si lo que armás es una estructura más pesada, mirá los
  <a href="/materiales/perfiles-metalicos/">perfiles metálicos</a>, y si es una puerta o un
  cerramiento, los <a href="/materiales/portones-y-rejas/">portones y rejas</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>tira</strong> o por <strong>metro</strong>, cuando el proveedor corta a
  medida. Para cotizar necesita el diámetro, el espesor de pared, el largo de tira que
  necesitás y la cantidad. Aclaralo si es para pilar de luz, porque el proveedor puede
  recomendarte qué medida y qué largo piden en ese caso. Los accesorios, como codos, sombreretes
  y tapas, se cotizan aparte, igual que el flete. El precio cambia con el diámetro, el espesor,
  la cantidad de tiras y el tipo de terminación del galvanizado.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Preguntá si el galvanizado es en caliente o si el caño viene solo pintado, porque la
  protección no es la misma a la intemperie. Revisá que las tiras vengan rectas, sin golpes que
  las deformen, y que el espesor de pared sea el que pediste; un caño más fino de lo
  necesario es el error más común en barandas y pilares. Si va a ser pilar de luz, las medidas
  y la instalación del medidor las confirmás con tu electricista, y el
  <a href="/materiales/tablero-electrico/">tablero eléctrico</a> y el
  <a href="/materiales/cable-electrico/">cable eléctrico</a> se piden aparte. Para estructuras
  con cargas, la medida la define quien calcula la obra. La tabla resume los casos
  habituales.
</p>
