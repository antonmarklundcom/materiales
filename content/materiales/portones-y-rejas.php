<h2>Para qué se usa</h2>
<p>
  <strong>Portones y rejas</strong> son trabajo de herrería para el cerramiento exterior: el
  portón de hierro en la entrada vehicular, corredizo o basculante, y las rejas para ventanas y
  frentes que buscan seguridad sin tapar del todo la vista. Se piden de muchas formas según la
  zona y el uso —portón corredizo, portón basculante, rejas de seguridad, simplemente
  "herrería"— pero en todos los casos se trata de piezas armadas a medida sobre el vano o el
  frente real, no productos de catálogo con medidas fijas. Cuando lo que hace falta es una puerta
  metálica para un acceso, no un portón ni una reja, la opción es
  <a href="/materiales/puertas-de-chapa/">puertas de chapa</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza como <strong>trabajo a medida, por unidad o por metro cuadrado</strong> según el
  taller. Lo que necesita el herrero para armar un presupuesto es la <strong>medida real del
  vano o del frente</strong> tomada en obra, el <strong>tipo</strong> —corredizo, basculante,
  batiente, reja fija— y una idea del diseño: una foto del frente suele decir más que cualquier
  descripción escrita. También conviene aclarar la terminación que buscás, si es fondo antióxido
  nada más o pintura final. El precio final depende del diseño elegido, del perfil y el espesor
  del hierro, de la superficie total a cubrir y de si el trabajo incluye colocación y anclaje.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Tomá las <strong>medidas en obra</strong>, no del plano: un vano real casi siempre difiere un
  poco de lo dibujado, y en herrería ese margen se nota. Definí el <strong>tipo de
  apertura</strong> —corredizo, basculante o batiente— pensando en el espacio disponible para el
  recorrido de la hoja. Confirmá si el presupuesto incluye la <strong>colocación y el
  anclaje</strong>, porque en herrería suele venir junto pero conviene que quede aclarado por
  escrito, igual que la terminación —fondo antióxido o pintura—. Si más adelante pensás
  motorizar el portón, consultalo desde el principio: la automatización es otro rubro aparte y
  no todos los talleres la ofrecen.
</p>

