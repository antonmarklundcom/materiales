<h2>Para qué se usa</h2>
<p>
  El <strong>barniz para madera</strong> protege la madera de la humedad, el sol y el desgaste
  sin taparla: deja una película transparente o levemente teñida a través de la cual se sigue
  viendo la veta. Es lo que se usa en <a href="/materiales/puertas-de-madera/">puertas de
  madera</a>, marcos y ventanas, en el <a href="/materiales/machimbre/">machimbre</a> de un
  cielorraso, en pérgolas, quinchos, decks y muebles. Mucha gente lo busca como
  <strong>pintura para madera</strong>, y conviene distinguir: si querés conservar el aspecto
  natural de la madera, lo que buscás es un barniz; si querés cubrirla con un color opaco, lo
  que corresponde es un esmalte. Dentro de los <strong>barnices</strong> hay versiones para
  interior, para exterior con filtro solar, y el llamado <strong>barniz marino</strong>, más
  resistente al agua y a la intemperie, que se elige para piezas muy expuestas. También se
  consiguen barnices con color —el <strong>barniz color cedro</strong> es de los más pedidos— y
  <strong>protectores para madera</strong> tipo impregnante, que penetran en vez de formar
  película y se renuevan con más facilidad.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>lata</strong>, en los litrajes de cada producto, y el rendimiento
  figura en el envase: cambia con la especie de madera, con cuánto absorbe y con la cantidad
  de manos. Una madera nueva y porosa toma más en la primera mano que una ya barnizada. Para
  pedir bien, contá qué vas a barnizar —puertas, machimbre, muebles, una pérgola—, cuántas
  piezas o cuántos m² son, si están adentro o afuera y si querés un acabado transparente o con
  color, brillante o satinado. Sumá al pedido la lija de distintos granos, el diluyente que
  indique el envase y pinceles de buena calidad, porque un pincel que suelta pelos arruina la
  terminación. El precio depende del tipo de barniz, del color, del litraje, de la cantidad
  total y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí por el lugar donde va la pieza: un barniz de interior en una puerta que da a la calle
  se agrieta y se pela con el sol, y después hay que lijar todo para volver a empezar. Si la
  madera ya tiene barniz viejo, preguntá si el producto nuevo es compatible o si hay que
  removerlo antes. Probá el color en un rincón que no se vea, porque el mismo tono queda
  distinto sobre pino, cedro o eucalipto. Lijá entre manos con grano fino para que la
  terminación quede lisa, y aplicá sobre madera seca y sin polvo: la humedad atrapada debajo
  del barniz es la que después forma manchas blancas.
</p>
