<h2>Para qué se usa</h2>
<p>
  Los listones son piezas de escuadría chica que se usan como auxiliares en distintos puntos
  de la obra: de <strong>clavadera</strong> bajo el <a href="/materiales/machimbre/">machimbre</a>
  de un cielorraso, como <strong>alfajía</strong> en marcos y bastidores, o como refuerzo en
  trabajos de carpintería de obra que no requieren la sección de un
  <a href="/materiales/tirantes/">tirante</a>. También se los pide como <strong>varilla de
  madera</strong> cuando la sección es más fina, para molduras o terminaciones menores. Su rol
  siempre es secundario respecto a la estructura principal, pero sin listones bien elegidos
  esa estructura no queda firme donde tiene que apoyar o sujetarse.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se venden por <strong>pieza o por metro lineal</strong>. Para pedir bien necesitás la
  <strong>escuadría</strong>, el <strong>largo</strong> de cada pieza y la
  <strong>cantidad</strong> total, igual que con los tirantes pero en secciones más chicas.
  Conviene aclarar si los vas a usar a la vista o tapados, porque de eso depende si necesitás
  la versión cepillada o alcanza con la que viene en bruto. El precio depende de la escuadría,
  el largo, el tipo de madera y la cantidad de piezas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Definí primero si necesitás listón cepillado o en bruto: para clavadera oculta bajo
  machimbre alcanza el bruto, pero para un marco o una terminación a la vista conviene el
  cepillado, que sale un poco más caro pero evita lijar en obra. Revisá que la escuadría sea
  pareja entre piezas, sobre todo si vas a usarlos como clavadera, porque una diferencia de
  pocos milímetros entre listones se nota en la planitud del machimbre que apoya encima.
  Calculá la cantidad con margen para descartes por nudos o torceduras, algo más frecuente en
  secciones chicas que en piezas de mayor escuadría. Si vas a usar el listón como junquillo
  para sujetar un vidrio o cerrar un marco, fijate también que el largo de cada pieza permita
  cortar sin desperdicio los tramos que necesitás, porque en secciones finas el sobrante no
  siempre sirve para otra cosa.
</p>

