<h2>Para qué se usa</h2>
<p>
  La <strong>puerta placa</strong> —también conocida como puerta de placa o puerta interior— es
  la que resuelve dormitorios, baños, cocinas y cualquier vano de interior donde no hace falta
  aguantar intemperie: hoja hueca, liviana, con un núcleo de panal o de listones que la hace
  rápida de colocar y fácil de mover. Se la busca mucho también como puerta placa de madera,
  porque el terminado suele ser un enchapado que imita a la madera maciza sin pesar ni costar lo
  mismo. Lo que no hace es aguantar sol, lluvia ni un golpe fuerte, así que para la entrada de la
  casa no sirve: ahí va una <a href="/materiales/puertas-de-madera/">puerta de madera</a> maciza
  o, si buscás algo más resistente y menos costoso, una
  <a href="/materiales/puertas-de-chapa/">puerta de chapa</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad</strong>, hoja sola o el conjunto con marco, según el proveedor.
  Como es un producto que se ajusta al vano de cada tabique, lo que necesita el fabricante para
  darte un número es el <strong>ancho y el alto real del vano</strong> tomados en obra, el
  <strong>espesor de la pared</strong> donde va a apoyar el marco, y si la apertura es izquierda
  o derecha. También conviene aclarar si el marco va a ser de madera o de chapa —depende del tipo
  de tabique— y qué terminación buscás, porque el enchapado cambia según el proveedor. El precio
  final varía según si pedís sólo la hoja o el conjunto completo con marco y herrajes, la
  terminación elegida y la cantidad de puertas del pedido; por eso no hay una cifra fija que
  sirva para toda obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá si el precio incluye <strong>marco, bisagras y cerradura</strong> o si eso se cotiza
  aparte: es la diferencia más común entre dos presupuestos que a simple vista parecen
  comparables. Fijate también en el grosor de la hoja y en el tipo de núcleo, porque una placa
  demasiado liviana se nota al cerrarla y transmite más ruido entre ambientes. Si el marco metálico
  va sobre un tabique de placa de yeso, preguntá cómo se fija —el anclaje no es el mismo que sobre
  mampostería— y pedí que te confirmen el sentido de apertura antes de fabricar, porque una vez
  hecha la puerta no se puede invertir sin cambiar el marco.
</p>

