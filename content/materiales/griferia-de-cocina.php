<h2>Para qué se usa</h2>
<p>
  La <strong>grifería de cocina</strong> lleva el agua al punto donde lavás alimentos,
  utensilios y vajilla. La canilla para pileta tiene que dejar espacio para trabajar y
  dirigir el chorro dentro de la bacha, sin quedar tan cerca del borde que resulte incómoda.
  Una canilla de cocina puede montarse en la pared, sobre la mesada o en la propia pileta,
  según cómo esté preparada la instalación. El <strong>monocomando de cocina</strong> regula
  el caudal y mezcla agua fría y caliente desde el mismo mando; el calentamiento se resuelve
  en otro equipo de la vivienda. Para renovar sin cambiar la mesada, conviene partir de las
  perforaciones y tomas existentes. Para una cocina nueva, la pileta y la grifería se definen
  juntas, porque el alcance del pico cambia cómo se aprovecha el espacio de lavado.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Pasá la cantidad, el tipo de montaje y las medidas
  de la pileta, de las perforaciones o de las tomas en pared, según corresponda. Aclará si
  tenés agua fría solamente o suministro de fría y caliente, y qué terminación buscás.
  Sumá tu ciudad o barrio para cotizar el flete. Pedí que detallen flexibles, juntas,
  fijaciones y cualquier adaptador necesario: pueden venir con el producto o presupuestarse
  aparte. Las llaves de paso y la colocación también deben figurar por separado si las
  necesitás. El precio cambia con el material del cuerpo, el mecanismo de cierre, la
  terminación, el diseño del pico y los accesorios. Si comparás una canilla sencilla con
  una de pico extraíble, pedí el detalle de cada conjunto para entender qué estás comprando.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Medí el espacio que deja la ventana, la pared o el mueble sobre la pileta. El pico y la
  palanca necesitan moverse sin chocar, y la base tiene que poder sujetarse al espesor del
  apoyo. Si el pico gira, confirmá que su recorrido sirva para tu pileta; si es extraíble,
  revisá con el instalador el lugar disponible debajo de la mesada para la manguera.
  Preguntá por el mecanismo de recambio y por las condiciones de presión que requiere el
  modelo. No elijas sólo por el acabado: una foto no muestra la medida de la rosca ni el
  largo de los flexibles. Pedí esos datos y comprobá que el producto recibido coincida
  con la descripción antes de instalarlo.
</p>

