<h2>Para qué se usa</h2>
<p>
  El <strong>inodoro</strong> completa el baño y se conecta al desagüe cloacal de la vivienda.
  Al equipar un baño nuevo o renovar uno existente, conviene elegirlo junto con la
  <strong>cisterna de baño</strong>, también llamada mochila o tanque de inodoro: el artefacto
  y la descarga tienen que funcionar como conjunto. Un inodoro con mochila apoyada ocupa un
  espacio distinto de una solución con depósito separado, y esa diferencia importa cuando
  la puerta, el lavatorio o la zona de ducha quedan cerca. En una renovación, el punto de
  partida es la instalación que ya existe. Elegir primero por la forma y revisar después
  la salida puede obligarte a modificar el piso o la cañería cuando sólo querías reemplazar
  el sanitario.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Pedí el conjunto de inodoro y cisterna, e indicá
  cuántos baños vas a equipar, las medidas disponibles y tu ciudad o barrio. Pasá el tipo
  de salida del desagüe y su posición respecto de la pared terminada, además de la ubicación
  de la toma de agua. Si no tenés esas medidas, pedile al instalador que las confirme antes
  de cerrar el pedido. La oferta tiene que aclarar si trae asiento, tapa, mecanismo de
  descarga, fijaciones y conexiones; lo que falte se cotiza aparte. También separá el flete
  hasta la obra y la colocación. El precio depende del modelo, la forma del conjunto, el
  sistema de descarga, la terminación y los accesorios incluidos. Compará presupuestos con
  el mismo detalle para no enfrentar un artefacto solo con otro listo para conectar.
</p>
