<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que las dimensiones permitan abrir la puerta, usar el baño y acceder al depósito
  para mantenimiento. Confirmá la compatibilidad entre la mochila y el inodoro, incluso si
  tienen un aspecto parecido: las fijaciones y la unión de descarga pueden cambiar. Preguntá
  por repuestos del mecanismo y por el asiento que corresponde a esa forma. Al recibirlo,
  mirá la superficie y los bordes para detectar golpes, fisuras o defectos visibles antes
  de colocarlo. Conservá el detalle del modelo cotizado para comprobar que el conjunto
  recibido sea el mismo. Si vas a cambiar también el piso, coordiná con quien instala la
  altura final y la conexión al desagüe; esa decisión conviene resolverla antes de asentar
  el artefacto.
</p>

