<h2>Para qué se usa</h2>
<p>
  El microcemento es un revestimiento decorativo continuo, sin juntas, que se aplica sobre una
  base ya preparada. Se pide mucho como <strong>microcemento para pisos</strong> (también como
  <strong>piso microcemento</strong>, <strong>microcemento pisos</strong> o <strong>pisos de
  microcemento</strong>) en interiores donde se busca una superficie pareja en vez de piezas con
  juntas. También se usa en las <strong>mesadas de cemento revestidas</strong> de cocina y baño, y
  en paredes de baño o cocina. Es una alternativa estética a la
  <a href="/materiales/ceramica-para-piso/">cerámica para piso</a> y al
  <a href="/materiales/porcelanato/">porcelanato</a>. Ojo: es un acabado, no una base. Si la
  base de abajo está floja, fisurada o húmeda, el microcemento no lo arregla, y para eso está el
  <a href="/materiales/cemento/">cemento</a> del contrapiso.
</p>
<p>
  Mucha gente lo confunde con el <strong>cemento alisado</strong> (también llamado
  <strong>alisados de cemento</strong> o <strong>pisos de cemento alisado</strong>). La
  diferencia está en la terminación: preguntale a quien lo aplica qué acabado vas a obtener y
  qué sistema usa.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>m²</strong> o como <strong>kit</strong>, que reúne los componentes del
  sistema. Para cotizar contá los metros cuadrados de cada superficie, si es piso, mesada o
  pared, y en qué estado está la base. Preguntá si el kit viene completo o si hay componentes que
  se piden por separado, como el sellador de terminación. También decidí desde el principio si
  vas a comprar solo el material o si querés que el proveedor te recomiende a alguien que lo
  aplique, porque la mano de obra es un trabajo aparte del material. El flete se cotiza aparte,
  y el precio cambia según los m², el sistema, la terminación y quién lo aplica.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes que el color o la textura, mirá la base: tiene que estar firme, limpia y seca, y tu
  maestro o quien dirige la obra puede confirmarlo. Pedí siempre el sistema completo de un mismo
  proveedor, sin mezclar componentes de distintos orígenes, y preguntá cuál es la terminación
  de sellado, porque de eso depende cómo se limpia y cómo resiste el uso. Si es piso de mucho
  tránsito, comparalo con una <a href="/materiales/pintura-para-piso/">pintura para piso</a> o
  una <a href="/materiales/pintura-epoxi/">pintura epoxi</a>, que cumplen otra función y a
  veces alcanzan. La tabla resume cada superficie.
</p>
