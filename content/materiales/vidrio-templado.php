<h2>Para qué se usa</h2>
<p>
  El <strong>vidrio templado</strong> —lo que acá se pide como blindex— es un vidrio de
  seguridad: resiste mucho más que el vidrio común y, si llega a romperse, se desgrana en
  pedacitos sin filo en lugar de partirse en esquirlas cortantes. Se usa en mamparas de baño,
  frentes de vidrio, puertas de vidrio, barandas y divisiones de ambiente, siempre como pieza
  terminada, ya cortada y perforada para sus herrajes. Es distinto del vidrio laminado, que en
  vez de templarse lleva una lámina interna que sostiene los pedazos si rompe, y se usa más en
  situaciones donde importa que el vidrio no se desprenda del todo, como un techo o un cerramiento
  en altura. Si lo que buscás es una ventana completa con marco, no una pieza de vidrio sola,
  la opción es <a href="/materiales/ventanas-de-aluminio/">ventanas de aluminio</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza como <strong>pieza a medida, por metro cuadrado</strong>. La particularidad del
  vidrio templado es que no se puede cortar ni perforar después de templado, así que las medidas
  se toman en obra, sobre el vano o el espacio real, no del plano. Para pedirlo necesitás el
  <strong>ancho y el alto exactos de cada pieza</strong>, el <strong>espesor</strong> que
  corresponde según el tamaño y el uso, y si va con herrajes —bisagras, tiradores, soportes— o
  sin marco. El precio depende de la medida de cada pieza, del espesor elegido, de la cantidad y
  ubicación de las perforaciones para herrajes, y de que la toma de medidas en obra es parte del
  trabajo, no un paso aparte.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Definí primero si necesitás <strong>templado o laminado</strong> según dónde va la pieza: para
  una mampara o una puerta, el templado alcanza; para algo en altura donde importa que no se
  desprenda si rompe, conviene evaluar el laminado. Confirmá el <strong>espesor</strong>
  recomendado para el tamaño de tu pieza, porque un vidrio subdimensionado para su superficie es
  un riesgo. Pedí que la toma de medidas se haga en obra antes de fabricar, ya que un vidrio
  templado con una medida mal tomada no se puede ajustar después. Y si la pieza lleva espejo o
  algún tratamiento adicional, aclaralo desde el pedido inicial.
</p>

