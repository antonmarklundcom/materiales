<h2>Para qué se usa</h2>
<p>
  El policarbonato se usa para techos donde se busca <strong>techo translúcido</strong>: dejar
  pasar luz natural sin dejar pasar agua ni perder resistencia. Se instala en galerías,
  parrilleros, estacionamientos, patios y como <strong>claraboya</strong> puntual dentro de un
  techo de chapa, para iluminar un sector sin depender de luz artificial durante el día. Hay dos
  familias bien distintas: el <strong>policarbonato alveolar</strong>, con cámaras de aire
  internas que aíslan más y pesan menos, y el <strong>policarbonato compacto</strong>, macizo,
  más resistente al impacto pero más pesado. Frente a una <a
  href="/materiales/chapa-de-zinc/">chapa</a> tradicional, el policarbonato suma luz donde la
  chapa da sombra total; frente al vidrio, es mucho más liviano y resiste mejor un granizo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>plancha o por metro cuadrado</strong>. Para pedir bien necesitás la
  <strong>superficie a cubrir</strong>, el <strong>espesor</strong> de plancha que buscás y si
  preferís alveolar o compacto, porque cada uno pide un tipo de perfil de sujeción distinto. Los
  perfiles de unión, las tapas terminales y la tornillería con sello se cotizan aparte de la
  plancha. El precio final depende del espesor, del tipo (alveolar o compacto), de la cantidad
  de m² y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El espesor es la variable que más cambia el uso final de la plancha. Como referencia general:
</p>
<table>
  <thead>
    <tr><th>Espesor</th><th>Uso típico</th></tr>
  </thead>
  <tbody>
    <tr><td>4 mm</td><td>Claraboyas chicas, cubiertas livianas sobre poca luz entre apoyos</td></tr>
    <tr><td>6 mm</td><td>Galerías y parrilleros, uso residencial general</td></tr>
    <tr><td>8 mm</td><td>Techos con mayor luz entre correas, estacionamientos</td></tr>
    <tr><td>10 mm</td><td>Cubiertas de mayor exigencia, más resistencia al impacto y granizo</td></tr>
  </tbody>
</table>
<p>
  Además del espesor, fijate en la <strong>protección UV</strong> de la cara expuesta al sol
  —viene marcada en una de las caras y tiene que ir siempre hacia arriba, porque sin esa capa
  la plancha se opaca y se vuelve quebradiza antes de tiempo— y en que la plancha no traiga
  rayas profundas ni burbujas internas. Si es alveolar, revisá que las cámaras internas no
  tengan humedad de fábrica, que después se nota como manchas por dentro.
</p>

