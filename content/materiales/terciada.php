<h2>Para qué se usa</h2>
<p>
  La terciada —lo que en obra casi siempre se pide como <strong>fenólico</strong> o
  <strong>placa de terciada</strong>, y en otros rubros como <strong>multilaminado</strong>—
  es una placa armada con capas de chapa de madera encoladas entre sí, en cruz, lo que le da
  más estabilidad que una tabla maciza del mismo espesor. En obra se usa sobre todo para
  <strong>encofrado</strong> de losas y elementos que van a quedar vistos, porque deja una
  cara lisa y continua sin las juntas de la <a href="/materiales/tabla-de-encofrado/">tabla de
  encofrado</a>. La variante <strong>fenólica</strong> lleva un tratamiento que resiste mejor
  la humedad del hormigón fresco y aguanta más reutilizaciones; la terciada común, sin ese
  tratamiento, rinde bien en trabajos de carpintería y ambientes secos, pero no en encofrado
  repetido.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>placa</strong>, en medidas estándar. Para pedir bien necesitás definir
  el <strong>espesor</strong> —según la presión del hormigón y la separación entre apoyos, si
  es para encofrado— y si buscás <strong>fenólica o común</strong>. El precio depende del
  espesor, de si es fenólica o común, de la medida de placa, de la cantidad de placas y del
  flete hasta la obra; una fenólica de buen espesor rinde más usos en encofrado, lo que compensa
  parte de esa diferencia a lo largo de la obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El espesor es la decisión central, porque determina si la placa aguanta la presión del
  hormigón sin flexar entre apoyos o si termina marcando la cara vista. Como referencia general
  de plaza:
</p>
