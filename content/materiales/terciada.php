<p>
  Además del espesor, confirmá si la placa es fenólica o común antes de cerrar el pedido —una
  terciada común expuesta a la humedad del hormigón se hincha y se despega en las capas—, y
  revisá que la cara vista no tenga golpes ni astillados si el encofrado va a quedar a la
  vista. Guardá las placas planas y protegidas del sol y la lluvia hasta el momento de usarlas,
  porque una placa alabeada rinde menos usos de los que debería.
</p>

