<h2>Para qué se usa</h2>
<p>
  El tanque de agua guarda la reserva que alimenta toda la instalación de la casa cuando falta
  presión de la red o se corta el servicio, y por eso es de los primeros materiales que se
  definen en una obra nueva. Acá casi todo el mundo pide el <strong>tanque tricapa</strong> o
  directamente lo que se conoce o pide como <strong>syopar</strong>, marca tan instalada en el
  rubro que terminó nombrando al tanque de agua en general, tenga o no ese origen. El litraje
  —lo que hace que se hable de <strong>tanque de 1000 litros</strong> o de
  <strong>tanque de agua 500 litros</strong>— sale de cuánta gente vive en la casa, de cuántos
  baños hay y de cuántas horas de reserva querés tener si se corta el suministro. Va apoyado
  sobre una base elevada, casi siempre de mampostería, para que la gravedad haga bajar el agua
  con presión pareja a toda la casa.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende <strong>por unidad y por litraje</strong>, así que lo primero que te van a pedir es
  cuántos litros necesitás. Para pedir bien conviene contar cuántas personas viven en la casa,
  cuántos baños tiene y cuánta reserva querés tener el día que falta presión de red, porque con
  esos tres datos te orientan mejor que adivinando el número. Si el tanque va a quedar al sol
  directo, preguntá por el modelo <strong>tricapa</strong> o <strong>bicapa</strong>, porque las
  capas interiores influyen en que el agua no tome temperatura ni se formen algas con la luz. La
  <strong>tapa hermética</strong> también es parte del pedido, no un accesorio aparte: sin ella
  entra tierra e insectos. El precio final depende del litraje, de la marca y de si además
  necesitás la base o flotante, así que conviene pedir todo junto en la misma consulta.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de cerrar el pedido, fijate que el tanque tenga tapa hermética de buen cierre y que el
  proveedor te confirme si es tricapa o bicapa, porque eso cambia cómo se comporta el agua
  adentro con el calor. Revisá también la <strong>base de tanque</strong>: tiene que estar bien
  nivelada y dimensionada para el peso del tanque lleno, no sólo del tanque vacío, porque mil
  litros de agua pesan una tonelada. El litraje conviene definirlo con margen y no ajustado al
  mínimo, para no quedarte corto el día que hay más gente en la casa o se corta el servicio por
  más tiempo del habitual.
</p>
