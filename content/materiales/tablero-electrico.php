<h2>Para qué se usa</h2>
<p>
  El tablero eléctrico es la caja donde llega la instalación y desde donde se reparte y se
  protege cada circuito de la casa o del local. En una vivienda se pide el
  <strong>tablero eléctrico domiciliario</strong>, que concentra las luces, los tomacorrientes y
  los equipos grandes, como la <a href="/materiales/ducha-electrica/">ducha eléctrica</a> o la
  <a href="/materiales/bomba-de-agua/">bomba de agua</a>. Cuando la conexión es de tres fases, o
  el comercio tiene motores o maquinaria, se habla de <strong>tablero trifásico</strong>. En una
  obra más grande aparece el <strong>tablero seccional</strong>, que cuelga del principal y
  reparte una parte del edificio, por ejemplo un piso o un sector. En talleres, galpones y
  fábricas se usan los <strong>tableros eléctricos industriales</strong> (también llamados
  <strong>tableros industriales</strong>), y a la intemperie, en el pilar o en un patio, el
  <strong>tablero eléctrico externo</strong>. Si buscás por rubro, todo esto está dentro de
  <a href="/materiales/electricidad/">electricidad</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>, ya armado o como caja para completar. Para cotizar, el
  proveedor necesita saber cuántos circuitos va a tener, si la instalación es monofásica o
  trifásica y si lo querés con las protecciones colocadas o solo la caja. Esos datos los define
  tu electricista a partir del proyecto, así que lo más práctico es pedirle la lista antes de
  cotizar. Los cables y los caños que llegan al tablero son otro pedido: mirá el
  <a href="/materiales/cable-electrico/">cable eléctrico</a> y el
  <a href="/materiales/cano-conduit/">caño conduit</a>. El flete se cotiza aparte, y el precio
  cambia según el tipo de tablero, la cantidad de circuitos, las protecciones incluidas y el
  lugar donde se instala.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Lo primero es que el tablero esté pensado para el lugar: uno interior no sirve para la
  intemperie. Fijate que la caja no venga golpeada ni con la pintura saltada, que la puerta
  cierre bien y que tenga lugar de sobra para sumar circuitos más adelante, porque ampliar una
  instalación es más común de lo que se piensa. La elección de las protecciones y la conexión
  son trabajo de tu electricista, y conviene que él confirme el pedido antes de que lo compres.
  La tabla resume cada tipo y qué preguntarle.
</p>
