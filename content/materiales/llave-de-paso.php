<h2>Para qué se usa</h2>
<p>
  La llave de paso es la que abre o corta el agua en un tramo de la instalación. Se usa a la
  entrada de la casa, en cada baño, en la cocina, detrás del lavatorio, en el
  <a href="/materiales/tanque-de-agua/">tanque de agua</a> y en cada ducha, para poder cortar el
  agua sin dejar toda la casa sin servicio cuando hay que arreglar una pérdida o cambiar una
  canilla. En el rubro se la pide como <strong>llaves de paso</strong>, <strong>llave de paso
  de agua</strong> o simplemente <strong>llave de agua</strong>. Hay distintas versiones:
  la <strong>llave de paso esférica</strong>, la <strong>llave de paso con campana</strong> (la
  que se pide como <strong>campana llave de paso</strong>) que se ve en la pared con un
  embellecedor, la <strong>llave de paso para ducha</strong> que va con la
  <a href="/materiales/llave-de-ducha/">llave de ducha</a>, y las de
  <strong>termofusión</strong> o <strong>fusión</strong> para cañería soldada.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Lo primero que te van a preguntar es la medida, que en
  obra se dice <strong>de 1/2</strong> (también "de media") o <strong>de 3/4</strong>, y que tiene
  que coincidir con el caño al que se conecta. También hay que decir cómo se une: por rosca o por
  termofusión, según el <a href="/materiales/cano-de-agua/">caño de agua</a> que tengas o vayas a
  instalar. Si es para pared y se va a ver, se pide con campana; si va escondida o en una
  derivación, alcanza con la común. El precio cambia con el tipo, la medida, el material de
  fabricación, la cantidad y el flete. Pedí las llaves junto con los caños y accesorios para que
  todo sea de la misma medida.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de pedir, contá cuántas llaves necesitás: una general a la entrada y una por baño, cocina
  y lavadero es un buen punto de partida, más las de ducha y las que vayan al tanque. Revisá que
  la medida sea la misma que la del caño, porque es un error muy común pedir 3/4 para un tramo de
  1/2 y viceversa. Si vas a usar <a href="/materiales/cano-de-pvc/">caño de PVC</a> o cañería de
  termofusión, preguntá qué llave es compatible con cada sistema. Para duchas y lavatorios, mirá
  también que combine con la <a href="/materiales/canilla-de-lavatorio/">canilla de lavatorio</a>
  o la llave de ducha que ya elegiste. Si hay dudas sobre cuántas llaves van y dónde, confirmalo
  con tu plomero o con quien dirige la obra.
</p>
