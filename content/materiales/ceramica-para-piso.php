<h2>Para qué se usa</h2>
<p>
  La cerámica para piso —que en la obra se pide directo como <strong>cerámico</strong>,
  <strong>piso cerámico</strong> o simplemente <strong>cerámica</strong>, y también como
  <strong>baldosa</strong> en algunas zonas— es la opción más difundida para cubrir piso
  interior en toda la casa: dormitorios, living, cocina y también
  <strong>piso para baño</strong> cuando se elige un modelo con la superficie tratada para
  zonas húmedas. Se fabrica con un cuerpo más poroso que el porcelanato y termina con una capa
  de esmalte, la <strong>cerámica esmaltada</strong>, que es la que le da el color y el brillo
  final a la pieza. Esa misma porosidad es lo que la hace más liviana y más fácil de cortar en
  obra, aunque también más sensible a golpes fuertes que una pieza de mayor dureza. Si el
  ambiente va a recibir tránsito pesado constante o mucha humedad de piso, ahí conviene mirar
  el <a href="/materiales/porcelanato/">porcelanato</a> en lugar de la cerámica.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>, siempre en <strong>caja cerrada</strong>: el
  proveedor no fracciona la caja, así que el pedido se redondea hacia arriba según cuántos m²
  entran en cada una. Para cotizar bien necesitás la superficie total a cubrir, el
  <strong>formato</strong> de la pieza (30x30, 45x45, 60x60, entre otros) y si buscás un
  esmaltado para piso o uno apto también para pared, porque no todo diseño viene en ambas
  versiones. El adhesivo y la pastina para la colocación se cotizan aparte de la cerámica, y
  conviene pedirlos juntos indicando el color de pastina que buscás. El precio final depende
  del formato elegido, del diseño o la calidad del esmalte y del volumen total en m², así que
  no hay una cifra que sirva para cualquier ambiente.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  El formato influye directo en el resultado: las piezas chicas como 30x30 disimulan mejor un
  contrapiso con pequeñas irregularidades, mientras que un 45x45 o un 60x60 da un piso más
  continuo pero exige una base más nivelada para que no se noten los desniveles entre placas.
</p>
