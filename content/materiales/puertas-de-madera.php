<h2>Para qué se usa</h2>
<p>
  La <strong>puerta de madera</strong> maciza es la puerta de entrada por excelencia: pesa,
  aísla del calor y del ruido, y envejece bien porque se puede lijar y volver a barnizar cuando
  el uso la marca. Se la pide como puerta maciza cuando hace falta distinguirla de la puerta
  placa hueca, y como puerta principal cuando va en el frente de la casa. En maderas duras bien
  trabajadas también aparece la puerta tallada, con relieves en el paño, para quien busca algo
  más que una puerta de entrada funcional. Para interiores livianos, donde no hace falta ese peso
  ni esa resistencia, conviene mirar la <a href="/materiales/puerta-placa/">puerta placa</a>, que
  sale más liviana y más rápida de colocar.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad</strong>, con o sin marco según el proveedor. Hay puertas de línea
  en medidas estándar que salen más rápido, y puertas hechas a medida que llevan su propio plazo
  de fabricación porque se trabajan sobre el <strong>ancho y el alto real del vano</strong>. Para
  pedir bien conviene indicar si el vano ya está hecho o todavía se está definiendo, la especie
  de madera que buscás —no todas aguantan igual la intemperie— y si el diseño va liso, con
  paneles o tallado. El precio depende de la especie de madera y su estado de secado, del diseño
  elegido, del marco y los herrajes, y de si el pedido incluye colocación o sólo la puerta: son
  variables que cambian bastante de un proveedor a otro.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Para una puerta de entrada, preguntá siempre la <strong>especie de madera y si está bien
  estacionada</strong>: una madera dura y bien secada aguanta el sol y la lluvia paraguaya mucho
  mejor que una blanda o mal curada, que se puede torcer o rajar con el tiempo. Fijate en el
  espesor de la hoja y en el tipo de bisagra y cerradura que trae, porque en una puerta de
  entrada eso hace a la seguridad. Confirmá si el precio incluye colocación: algunos proveedores
  la suman y otros cotizan sólo el producto, y ese dato cambia bastante la comparación entre
  presupuestos.
</p>

