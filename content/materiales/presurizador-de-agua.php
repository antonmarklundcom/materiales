<h2>Para qué se usa</h2>
<p>
  El presurizador de agua es el equipo que le da presión a la red de la casa cuando el agua
  llega floja. Pasa seguido cuando el <a href="/materiales/tanque-de-agua/">tanque de agua</a>
  está poco más alto que las duchas, cuando la cañería es larga o cuando el agua sale con
  poca fuerza en el último baño. Lo que hace es empujar el agua desde el tanque o desde el pozo
  hacia las canillas y duchas, de modo que no dependa sólo de la gravedad. En obra y en casa se
  lo pide como <strong>bomba presurizadora</strong>, <strong>motor presurizador de
  agua</strong>, <strong>bomba de presión de agua</strong>, <strong>bomba de agua con
  presurizador</strong> o <strong>presurizador para bomba de agua</strong>, según se trate del
  equipo solo o de uno que viene integrado. Se instala junto a la
  <a href="/materiales/bomba-de-agua/">bomba de agua</a> o en lugar de ella, y se conecta a la
  <a href="/materiales/cano-de-agua/">cañería de agua</a> de la casa.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>. Para cotizar bien, el proveedor necesita saber de dónde
  sale el agua (tanque elevado, cisterna o pozo), cuántos baños y artefactos hay que alimentar,
  y si el problema es falta de presión en toda la casa o sólo en un punto. Contá además cómo es
  la conexión eléctrica donde va el equipo. Quien pregunta por <strong>presurizador de agua
  precio</strong> suele olvidarse de que el precio no depende sólo del equipo: también entran
  las llaves de paso, los caños de conexión, el tablero y el flete hasta tu zona. Por eso
  conviene pedir todo en el mismo pedido y comparar propuestas completas. El precio final varía
  con el tipo de equipo, la potencia, la cantidad que lleves y el momento en que pidas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Antes de comprar un presurizador, confirmá que el problema realmente sea de presión: a veces
  hay una llave de paso a medio abrir, una cañería en mal estado o un tanque mal ubicado, y el
  equipo no lo arregla. Pedile al proveedor que te recomiende el modelo según la altura de tu
  tanque, el largo del recorrido y cuántos artefactos se usan a la vez. Fijate también que la
  conexión eléctrica del equipo sea la que tenés disponible, y que haya
  <a href="/materiales/llave-de-paso/">llaves de paso</a> a la entrada y a la salida para poder
  sacarlo sin cortar toda la casa. La instalación eléctrica y la conexión a la red de agua
  confirmalas con un electricista o un plomero.
</p>
