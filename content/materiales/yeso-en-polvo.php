<h2>Para qué se usa</h2>
<p>
  El yeso en polvo, que casi siempre se pide simplemente como <strong>yeso</strong> o
  <strong>yeso para pared</strong>, enluce paredes y cielorrasos de mampostería tradicional y
  deja una superficie lisa lista para pintar, sin la arenosidad que deja el revoque de cal y
  cemento. Se usa mucho para reparar grietas, tapar rastros de instalación eléctrica embutida y
  rematar molduras y buñas, tareas donde conviene un material que fragua rápido y no requiere
  curado con agua como el cemento. También se aplica como <strong>yeso proyectado</strong> con
  máquina en superficies grandes, cuando el enlucido a mano a fratacho llevaría demasiado
  tiempo. No es un material de exterior ni reemplaza a la placa de yeso: enluce lo que ya está
  construido, no arma tabiques ni cielorrasos suspendidos.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>bolsa</strong>. Para calcular cuántas necesitás, pasá los
  <strong>metros cuadrados</strong> de pared o cielorraso a enlucir y el <strong>espesor</strong>
  aproximado de la capa que vas a aplicar, porque un enlucido más grueso consume más bolsas por
  m². Si el uso es <strong>yeso en bolsa</strong> para trabajo manual o yeso proyectado con
  máquina también conviene aclararlo, porque cambia el rendimiento por bolsa. El precio final
  depende de la cantidad de bolsas, de si el trabajo es a mano o proyectado y del flete hasta tu
  obra, así que no hay una cifra fija que aplique a toda superficie.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá la fecha de fraccionamiento y que la bolsa esté bien cerrada, porque el yeso absorbe
  humedad del ambiente y pierde tiempo de trabajabilidad si estuvo mal guardado. Preguntá por
  el tiempo de fragüe del lote que te ofrecen: como fragua rápido, conviene preparar poca
  cantidad por vez, y un yeso de fragüe muy acelerado deja menos margen para trabajarlo parejo.
  Si el <strong>enlucido de yeso</strong> va a quedar visto antes de pintar, pedí que te
  confirmen que es apto para terminación fina y no una variante pensada solo para relleno
  grueso. Y calculá con margen: quedarte corto a mitad de una pared genera una junta de fragüe
  distinto que después se nota con la pintura.
</p>

