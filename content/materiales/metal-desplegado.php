<h2>Para qué se usa</h2>
<p>
  El <strong>metal desplegado</strong> es una chapa de acero que se corta y se estira hasta
  formar una malla de rombos. No lleva soldaduras ni alambres atados: toda la pieza es una
  sola chapa. Por eso se pide también como <strong>chapa desplegada</strong>,
  <strong>malla desplegada</strong> o <strong>malla de metal desplegado</strong>. En obra
  tiene tres usos principales. El primero, como <strong>metal desplegado para revoque</strong>:
  se fija sobre los encuentros entre ladrillo y hormigón, sobre las canaletas donde se
  embutieron caños o sobre superficies lisas, para que el grueso tenga de dónde agarrarse
  (el paso a paso está en la guía <a href="/guias/como-revocar-una-pared/">cómo revocar una
  pared</a>). El segundo, en el cielorraso armado: el metal desplegado se sujeta a una
  estructura y después se revoca por debajo. El tercero, en su versión de chapa más gruesa,
  como cerramiento: cercos, protecciones de ventanas, frentes de rejas y pisos de paso. No
  reemplaza a la <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a>, que va
  dentro del hormigón de contrapisos y losas y trabaja de otra manera.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>hoja</strong>. Para cotizar contá primero el uso —revoque, cielorraso
  o cerramiento—, porque de eso depende qué tipo te ofrecen: el liviano, de chapa fina, es el
  de revoques y cielorrasos; el pesado, de chapa más gruesa, el de cercos y protecciones.
  Después pasá los metros cuadrados a cubrir o la cantidad de hojas, y si tenés una medida
  de rombo o un espesor definido en el plano, poné esos datos tal cual. Aclará si lo querés
  galvanizado o negro: para exterior o para zonas húmedas conviene preguntar por el
  galvanizado. Los perfiles o tirantes de la estructura, los clavos, tornillos o alambre
  para fijarlo y el corte a medida se cotizan aparte, igual que el flete hasta tu zona. El
  precio depende del espesor de la chapa, del tamaño del rombo, de la medida de la hoja, del
  acabado y de la cantidad total.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Revisá que el tipo corresponda al uso: un metal desplegado liviano pensado para revoque no
  sirve como cerco, y uno pesado de cerramiento es innecesario debajo de un revoque. Pedí
  que te confirmen el espesor y el tamaño del rombo por escrito, porque dos hojas que se ven
  iguales pueden no serlo. Fijate que las hojas lleguen planas y sin óxido suelto, y que los
  bordes no estén deformados; si el material va a quedar a la intemperie sin pintar, eso
  pesa más. Para cielorrasos, calculá la superficie sumando el solape entre hojas y consultá
  con quien arma la estructura cada cuánto hay que fijarlo. Si lo que buscás es cerrar un
  terreno grande, compará también con el <a href="/materiales/tejido-de-alambre/">tejido de
  alambre</a>, que es el cerco más común para lotes y predios.
</p>

