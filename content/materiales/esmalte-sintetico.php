<h2>Para qué se usa</h2>
<p>
  El <strong>esmalte sintético</strong> —en el mostrador, casi siempre <strong>pintura
  sintética</strong> o <strong>esmalte</strong> a secas— es la pintura para metal y para
  madera que se quiere cubrir con un color. Deja una película dura, lavable y brillante o
  satinada, que aguanta el roce y la intemperie mejor que un látex. Por eso es la
  <strong>pintura para rejas</strong> y portones, para <a href="/materiales/puertas-de-chapa/">puertas
  de chapa</a> y marcos metálicos, para barandas, estructuras de hierro y columnas de galpón, y
  también para puertas, ventanas y muebles de madera que van pintados en vez de barnizados.
  Sobre hierro trabaja en equipo con el <strong>antióxido</strong>: el fondo va primero y
  frena la corrosión, y el esmalte va encima y da el color y la protección final. No es una
  pintura para pared de revoque; ahí va el látex, que respira y se limpia con agua.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>lata</strong>, en los litrajes de cada producto, y el rendimiento
  figura en el envase. Como las piezas de metal rara vez se miden en m², la forma más práctica
  de pedir es contar qué vas a pintar: cuántos metros de reja, cuántos portones y de qué
  tamaño, cuántas puertas. Aclará el color y la terminación, brillante o satinada, y si la
  pieza es nueva, ya pintada o tiene óxido. En el mismo pedido sumá el fondo antióxido o el
  fondo para madera, el aguarrás o diluyente que indique el envase, la lija o el cepillo de
  alambre para sacar el óxido suelto y los pinceles y rodillos para esmalte. El precio depende
  del color, de la terminación, del litraje, de si sumás fondo y diluyente, de la cantidad
  total y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  La durabilidad se juega en la preparación. Sobre hierro, sacá todo el óxido suelto, limpiá
  la grasa y aplicá el antióxido antes del esmalte: pintar directo sobre óxido es pintar dos
  veces. Si la pieza ya tiene esmalte viejo en buen estado, alcanza con lijar para abrir poro;
  si está descascarado, hay que sacarlo. Confirmá con qué se diluye el producto que te
  cotizan, porque no todos usan el mismo solvente, y no combines un fondo y un esmalte de
  distinto tipo sin preguntar si son compatibles. Aplicá en capas finas y respetá el secado entre
  manos que indica el envase: una mano gruesa chorrea y tarda en endurecer.
</p>
