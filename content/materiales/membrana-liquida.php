<h2>Para qué se usa</h2>
<p>
  La membrana líquida —muchos la conocen como <strong>membrana en pasta</strong> o
  <strong>impermeabilizante acrílico</strong>— se aplica con rodillo o pincel, y por eso se
  adapta a techos con muchos encuentros, bajadas, caños y detalles donde un rollo de membrana
  asfáltica no entra cómodo. También funciona como <strong>pintura impermeabilizante</strong>
  de mantenimiento sobre una superficie que ya estuvo tratada antes. Es la
  <strong>membrana líquida para techos</strong> más elegida cuando la geometría es
  complicada o cuando se busca renovar una impermeabilización existente sin levantar nada. Para
  superficies grandes y regulares, en cambio, suele salir más práctico cubrir con
  <a href="/materiales/membrana-asfaltica/">membrana asfáltica</a> en rollo de una sola pasada.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>balde</strong>, por litro o por kilo según el producto, y el rendimiento
  de cada balde depende de cuántas manos de aplicación pide el fabricante y de cuánto absorba
  la superficie donde va. Para pedir bien, pasá los metros cuadrados de techo a cubrir y
  confirmá el rendimiento declarado por mano, porque ahí es donde más varía la cantidad de
  baldes que necesitás. Si la superficie tiene fisuras, encuentros o bajadas, sumá la malla de
  refuerzo al pedido: se coloca entre manos y es la que resiste el movimiento en esos puntos.
  El precio final depende del producto, del rendimiento por mano, de los m² reales y de si
  suma o no la malla de refuerzo.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá cuántas manos de aplicación pide el producto que te ofrecen: no es lo mismo un
  sistema de dos manos que uno de tres, y eso cambia tanto el rendimiento como el tiempo de
  obra. Preguntá si necesitás <strong>malla de refuerzo</strong> en fisuras y bajadas, porque
  ahí es donde el movimiento rompe la película con el tiempo. Tené en cuenta que es un sistema
  de mantenimiento que se repasa cada cierto tiempo según la exposición al sol y la lluvia, no
  una solución que se coloca una vez y se olvida. Y si la humedad que te preocupa es de pared
  interior y no de techo, lo que corresponde es
  <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>, no membrana líquida.
</p>

