<h2>Para qué se usa</h2>
<p>
  Las <strong>puertas de chapa</strong> —puertas metálicas para quien las busca por ese nombre—
  resuelven entradas de servicio, depósitos, salas de máquinas y cualquier acceso donde importa
  más la resistencia que la estética. Se piden como puerta metálica reforzada cuando el bastidor
  y la chapa son más gruesos de lo normal, y como puerta de seguridad cuando el objetivo
  principal es dificultar una entrada forzada. Es trabajo de herrería hecho sobre el vano real,
  no un producto de catálogo con medidas fijas. Si en cambio buscás algo para el frente de la
  casa con otro criterio estético, la opción es una
  <a href="/materiales/puertas-de-madera/">puerta de madera</a>; y si lo que necesitás es cerrar
  un acceso vehicular o perimetral, ahí entrás en <a href="/materiales/portones-y-rejas/">portones y rejas</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad, según la medida del vano</strong>. Como cada puerta se fabrica a
  medida, lo que necesita el taller para dar un número es el <strong>ancho y el alto real del
  vano</strong> tomados en obra, el uso que le vas a dar —entrada, depósito, acceso de
  servicio— y si necesitás marco incluido. Contar el uso ayuda porque de ahí sale el espesor de
  chapa y el refuerzo del bastidor que recomienda el taller: una puerta de depósito no lleva el
  mismo blindaje que una de seguridad para vivienda. El precio final depende de la medida del
  vano, del espesor de la chapa y el refuerzo elegidos, de si lleva cerradura de seguridad, y de
  la terminación —con o sin pintura— que pidas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Preguntá el <strong>espesor de la chapa y cómo está armado el bastidor</strong>: cuanto más
  gruesa y más reforzado, más pesa y más aguanta, pero también sube el precio, así que conviene
  ajustarlo al uso real y no sobredimensionar. Confirmá si el marco viene incluido y si la
  cerradura se cotiza aparte, porque en herrería eso varía mucho de un taller a otro. Las puertas
  de chapa suelen entregarse con fondo antióxido nada más, así que si la querés lista para usar
  aclará desde el pedido que la necesitás pintada, porque esa terminación no siempre está
  incluida.
</p>

