<h2>Para qué se usa</h2>
<p>
  El alambre negro, también conocido como <strong>alambre dulce</strong> o
  <strong>alambre recocido</strong>, es el que se usa en obra para atar la armadura antes de
  hormigonar: une cada cruce de varillas y estribos para que la estructura quede firme mientras
  se encofra y se vuelca el hormigón. Es <strong>alambre de atar</strong> por definición, no
  alambre de cerco ni alambre estructural, y se distingue de otros tipos porque es blando y se
  dobla con la mano o con tenaza sin quebrarse. Sirve también como <strong>alambre para atar
  hierro</strong> en encofrados de madera, sujetando puntos donde el clavo no alcanza o no
  conviene. Va siempre de la mano de la <a href="/materiales/varilla-de-hierro/">varilla de
  hierro</a> y de la <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a>: casi
  ninguna obra pide armado sin pedir también alambre para atarlo.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>rollo</strong> o por <strong>kilo</strong>: en obra chica alcanza con
  rollos, para una estructura completa se pide por kilo. Para cotizar bien conviene indicar el
  número de alambre (el grosor), si lo vas a llevar por kilo o por rollo, la cantidad y tu zona
  de entrega. Una referencia práctica para calcular cuánto llevar es la cantidad de nudos que
  tiene el armado: cuanto más denso el atado —más estribos, más cruces—, más alambre se
  consume, y el proveedor puede orientarte con la proporción según el tipo de estructura. El
  precio final depende del número de alambre, de si comprás por kilo o por rollo, de la
  cantidad total y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá que lo que estás llevando es alambre recocido y no otro tipo: el alambre galvanizado
  o el alambre de fardo tienen otra rigidez y no cumplen la misma función de atado, aunque a
  simple vista se parezcan. Fijate que el rollo no tenga oxidación avanzada ni tramos
  quebradizos, porque un alambre que se corta al doblar obliga a rehacer el nudo y perder
  material. Calculá la cantidad con margen: quedarte corto en medio del atado de una losa
  complica el ritmo de obra más que sobrar unos kilos. Si vas a atar mucho volumen, preguntá
  por presentaciones en rollo más grande, que rinden mejor que varios rollos chicos.
</p>

