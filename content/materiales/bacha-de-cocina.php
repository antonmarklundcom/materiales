<h2>Para qué se usa</h2>
<p>
  La <strong>bacha de cocina</strong> —que en muchas casas se pide como <strong>pileta de
  cocina</strong> o <strong>pileta para cocina</strong>— es el lugar donde se lava la vajilla, se
  enjuagan los alimentos y se resuelve buena parte del día a día de la cocina. Se pide en plural,
  como <strong>bachas para cocina</strong>, cuando se arma la cocina completa, y se la define
  junto con la mesada porque una cosa condiciona a la otra: la
  <strong>mesada de cocina con pileta</strong> puede ser una mesada de piedra o de cemento con
  el hueco ya previsto, o una bacha que viene integrada al propio mueble. Lo más común es la
  <strong>bacha de acero inoxidable</strong> (también llamada <strong>pileta inox</strong>), que
  se apoya o se encastra en la mesada; hay quien prefiere una <strong>pileta de mármol para
  cocina</strong> o una <strong>pileta para cocina de cemento</strong>, hechas en obra o por
  encargo, y cada vez se ven más <strong>bachas de cocina modernas</strong>, de líneas rectas y
  esquinas marcadas. También se usa la bacha, más grande y profunda, como
  <strong>bacha de lavadero</strong> en la zona de servicio. Sobre la pileta va la
  <a href="/materiales/griferia-de-cocina/">grifería de cocina</a>, así que conviene decidir las
  dos cosas juntas.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>unidad</strong>, y muchas veces el desagüe y la
  <strong>sopapa para pileta de cocina</strong> se cotizan aparte o vienen según el modelo:
  preguntá qué incluye cada cotización para comparar lo mismo con lo mismo. Para que el
  proveedor te cotice bien, pasá la medida del hueco de la mesada, cuántas bachas querés (simple
  o <strong>bacha doble</strong>), si va con escurridor, de qué material tiene que ser y si ya
  tenés la grifería elegida, porque la cantidad de agujeros del borde depende de la canilla. El
  flete se cotiza aparte y depende del tamaño del pedido y de la distancia hasta tu obra. El
  precio se mueve con el material, la cantidad de bachas, si es simple o doble, el escurridor,
  los accesorios de desagüe y la terminación.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Lo primero es la medida: la bacha tiene que calzar en el hueco de la mesada, y es mejor
  medirlo con la mesada ya definida que de memoria. Revisá que el acabado del acero sea parejo,
  sin golpes ni rayaduras de fábrica, y que el fondo tenga la pendiente hacia el desagüe para
  que no quede agua estancada. Fijate qué desagüe lleva y cómo se conecta al
  <a href="/materiales/cano-de-pvc/">caño de PVC</a> del desagüe, porque una bacha con un
  desagüe incompatible te obliga a improvisar un adaptador. Prevé también la
  <a href="/materiales/llave-de-paso/">llave de paso</a> para poder cortar el agua de la cocina
  sin cerrar toda la casa, y sellá el borde de la bacha con
  <a href="/materiales/selladores-y-siliconas/">silicona</a> para que no se filtre agua bajo la
  mesada. Si en el baño o en la zona de servicio vas a sumar otra pileta, la lógica es parecida a
  la de la <a href="/materiales/canilla-de-lavatorio/">canilla de lavatorio</a>.
</p>
