<h2>Para qué se usa</h2>
<p>
  La tierra gorda —en la mayoría de las obras se pide directamente como <strong>tierra
  colorada</strong>, y a veces como <strong>tosca</strong> o <strong>tierra vegetal</strong>
  cuando se necesita para jardín— es la que se usa para nivelar terrenos, rellenar desniveles y
  preparar la base antes de un contrapiso o una vereda. Se pide también como <strong>tierra
  para relleno</strong> cuando el objetivo es simplemente ganar cota en un terreno bajo o
  parejizar un desnivel antes de empezar a construir. A diferencia de la <strong>tierra
  negra</strong> —que tiene más materia orgánica y se usa para jardinería, no para relleno
  estructural— la tierra colorada compacta mejor y es la que corresponde cuando después va a
  ir un piso, un contrapiso o una construcción encima. Si lo que tenés es material de demolición
  o sobrante de obra para rellenar sin exigencia de compactación, ahí conviene el
  <a href="/materiales/escombro-relleno/">escombro para relleno</a> en lugar de tierra.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cúbico</strong> o por <strong>camionada</strong>. Para cotizar,
  el proveedor necesita saber la <strong>cantidad</strong> aproximada en m³ (calculada según el
  área y la altura de relleno que necesitás) y la <strong>zona</strong> de entrega, porque el
  acceso a un terreno recién comprado o en construcción puede complicar la descarga del
  camión. El precio depende del volumen, de la distancia de traslado y del estado del acceso a
  la obra, así que conviene tener claro el volumen antes de pedir presupuesto. Si vas a
  compactar el relleno después, puede convenir pedir junto algo de
  <a href="/materiales/arena-gorda/">arena gorda</a> para las últimas capas.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que la tierra no tenga raíces, restos de pasto o basura mezclada, porque eso genera
  huecos al descomponerse y hace que el relleno se asiente de forma pareja con el tiempo. Un
  error común es usar tierra negra para rellenar antes de construir: al tener materia orgánica,
  se pudre y el terreno se hunde después, así que para esa tarea siempre conviene la tierra
  colorada. Preguntá también por la humedad del material, porque tierra demasiado seca es más
  difícil de compactar en capas y tierra demasiado húmeda tarda en asentar. Si el relleno es
  para una zona que después va a soportar peso (una construcción, un piso), avisá al proveedor
  para que te oriente sobre cómo compactarla en capas.
</p>

