<h2>Para qué se usa</h2>
<p>
  La teja española —conocida también como <strong>teja colonial</strong>,
  <strong>teja romana</strong> o simplemente "tejas" en muchas obras— es la teja curva
  tradicional que se ve en casas de estilo colonial y campo en todo Paraguay. Se usa en
  techos de vivienda donde se busca esa terminación clásica, en corredores y galerías, y en
  restauraciones de casas antiguas que ya tenían este tipo de cubierta. Al ser una
  <strong>teja cerámica española</strong> hecha de barro cocido, además de la estética aporta
  buena inercia térmica: el techo tarda más en calentarse durante el día. Si en cambio buscás
  una línea recta y moderna, con encastre plano en vez de la superposición curva, la
  <a href="/materiales/teja-francesa/">teja francesa</a> es la que corresponde.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad o por millar</strong>, según el volumen de la obra. Para pedir
  bien necesitás la <strong>superficie de techo a cubrir</strong> (para calcular cuántas piezas
  entran por m² según el solape) y la <strong>pendiente</strong> proyectada, porque una teja
  colonial necesita una pendiente mínima para que el agua no se filtre entre piezas. El
  tirantillo o clavaderas sobre los que se apoya la teja se cotizan aparte, igual que las
  piezas especiales de remate y limahoya. El precio final depende de la cantidad de piezas, de
  si son lisas o esmaltadas, y del flete hasta tu zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en la <strong>uniformidad de la cocción</strong>: piezas de un mismo lote deberían
  tener color y curvatura parejos, porque las diferencias se notan mucho en un techo terminado.
  Golpeá suavemente algunas piezas al recibirlas: un sonido metálico indica buena cocción,
  mientras que un sonido opaco puede señalar tejas más frágiles y porosas, que absorben
  humedad y se deterioran antes. Revisá también que no traigan fisuras finas ni descascarados
  en los bordes, porque son los puntos por donde después entra agua. Consultá la pendiente
  mínima recomendada para tu zona antes de cerrar el pedido de estructura.
</p>

