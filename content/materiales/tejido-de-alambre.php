<h2>Para qué se usa</h2>
<p>
  El tejido de alambre —el <strong>tejido romboidal</strong> o <strong>alambrado</strong> de
  toda la vida— es el cerco más usado en Paraguay para lotes, patios, predios y potreros. Se
  arma como <strong>malla para cerco</strong> tensada entre postes, y casi siempre va acompañado
  de <strong>alambre de púas</strong> en la parte superior cuando el cerco busca disuadir el
  paso, y de <strong>alambre galvanizado</strong> liso para tensores y remates. Sirve tanto para
  delimitar un terreno urbano como para un <strong>cerco perimetral</strong> rural con
  <strong>poste de alambrado</strong> de madera o de hormigón. No hay que confundirlo con la
  <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a>, que es un armado rígido
  para hormigón y no un cerco: si lo que buscás es cerrar un perímetro, el tejido es el
  material correcto; si es armar una losa o un contrapiso, no.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>rollo</strong>, con la altura y el largo ya definidos, y también por
  <strong>metro lineal</strong> cuando necesitás una cantidad puntual. Para cotizar, pasá los
  <strong>metros de perímetro</strong> a cercar y la <strong>altura</strong> que buscás, y el
  proveedor calcula cuántos rollos hacen falta. El calibre del alambre y el tipo de galvanizado
  también entran en el precio, y conviene definirlos según el uso: no es lo mismo un cerco de
  patio que uno para un predio con animales. Los <strong>postes, tensores, grampas y alambre de
  púas</strong> casi nunca vienen incluidos en el tejido y se cotizan aparte, así que conviene
  pedirlos en la misma consulta para tener el costo real del cerco terminado. El precio final
  depende de la altura del rollo, el calibre, los metros lineales totales y el flete hasta tu
  zona.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Elegí el calibre y el tipo de galvanizado según el uso real del cerco: un jardín urbano no
  exige lo mismo que un potrero con ganado, donde el tejido recibe más tensión y más roce.
  Revisá que el rollo tenga el romboide parejo en todo el largo, sin deformaciones que después
  cuesten corregir al tensar. Contá bien la cantidad de postes y su separación antes de comprar
  el tejido, porque un cerco mal apuntalado se destensa con el tiempo aunque el tejido en sí sea
  bueno. Si vas a sumar alambre de púas, verificá que la altura de poste alcance para dejar
  espacio a esa hilera superior.
</p>

