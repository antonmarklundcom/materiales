<p>
  Lo más importante es el <strong>sellado</strong>: una claraboya mal terminada filtra en la
  primera tormenta, así que preguntá qué accesorios y qué sellador lleva. En un techo de losa
  coordiná la colocación con la impermeabilización; la guía
  <a href="/guias/como-impermeabilizar-una-losa/">cómo impermeabilizar una losa</a> te ayuda a
  ordenar los pasos. Y recordá que la medida del hueco se confirma con quien dirige la obra
  antes de cortar, para no debilitar la estructura.
</p>

