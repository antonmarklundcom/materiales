<h2>Para qué se usa</h2>
<p>
  La claraboya es una abertura en el techo que deja entrar luz natural a un ambiente que, de
  otra forma, quedaría a oscuras. Se pide también como <strong>tragaluz para techo</strong> o
  como <strong>lucernario</strong>, y se usa en baños sin ventana, pasillos, cocinas, galerías y
  galpones donde el techo de chapa deja todo en sombra. Hay <strong>claraboya de chapa</strong>
  o panel translúcido, que se coloca en la misma línea que el techo, y otras de
  <strong>policarbonato</strong> o de <strong>acrílico</strong>, además de modelos
  <strong>con ventilación</strong> y la <strong>claraboya para techo de losa</strong>. Un
  <strong>techo con tragaluz</strong> bien ubicado te ahorra prender la luz durante el día, y
  una <strong>claraboya para baño</strong> además ventila si el modelo se abre. Si lo
  que buscás es cubrir una galería entera con luz, mirá directamente el
  <a href="/materiales/policarbonato/">policarbonato</a>.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>unidad o a medida</strong>. Para pedir una claraboya el proveedor
  necesita saber la <strong>medida del hueco</strong> que vas a dejar, el tipo de techo donde
  va (<a href="/materiales/chapa-trapezoidal/">chapa trapezoidal</a>, otra chapa, teja o losa) y
  si la querés fija o con apertura. Con una foto del techo y las medidas, el proveedor te dice
  si tiene un modelo estándar o si la fabrica a medida. Las piezas de fijación y el sellado
  alrededor se cotizan aparte, y son las que determinan si después gotea o no. El precio
  cambia con el material, la medida, si lleva ventilación, el tipo de techo y el flete hasta
  tu zona.
</p>

