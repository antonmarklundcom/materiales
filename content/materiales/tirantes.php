<h2>Para qué se usa</h2>
<p>
  Los tirantes —también pedidos como <strong>tirantería</strong> o <strong>viga de
  madera</strong>— son la pieza principal de la estructura del techo: apoyan sobre las
  soleras o los muros y sostienen las correas, el machimbre o la cubierta que va arriba. En
  entrepisos de madera cumplen el mismo rol, salvando la luz entre apoyos. Se piden en
  distintas escuadrías según lo que tengan que soportar: una escuadría chica alcanza para una
  galería con poca luz, mientras que un techo con luces largas o cargas mayores pide una
  escuadría mayor. También se los conoce como <strong>tirante de techo</strong> cuando el
  pedido es puntualmente para esa función, aunque el mismo tipo de pieza sirve para otras
  estructuras de obra.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>pieza o por metro lineal</strong>, según cómo trabaje cada proveedor.
  Para pedir bien necesitás la <strong>escuadría</strong> (el ancho y alto de la sección), el
  <strong>largo</strong> de cada pieza y la <strong>cantidad</strong> que vas a usar. Contá
  también la luz que tiene que cubrir cada tirante y la separación que vas a dejar entre uno y
  otro, porque de ahí sale la escuadría que realmente necesitás —no siempre la que uno
  supone a ojo alcanza. El precio depende de la escuadría, el largo, el tipo de madera y el
  tratamiento (si va a quedar expuesto conviene aclarar si viene tratado), además de la
  cantidad total de piezas y el flete hasta la obra.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Confirmá que la escuadría que te ofrecen sea la que corresponde a tu luz y a tu carga, no
  la que el proveedor tiene más disponible en el momento. Preguntá si la madera viene
  estacionada o recién aserrada: una pieza verde se tuerce y se abre al secar, y en una
  estructura de techo eso después se nota. Si el tirante va a quedar expuesto a la humedad —un
  alero, una galería sin cielorraso— pedí que te aclaren el tratamiento contra hongos e
  insectos. Revisá también que los largos coincidan con tu diseño de estructura, porque los
  empalmes en un tirante de carga no son ideales y conviene evitarlos siempre que se pueda.
</p>

