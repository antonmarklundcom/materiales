<h2>Para qué se usa</h2>
<p>
  La cal viva —muchos la conocen como <strong>cal sin apagar</strong> o <strong>cal en terrón</strong>—
  es la materia prima que se usa cuando en obra se quiere apagar la propia cal en vez de comprarla ya
  procesada. Se emplea sobre todo en obras que arman su propia mezcla de revoque tradicional o pintura a
  la cal desde cero, porque el proceso de apagado en obra da una pasta que muchos maestros mayores
  prefieren para terminaciones antiguas o restauración. También se usa en algún tratamiento de suelo para
  estabilizar terreno antes de una base, aprovechando la reacción con el agua. Es un material que exige
  manejo cuidadoso: al entrar en contacto con agua libera calor y hay que dejarla actuar en un recipiente
  aparte antes de usarla, no se mezcla directo en el muro como el cemento.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>bolsa</strong>, y para pedirla basta indicar la cantidad que necesitás según cuánta
  mezcla vas a preparar. Como es un insumo que se transforma en obra —no se aplica tal cual sale de la
  bolsa— conviene aclarar en el pedido si la vas a usar para apagar vos mismo o si en realidad buscás cal
  ya lista para aplicar, porque en ese caso lo que corresponde es la <a
  href="/materiales/cal-hidratada/">cal hidratada</a>. El precio depende de la cantidad de bolsas y del
  flete hasta tu obra, igual que con el resto de los aglomerantes de la categoría.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que la <strong>cal en piedra</strong> venga en trozos firmes y sin polvo excesivo en el fondo de
  la bolsa, señal de que no absorbió humedad antes de tiempo —una cal que ya reaccionó parcialmente con el
  aire pierde poder de apagado y rinde menos. Antes de comprar, confirmá que en tu obra vas a tener espacio
  y recipiente adecuado para <strong>cal para apagar</strong> con seguridad, lejos de donde circule gente,
  porque el proceso genera calor y salpica. Si no tenés forma de manejar ese proceso en obra, es más
  práctico pedir directamente cal ya apagada en bolsa antes que arriesgarte con la cal viva.
</p>

