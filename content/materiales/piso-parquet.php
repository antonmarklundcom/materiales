<h2>Para qué se usa</h2>
<p>
  El <strong>piso parquet</strong> es un piso de madera maciza armado con piezas chicas que
  se pegan o se fijan sobre un contrapiso nivelado y, una vez colocadas, se lijan y se
  plastifican en la misma obra. Se pide como <strong>parquet</strong>, <strong>parqué</strong>,
  <strong>piso de parquet</strong> o <strong>parquet de madera</strong>, y es la terminación
  de livings, dormitorios y pasillos en casas donde se busca un piso de madera de verdad y
  no una imitación. Como la pieza es madera en todo su espesor, cuando la superficie se gasta
  se puede volver a lijar y plastificar sin cambiar el piso. Conviene no confundirlo con el
  <a href="/materiales/piso-vinilico/">piso flotante y el vinílico</a>, que encastran o se
  pegan sobre el piso que ya está y no se pulen, ni con el
  <a href="/materiales/porcelanato/">porcelanato símil madera</a>, que da el aspecto de la
  madera con el mantenimiento de una cerámica. Esta página es la del piso de madera maciza.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>. Para cotizar pasá la superficie de cada
  ambiente, la especie de madera que te interesa y el formato de colocación que tenés en
  mente —en damero, en espina de pez, en tablas corridas—, porque el dibujo cambia el
  desperdicio por cortes. Aclará si pedís sólo la madera o también el adhesivo, la
  colocación, el lijado y el plastificado: son partidas distintas y cada proveedor puede
  armarlas de otra manera, así que pedí que la oferta las detalle una por una. El zócalo
  y el flete hasta tu zona también se cotizan aparte. El precio se mueve con la especie
  —cada madera dura tiene su dureza, su color y su disponibilidad—, con el formato y el
  espesor de la pieza, con los metros cuadrados totales y con lo que incluya el trabajo en
  obra. Dos presupuestos por metro cuadrado sólo se comparan si cubren las mismas partidas.
</p>
