<h2>Qué mirar antes de comprar</h2>
<p>
  La madera tiene que estar estacionada: una pieza que todavía tiene humedad se mueve, se
  separa o se levanta cuando termina de secar ya colocada. Preguntalo siempre y pedí que te
  aclaren el estado de secado antes de cerrar el pedido, igual que con cualquier
  <a href="/materiales/madera-dura/">madera dura</a>. El contrapiso importa tanto como la
  madera: tiene que estar firme, nivelado y seco, y si el ambiente tiene humedad que sube
  desde el piso, eso se resuelve antes de colocar. Por el mismo motivo, el parquet no es el
  piso para un baño ni para un lavadero. Pedí todas las piezas del mismo lote para que el
  color sea parejo, y sumá un margen por cortes que el proveedor o el colocador te pueden
  confirmar según el dibujo elegido. Un error común es comparar el precio de la madera sola
  contra un presupuesto que ya trae lijado y plastificado incluidos.
</p>

