<h2>Para qué se usa</h2>
<p>
  La piedra laja es el <strong>revestimiento de piedra</strong> que se usa para dar terminación
  natural a fachadas, zócalos exteriores y también paredes interiores como acento visual, algo
  que ningún cerámico ni porcelanato reproduce del todo porque cada placa sale distinta de la
  cantera. Se conoce también como <strong>piedra de revestimiento</strong> o
  <strong>piedra para fachada</strong>, y se usa mucho en <strong>muros de piedra</strong>
  exteriores, columnas y frentes de casa donde se busca textura y color natural en vez de una
  superficie lisa y uniforme. A diferencia de la piedra bruta o triturada que va en cimiento y
  hormigón, la laja se corta en placas finas pensadas específicamente para pegarse sobre una
  pared ya construida, no para estructura. Si lo que se busca es el aspecto de piedra pero con
  la uniformidad y el mantenimiento de una pieza cerámica, el
  <a href="/materiales/porcelanato/">porcelanato símil piedra</a> cubre esa necesidad mejor que
  la laja natural.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se vende por <strong>metro cuadrado</strong>. Para cotizar necesitás la superficie de pared o
  fachada a cubrir y, si la conocés, el tipo de piedra o el color que buscás, porque el tono y
  la veta varían bastante entre canteras y no siempre hay stock parejo de un mismo lote. El
  adhesivo para fijar la placa a la pared se cotiza aparte de la piedra, y como el peso de la
  laja es mayor que el de una pieza cerámica, conviene confirmar que sea un adhesivo apto para
  ese peso antes de comprar. El precio depende del tipo de piedra, del espesor de la placa, de
  la superficie total en m² y del flete, ya que la piedra pesa más que otros revestimientos y
  eso incide en el traslado.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate en el <strong>espesor</strong> de la placa, porque una laja más fina resulta más fácil
  de manipular pero exige una base bien firme para no fisurarse al fijarla, mientras que una más
  gruesa pesa más y necesita un adhesivo reforzado acorde. Revisá que las piezas tengan un
  espesor relativamente parejo entre sí, porque la irregularidad natural de la piedra es parte
  de su terminación, pero una diferencia excesiva entre placas complica la colocación pareja.
  Un error frecuente es comprar la cantidad exacta calculada sin margen: como cada placa es
  irregular, siempre se pierde más material en el corte y el ajuste que con una pieza cerámica
  de formato fijo, así que conviene pedir un poco más de lo calculado. Si la instalación es a
  la intemperie, preguntá por el tipo de piedra más resistente a la exposición constante al sol
  y la lluvia.
</p>

