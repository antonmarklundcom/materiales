<h2>Para qué se usa</h2>
<p>
  El ladrillo hueco —también pedido como <strong>ladrillo de 8</strong>,
  <strong>ladrillo de 12</strong> o <strong>ladrillo cerámico hueco</strong> según el espesor
  que necesites— se usa sobre todo en tabiques divisorios y paredes internas que no cumplen
  función estructural. Al tener perforaciones pesa menos que el ladrillo macizo, así que se
  levanta más rápido y carga menos peso sobre la losa o la fundación, algo que se agradece en
  ampliaciones o pisos superiores. También se usa en cerramientos exteriores de poca exigencia
  estructural cuando el diseño no requiere un muro portante. Si la pared va a llevar carga
  estructural real, ahí conviene el <a href="/materiales/ladrillo-comun/">ladrillo común</a> en
  lugar del hueco, porque el macizo resiste más.
</p>

<h2>Cómo se vende, cómo pedirlo y de qué depende el precio</h2>
<p>
  Se cotiza por <strong>millar</strong>, igual que el resto de los ladrillos cerámicos, y el
  dato clave para pedirlo es el espesor —8, 12 o 18— según el tipo de tabique que vas a levantar.
  Contale al proveedor el metro cuadrado de pared que necesitás cubrir y el espesor elegido para
  que calcule el millar correcto; pedir de más o de menos por no aclarar el espesor es de los
  errores más comunes en este material. El flete se cotiza aparte y depende del volumen total y
  la zona de entrega. El precio final varía según el espesor, la cantidad de millares y la
  distancia hasta tu obra, así que no hay una cifra fija que sirva para cualquier tabique.
</p>

<h2>Qué mirar antes de comprar</h2>
<p>
  Fijate que las paredes del ladrillo no estén rajadas ni con las perforaciones colapsadas,
  porque un hueco débil se rompe al clavar o al enganchar una instalación. Revisá que el espesor
  sea uniforme entre las piezas del mismo pedido, porque una mezcla de espesores complica el
  revoque parejo. Un error frecuente es usar ladrillo hueco donde hace falta resistencia
  estructural real: no es su función, y ahí corresponde el ladrillo macizo. Las medidas más
  comunes en Paraguay y su uso típico:
