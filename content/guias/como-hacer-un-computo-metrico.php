<h2>Qué es un cómputo métrico</h2>
<p>
  Un cómputo métrico es simplemente el paso de convertir un plano (o las medidas de tu obra, si
  todavía no tenés plano formal) en una lista de cantidades: cuántos metros cúbicos de hormigón,
  cuántos ladrillos, cuántas bolsas de cemento, cuántos metros cuadrados de techo. No hace falta
  ser calculista para armarlo a nivel de compra: alcanza con medir cada ambiente o cada rubro por
  separado —cimientos, paredes, techo, instalaciones, terminaciones— y anotar sus metros o metros
  cuadrados antes de salir a comprar. La idea es tener, rubro por rubro, la cantidad real que vas
  a necesitar, en vez de calcular "a ojo" en el momento en que el corralón te pregunta cuánto
  llevás.
</p>
<p>
  No tiene que ser exhaustivo desde el primer día. Podés empezar con lo que ya tenés definido —por
  ejemplo, los metros cuadrados de pared que vas a levantar con
  <a href="/materiales/ladrillo-comun/">ladrillo común</a>— y sumar rubros a medida que la obra
  avanza y se van definiendo los siguientes. Lo importante es que cada cantidad salga de una
  medida real tomada del plano o del terreno, no de un recuerdo de "la obra anterior llevó tantas
  bolsas".
</p>

<h2>Por qué conviene hacerlo antes de comprar</h2>
<p>
  Comprar sin cómputo suele terminar en uno de dos problemas: comprar de más, con materiales que
  quedan sin usar y plata inmovilizada en algo que no vas a necesitar, o comprar de menos, con la
  obra frenada a mitad de jornada esperando un segundo pedido que además suele salir más caro por
  ir en cantidades chicas y con flete aparte. Ninguno de los dos escenarios es grave si pasa una
  vez, pero se repite en cada rubro si no hay una cantidad de referencia antes de salir a
  comprar. El cómputo evita eso: te da un número por el cual pedir, y ese número lo podés ajustar
  con tu maestro mayor de obra o tu calculista según la dosificación o el criterio que estén
  usando en tu obra puntual.
</p>
<p>
  Si además el rubro que estás por comprar depende de decisiones que ya tomaste antes —qué
  espesor de pared, qué tipo de <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a>
  vas a usar en la estructura— conviene tener resuelto primero de qué depende el costo de esa
  etapa. Si todavía no lo tenés claro, es útil leer primero
  <a href="/guias/de-que-depende-el-costo-de-construir-en-paraguay/">de qué depende el costo de
  construir en Paraguay</a> para entender el panorama completo antes de entrar en el detalle de
  cada rubro.
</p>

<h2>En qué orden calcular cada rubro</h2>
<p>
  Conviene computar los rubros en el mismo orden en que vas a comprar y ejecutar la obra, porque
  así el cómputo te sirve también como agenda de compras. Primero va la
  <strong>estructura</strong>: cimientos, columnas, vigas y losas, todo lo que se resuelve con
  <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a> y hierro según lo que indique
  el calculista. Después la <strong>mampostería</strong>, con los metros cuadrados de pared que
  definen cuánto <a href="/materiales/ladrillo-comun/">ladrillo común</a> (u otro tipo de
  ladrillo o bloque, según lo que hayas elegido) vas a necesitar. Sigue la
  <strong>cubierta</strong>, con la superficie de techo a cubrir y su estructura de sostén.
  Después las <strong>instalaciones</strong> —sanitaria y eléctrica— que conviene tener
  computadas antes de cerrar paredes y contrapisos, porque ahí van los caños y cajas que después
  quedan embutidos. Por último las <strong>terminaciones</strong>: revoques, contrapisos, pisos y
  todo lo que se hace sobre la obra gruesa ya resuelta.
</p>
<p>
  Este orden no es arbitrario: es el mismo en el que se compra y se ejecuta en la mayoría de las
  obras, así que computar en ese orden te permite ir comprando por etapas sin adelantar plata en
  materiales que vas a necesitar recién dentro de varios meses, ni quedarte sin lo que sí necesitás
  ahora.
</p>

<h2>De metros a cantidades: usá las calculadoras</h2>
<p>
  Una vez que tenés los metros cuadrados o metros cúbicos de cada rubro, el paso que sigue es
  convertir esa medida en unidades de compra: bolsas, ladrillos, metros cúbicos de hormigón (si
  alguna unidad no te suena, el <a href="/guias/glosario-de-obra-paraguay/">glosario de obra</a>
  la define). Ahí
  es donde entran las calculadoras del sitio: cargá los metros cúbicos que vas a hormigonar en la
  <a href="/calculadoras/hormigon-por-m3/">calculadora de hormigón por m³</a> y los metros
  cuadrados de pared en la <a href="/calculadoras/ladrillos-por-m2/">calculadora de ladrillos por
  m²</a>, y obtenés directamente la cantidad de material sin tener que memorizar ninguna
  dosificación ni rendimiento. Fijate que estas herramientas siempre parten de un dato que vos
  cargás —el metro cuadrado o metro cúbico real de tu obra— y no de un promedio genérico, así que
  cuanto más precisa sea la medida que tomaste, más ajustado va a salir el resultado. En
  <a href="/calculadoras/">la sección de calculadoras</a> vas a encontrar el resto de las
  herramientas para ir cubriendo cada rubro a medida que avanza el cómputo.
</p>
<p>
  Con las cantidades de cada rubro ya convertidas en unidades de compra, lo que queda es pedir el
  pedido armado en el orden que corresponde a tu obra. Contanos en qué etapa estás y qué rubros ya
  tenés medidos, y te ayudamos a organizar el pedido de <a href="/materiales/cemento/">cemento</a>,
  <a href="/materiales/ladrillo-comun/">ladrillo común</a> y
  <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a> según tu cronograma.
  <a href="/cotizar/">Pedí tu cotización</a> y te respondemos con las cantidades ajustadas a tu
  obra.
</p>
