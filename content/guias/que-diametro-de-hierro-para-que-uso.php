<h2>Qué define el diámetro</h2>
<p>
  El diámetro de <a href="/materiales/varilla-de-hierro/">varilla de hierro</a> que corresponde a
  cada elemento de una estructura lo define el cálculo estructural, no una regla general que
  sirva para cualquier obra. El ingeniero o calculista determina el diámetro y la cantidad de
  varillas según la carga que va a soportar cada elemento, la luz que cubre, la resistencia del
  hormigón usado y las normas de diseño vigentes. Por eso esta guía no reemplaza ese cálculo:
  sirve para entender de forma general por qué distintos elementos de una misma obra suelen llevar
  distintos diámetros, y para saber qué información necesita el proveedor cuando vas a hacer el
  pedido.
</p>
<p>
  En términos generales, cuanto mayor es la carga que tiene que resistir un elemento estructural,
  mayor suele ser el diámetro de hierro requerido, aunque también influye la cantidad de varillas
  que se combinan y cómo se distribuyen en la sección. Un mismo diámetro puede usarse en distintos
  elementos si el cálculo así lo determina; lo que nunca conviene es elegir el diámetro "a ojo"
  copiando lo que se usó en otra construcción con cargas o luces distintas.
</p>

<h2>Columnas, vigas, losas y estribos</h2>
<p>
  En <strong>columnas</strong> y <strong>vigas</strong>, el hierro principal suele llevar
  diámetros mayores porque son los elementos que concentran las cargas verticales y los esfuerzos
  de flexión de toda la estructura. En <strong>losas</strong>, en cambio, es común usar diámetros
  menores pero distribuidos en una malla más cerrada, y ahí muchas obras recurren a
  <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a> para agilizar la colocación
  en superficies grandes, sobre todo en losas de piso o contrapisos armados. Los
  <strong>estribos</strong> —esas varillas que envuelven el hierro principal en columnas y vigas,
  formando anillos o ganchos— suelen ser de menor diámetro que el hierro longitudinal, porque su
  función es distinta: confinan el hormigón y el hierro principal, y ayudan a resistir esfuerzos
  de corte, no la carga axial o de flexión.
</p>
<p>
  La separación entre estribos también forma parte del cálculo, y suele achicarse cerca de los
  nudos —donde columna y viga se encuentran— porque ahí se concentran mayores esfuerzos durante un
  sismo o una sobrecarga. Ninguno de estos valores —diámetro, cantidad, separación— es intercambiable
  entre obras distintas: cada estructura tiene su propio cálculo según sus propias cargas y luces.
</p>
<p>
  En cimientos y zapatas también aparece hierro, generalmente en diámetros intermedios y en
  parrillas cruzadas, porque ahí la estructura transmite toda la carga del edificio al suelo. La
  cantidad de capas y el recubrimiento del hierro respecto del borde de hormigón también forman
  parte del cálculo, y varían según el tipo de suelo y la humedad de la zona.
</p>

<h2>Qué datos necesita el proveedor</h2>
<p>
  Para armar un pedido de <a href="/materiales/hierro/">hierro</a> ajustado a tu obra, lo ideal es
  llevar la planilla de hierros o el plano de armado que te haya entregado el calculista, donde
  figuran los diámetros, las longitudes y las cantidades de varillas para cada elemento. Con esa
  planilla, el proveedor puede calcular el peso total en kilos o toneladas y organizar el corte y
  doblado si esa es una opción disponible, ahorrándote tiempo en obra. Si todavía no tenés la
  planilla definitiva pero ya sabés qué elementos vas a armar primero —por ejemplo zapatas y
  columnas antes que losa— podés pedir por etapas para no acumular material esperando en el
  terreno.
</p>
