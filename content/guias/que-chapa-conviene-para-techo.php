<h2>Calor y ruido</h2>
<p>
  La primera pregunta antes de elegir chapa no es el precio, sino qué hay debajo del techo. Si
  abajo va un ambiente habitable —dormitorio, oficina, un local con gente todo el día— el calor
  que baja al mediodía y el ruido de la lluvia contra la chapa se sienten mucho más que en un
  galpón o una cochera. Para esos casos existe la <a href="/materiales/chapa-termoacustica/">chapa
  termoacústica</a>, que lleva un núcleo aislante entre dos caras metálicas y corta buena parte de
  ese calor y ese ruido, algo que ninguna chapa simple resuelve por más gruesa que sea. Si en
  cambio el ambiente de abajo es un depósito, un galpón sin uso constante o una cochera, una chapa
  sin aislación suele alcanzar y resulta bastante más económica de entrada.
</p>
<p>
  Dentro de las chapas sin núcleo aislante, la más usada sigue siendo la
  <a href="/materiales/chapa-de-zinc/">chapa de zinc</a> ondulada, un clásico que cumple bien en
  techos simples, aunque transmite calor y ruido de lluvia sin filtro. La
  <a href="/materiales/chapa-trapezoidal/">chapa trapezoidal</a>, con su perfil de ondas más
  altas y rectas, da mayor rigidez estructural y permite salvar luces más grandes entre apoyos, lo
  que la hace común en galpones y techos de mayor superficie.
</p>

<h2>Luz a cubrir y estructura</h2>
<p>
  La luz a cubrir —la distancia entre correas o entre apoyos de la estructura— es otro factor
  clave para elegir el perfil de chapa. Cuanto mayor sea esa distancia, más rígido tiene que ser
  el perfil para no flexar con el peso propio, el agua acumulada o el viento, y ahí la chapa
  trapezoidal suele rendir mejor que la ondulada tradicional porque su forma le da más resistencia
  a flexión con el mismo espesor de metal. La chapa termoacústica, al ser más pesada que una chapa
  simple por el núcleo que lleva, exige revisar que la estructura de apoyo —correas y tirantería—
  esté dimensionada para ese peso adicional, algo que conviene chequear con quien calculó la
  estructura antes de definir qué chapa comprar.
</p>
<p>
  La pendiente del techo también entra en la ecuación: cada perfil de chapa tiene una pendiente
  mínima recomendada para que el agua escurra bien y no se filtre por las juntas o los
  solapamientos. Antes de cerrar la compra conviene confirmar con el proveedor cuál es la
  pendiente mínima que soporta el perfil elegido para el ancho de chapa que vas a usar, porque
  eso varía según el fabricante y el tipo de onda.
</p>
<p>
  El sentido de montaje de las chapas —contra el viento predominante de la zona— y el solape
  entre chapas consecutivas también afectan cuánta agua se filtra en tormentas fuertes. Un
  solape corto ahorra material pero deja más riesgo de filtración; conversalo con el proveedor
  antes de calcular cuántas chapas necesitás para cubrir el ancho total del techo.
</p>

<h2>Accesorios que se cotizan aparte</h2>
<p>
  Ninguna cotización de techo queda completa con solo la chapa. Cumbreras, babetas laterales,
  canaletas y la tornillería autoperforante con arandela se cotizan aparte del metro cuadrado de
  chapa, y conviene pedirlos en la misma consulta para no terminar coordinando dos fletes
  distintos. Si vas a usar chapa termoacústica también en paredes —algo común en cámaras
  frigoríficas o depósitos— avisá desde el pedido, porque ahí entran además los perfiles de
  fijación oculta que dan una terminación más prolija que el tornillo visto.
</p>
<p>
