  esta misma cuenta con tus medidas. La dosificación de tu obra la define quien la calcula.
  Estas proporciones son las de manual; si tu maestro o tu calculista usa otra, cambiá la
  proporción y rehacé la cuenta.
</p>

<h2>Qué pedir de cada árido</h2>
<p>
  Para pedir bien arena y ripio, lo primero es tener el volumen total de hormigón que necesitás en
  metros cúbicos, calculado a partir de las medidas del elemento —contrapiso, zapata, columna,
  viga o losa— según el plano de estructura. Con ese volumen y la dosificación que te indique tu
  calculista, el proveedor puede calcular cuánta arena y cuánto ripio corresponden a tu pedido. Es
  importante no aplicar de memoria una proporción que usaste en otra obra, porque la dosificación
  cambia según la resistencia requerida, el tamaño máximo del árido disponible y las
  recomendaciones del ingeniero a cargo.
</p>
<p>
  También conviene pedir los dos áridos juntos y coordinados con la entrega del cemento, para que
  no falte uno mientras el otro ya está en obra: eso evita que el pastón quede parado esperando un
  material. Si tu obra tiene varios elementos con distinta dosificación —por ejemplo, un
  contrapiso con mezcla más pobre y una losa con mezcla más resistente— avisale al proveedor para
  que te ayude a separar las cantidades de cada tramo y no mezclar los pedidos.
</p>
<p>
  Pedí la entrega con margen respecto al día de la colada, sobre todo si el acceso a tu terreno es
  angosto o si el camión necesita descargar en un punto puntual del lote: un volquete de arena o
  ripio mal ubicado obliga a mover material dos veces, lo que suma horas de mano de obra al costo
  final. Si el terreno tiene pendiente o el acceso es de tierra, avisale al proveedor antes de
  coordinar la fecha, para que confirme si el camión puede entrar cargado o si conviene una entrega
  fraccionada.
</p>

<h2>Cuándo conviene hormigón elaborado</h2>
<p>
  Para volúmenes grandes o para elementos donde la resistencia y la homogeneidad de la mezcla son
  críticas —losas grandes, columnas de estructuras de varios niveles— muchas obras optan por
  <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a> en lugar de mezclar en obra.
  La ventaja es que la dosificación viene controlada de fábrica según la resistencia pedida, y se
  evita la variabilidad que puede surgir al mezclar arena, ripio y cemento a pala en el sitio. Para
  volúmenes chicos o elementos puntuales, en cambio, sigue siendo común comprar los áridos por
  separado y mezclar en obra, siempre respetando la dosificación indicada por el calculista.
</p>
