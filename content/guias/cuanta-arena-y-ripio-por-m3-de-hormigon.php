<h2>Cómo se compone un metro cúbico</h2>
<p>
  Un metro cúbico de hormigón se arma combinando cemento, agua y áridos —arena y ripio,
  principalmente— en proporciones que definen tanto la resistencia como la trabajabilidad de la
  mezcla. Esa proporción, sin embargo, no es un número fijo que sirva para toda obra: depende de
  la dosificación que indique tu calculista o ingeniero según el uso que le vas a dar al
  hormigón —no es lo mismo un contrapiso que una columna o una losa estructural. Por eso, más que
  buscar una receta única, conviene entender qué rol cumple cada componente para después pedirle
  al proveedor una dosificación ajustada a tu elemento estructural.
</p>
<p>
  La <a href="/materiales/arena-lavada/">arena lavada</a> actúa como árido fino, rellenando los
  espacios entre las piedras del ripio y aportando trabajabilidad a la mezcla fresca. El
  <a href="/materiales/ripio/">ripio</a>, como árido grueso, aporta el volumen y buena parte de la
  resistencia final del hormigón endurecido. La calidad de ambos —granulometría pareja, sin barro
  ni materia orgánica— influye directamente en cuánto cemento vas a necesitar para lograr la
  resistencia especificada: un árido de mala calidad obliga a compensar con más cemento, lo que
  encarece la mezcla sin necesidad.
</p>
<p>
