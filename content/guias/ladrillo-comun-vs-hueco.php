<h2>Peso, aislación y velocidad de obra</h2>
<p>
  La comparación entre <a href="/materiales/ladrillo-comun/">ladrillo común</a> y
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a> aparece en casi toda obra nueva, porque
  cada uno resuelve cosas distintas. El ladrillo común es macizo, más pesado por unidad y más
  chico, lo que significa más piezas y más juntas por metro cuadrado de pared: se levanta más
  despacio, pero da una pared densa, con buena inercia térmica y una terminación tradicional que
  todavía se pide mucho para frentes vistos o mampostería de calidad. El ladrillo hueco, al tener
  cámaras de aire internas, pesa menos por unidad de volumen y se coloca más rápido porque cada
  pieza cubre más superficie de pared, lo que reduce la mano de obra y acelera el avance de la
  obra gruesa.
</p>
<p>
  En cuanto a aislación, las cámaras de aire del ladrillo hueco ayudan a cortar la transmisión de
  calor y ruido mejor que un ladrillo macizo del mismo espesor, aunque el resultado final siempre
  depende del espesor de pared, del revoque y de si se usa una o dos hojas de ladrillo. El peso
  también entra en la ecuación estructural: un muro de ladrillo común carga más peso propio sobre
  la fundación y la estructura que uno de ladrillo hueco del mismo espesor, algo que el
  calculista tiene en cuenta al dimensionar cimientos y vigas.
</p>

<h2>Cuándo va cada uno</h2>
<p>
  El ladrillo común se sigue eligiendo para mampostería de carga en construcciones tradicionales,
  para frentes que van a quedar vistos y para reformas donde hay que empatar con una construcción
  existente hecha con el mismo material. El ladrillo hueco, en cambio, es el más usado hoy en
  cerramientos de estructuras de hormigón armado —donde la pared no es portante sino que rellena
  entre columnas y vigas— porque ahí lo que más pesa es la velocidad de colocación y el menor peso
  sobre la losa. También se usa en tabiques interiores y divisiones donde no hace falta la
  resistencia de una pared maciza.
</p>
<p>
  Ninguno de los dos es "mejor" en términos absolutos: depende del tipo de estructura, del uso
  que le vas a dar a esa pared (portante o de cerramiento) y de la terminación que buscás. Un
  mismo proyecto puede combinar los dos materiales sin problema, usando ladrillo común donde
  conviene la mampostería tradicional y ladrillo hueco donde se prioriza avance de obra y menor
  peso. La decisión final sobre qué muros son portantes y qué material corresponde en cada caso
  la tiene que confirmar el profesional a cargo del proyecto.
</p>

<h2>Qué preguntar antes de comprar</h2>
<p>
  Antes de cerrar el pedido, fijate en el tamaño exacto de la pieza que vas a usar, porque varía
  entre proveedores y eso cambia cuántas unidades entran por metro cuadrado de pared. Preguntá
  también por la resistencia y la cocción del ladrillo, sobre todo si es para mampostería
  portante, y pedí ver una muestra si es para un frente visto, porque el color y la textura
  pueden variar entre partidas. Si vas a combinar ladrillo común y hueco en la misma obra, avisale
  al proveedor para que te oriente sobre cantidades de cada uno según los metros cuadrados de cada
  tipo de pared. También podés revisar el resto de la familia en
  <a href="/materiales/ladrillos-y-bloques/">ladrillos y bloques</a> si tu proyecto necesita otras
  variantes.
</p>
<p>
  Contanos los metros cuadrados de pared que tenés que levantar, si son muros portantes o de
  cerramiento, y qué terminación buscás, y te ayudamos a definir qué ladrillo conviene en cada
  tramo de la obra. <a href="/cotizar/">Pedí tu cotización</a> y coordinamos cantidad y entrega
  según tu cronograma.
</p>
