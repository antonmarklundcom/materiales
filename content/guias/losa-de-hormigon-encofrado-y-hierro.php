<h2>Qué es el hormigón armado</h2>
<p>
  Una losa de hormigón armado combina dos materiales que trabajan juntos: el hormigón, que
  resiste bien la compresión pero poco la tracción, y el hierro, que aporta justamente la
  resistencia a tracción que al hormigón le falta. Para que esa combinación funcione como espera
  el cálculo estructural, hacen falta dos cosas antes de llegar al hormigonado: un
  <strong>encofrado</strong> que le dé forma a la losa mientras el hormigón fragua, y una
  <strong>armadura de hierro</strong> ubicada exactamente donde indica el plano de estructura. Ni
  el encofrado ni el hierro son opcionales ni improvisables: ambos siguen las medidas y
  especificaciones que definió el calculista para esa losa en particular, según la luz a cubrir y
  las cargas previstas.
</p>
<p>
  El <a href="/materiales/hormigon-elaborado/">hormigón elaborado</a> es la opción más usada hoy
  para losas, porque garantiza una dosificación controlada y homogénea en toda la superficie a
  hormigonar, algo difícil de lograr mezclando a pala en obra cuando el volumen es grande. La
  dosificación de resistencia que se pide siempre depende de lo que indique el calculista para esa
  losa puntual, según el uso y las cargas previstas.
</p>

<h2>El encofrado: tablas, puntales y desencofrado</h2>
<p>
  El encofrado es la estructura provisoria de tablas y puntales que sostiene el peso del hormigón
  fresco hasta que endurece y adquiere resistencia propia. Se arma con tablas de encofrado
  apoyadas sobre una grilla de puntales metálicos o de madera, calculada para no ceder bajo el
  peso del hormigón fresco, que es considerablemente más pesado que el hormigón ya curado. La
  separación entre puntales y el espesor de las tablas dependen del espesor de losa proyectado y
  de la carga que va a soportar durante el hormigonado, así que conviene seguir las indicaciones
  del maestro mayor de obra o del calculista antes de armar la grilla.
</p>
<p>
  El <strong>desencofrado</strong> —el retiro de tablas y puntales— no se hace por calendario fijo
  sino respetando los tiempos de curado que indique el calculista según el tipo de cemento
  usado, la temperatura ambiente y el espesor de la losa. Retirar el encofrado antes de tiempo es
  uno de los errores más riesgosos en obra, porque el hormigón todavía no alcanzó la resistencia
  necesaria para sostenerse solo. Muchas obras dejan puntales de seguridad (reapuntalado) incluso
  después de retirar las tablas, como resguardo mientras la losa sigue ganando resistencia.
</p>

<h2>El hierro de la losa y de las zapatas</h2>
<p>
  Sobre el encofrado ya armado se coloca la armadura de <a href="/materiales/varilla-de-hierro/">
  varilla de hierro</a>, distribuida según el plano de armado en una o dos capas (parrilla
  superior e inferior) separadas por los espaciadores necesarios para que el hierro no toque el
  encofrado ni quede sin recubrimiento de hormigón. El diámetro, la separación entre varillas y la
  cantidad de capas los define el cálculo estructural para esa losa en particular, según la luz
  entre apoyos y las cargas previstas; no son datos que se puedan copiar de otra obra con
  distintas dimensiones. Las zapatas, que reciben la carga de las columnas y la transmiten al
  suelo, también llevan su propia armadura de hierro, generalmente de mayor diámetro que el de la
  losa, definida igualmente por el calculista según el tipo de suelo y la carga de la estructura.
</p>
<p>
  Es importante que la armadura quede fija y firme antes del hormigonado, sin desplazarse cuando
  se vuelca y vibra el hormigón, porque un desplazamiento del hierro respecto de lo calculado
  puede comprometer el comportamiento de la losa terminada.
</p>

<h2>Qué pedir al proveedor y en qué orden</h2>
<p>
  El pedido para una losa suele organizarse en etapas: primero la
  <a href="/materiales/tabla-de-encofrado/">tabla de encofrado</a> y los puntales, para armar la
  estructura provisoria; después el hierro cortado y doblado según la planilla del calculista,
  para armar la parrilla sobre el encofrado ya listo; y por último el hormigón elaborado, para el
  día del hormigonado, coordinado con antelación porque ese día no puede haber demoras en la
  entrega. Llevar el plano de encofrado y la planilla de hierros a la consulta ayuda al proveedor
  a calcular cantidades ajustadas de cada material y a coordinar las fechas de entrega según tu
  cronograma de obra.
</p>
<p>
  Contanos la superficie de la losa, el espesor y la etapa de la obra en la que estás, y te
  ayudamos a coordinar el pedido de tabla de encofrado, hierro y hormigón elaborado en el orden
  que corresponde. <a href="/cotizar/">Pedí tu cotización</a> y organizamos la entrega según tu
  cronograma.
</p>
