<h2>Qué lleva un revoque</h2>
<p>
  Un revoque tradicional se arma en capas, cada una con una función distinta sobre la pared. La
  primera capa, el <strong>revoque grueso</strong>, es la que empareja las irregularidades de la
  mampostería y le da el espesor base a la terminación; se hace con una mezcla de
  <a href="/materiales/cal-hidratada/">cal hidratada</a>, <a href="/materiales/arena-lavada/">arena
  lavada</a> y <a href="/materiales/cemento/">cemento</a> en la proporción que indique tu maestro
  mayor de obra o tu proveedor según el tipo de pared y el ambiente —no es la misma mezcla para
  interior que para una fachada expuesta a la lluvia. La segunda capa, el
  <strong>revoque fino</strong>, se aplica sobre el grueso ya firme y da la terminación lisa que
  después recibe pintura u otro revestimiento.
</p>
<p>
  La cal hidratada cumple un rol importante en la mezcla: aporta plasticidad, hace que el mortero
  sea más fácil de aplicar con la llana y ayuda a que el revoque no se fisure tanto al secar,
  comparado con una mezcla de cemento y arena sin cal. La proporción exacta de cada componente
  —cemento, cal y arena— depende de la dosificación que uses, y esa dosificación conviene
  consultarla con tu proveedor o con el calculista según el tipo de superficie, el ambiente
  (interior, exterior, zona húmeda) y la terminación final que busques.
</p>

<h2>Grueso y fino: cómo se hace</h2>
<p>
  Antes de aplicar el grueso, la pared tiene que estar limpia, sin polvo suelto ni restos de
  mortero de asiento, y en muchos casos se moja previamente para que el ladrillo no le robe agua
  a la mezcla fresca demasiado rápido. Donde la pared se encuentra con una columna o una viga
  de hormigón, o sobre una canaleta donde se embutieron caños, se suele fijar antes una tira de
  <a href="/materiales/metal-desplegado/">metal desplegado</a> para que el revoque tenga de
  dónde agarrarse sobre materiales distintos. El grueso se tira con cuchara y se empareja con regla o
  fratacho, dejando una superficie pareja pero todavía rugosa, que es justamente la que necesita
  el fino para agarrarse bien. Hay que dejar que el grueso fragüe y tome cierta firmeza antes de
  pasar a la siguiente capa; aplicar el fino demasiado pronto sobre un grueso todavía blando suele
  terminar en fisuras o desprendimientos más adelante.
</p>
<p>
  El fino se aplica con una mezcla más fina y se termina con llana o fratacho metálico, según la
  textura final que busques —fratasado, alisado, texturado. En esta etapa es donde más se nota la
  mano de obra: un buen fino requiere pasadas parejas y buen manejo de los tiempos de fragüe para
  no marcar la herramienta sobre la superficie. En fachadas o zonas húmedas conviene consultar con
  el proveedor si conviene sumar algún aditivo hidrofugante a la mezcla, según el uso que le vas a
  dar a esa pared.
</p>

<h2>Cuánto material calcular</h2>
<p>
  El cálculo de material para revocar depende de los metros cuadrados totales de pared o
  cielorraso a cubrir, del espesor previsto para cada capa (grueso y fino por separado) y de la
  dosificación elegida para cada mezcla. Cuantos más metros cuadrados y mayor el espesor, más cal,
  arena y cemento vas a necesitar, pero la proporción exacta entre esos tres componentes es la que
  define tu calculista o tu proveedor, nunca una receta fija que sirva para cualquier obra. Contar
  con los metros cuadrados exactos de cada ambiente antes de pedir el material evita comprar de
  más o quedarte a mitad de pared por falta de mezcla.
</p>
