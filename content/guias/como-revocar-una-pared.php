<p>
  <strong>Un ejemplo:</strong> 30 m² de pared con un revoque grueso de 1,5 cm son 30 × 0,015 =
  0,45 m³ de mezcla; con un 10 % de desperdicio, 0,495 m³. En mortero con cal eso pide
  0,495 × 4 = 1,98, o sea <strong>2 bolsas de cemento</strong>, unos 50 kg de cal y 0,52 m³ de
  arena. La <a href="/calculadoras/revoque-y-mortero/">calculadora de revoque</a> hace la cuenta
  con tus medidas. La dosificación de tu obra la define quien la calcula. Estas proporciones son
  las de manual; si tu maestro o tu calculista usa otra, cambiá la proporción y rehacé la cuenta.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  A la hora de pedir, llevá los metros cuadrados de cada superficie a revocar, separados por
  ambiente si tenés espesores o terminaciones distintas, y contá si ya tenés definida la
  dosificación o si necesitás orientación según el tipo de pared y el ambiente. Un proveedor con
  experiencia en obra puede ayudarte a estimar cal, arena y cemento para grueso y fino por
  separado, y coordinar que lleguen juntos para no frenar la obra esperando un material.
</p>
<p>
  Contanos los metros cuadrados que tenés que revocar y en qué ambientes, y te ayudamos a armar el
  pedido de cal hidratada, arena lavada y cemento para cada capa.
  <a href="/cotizar/">Pedí tu cotización</a> y coordinamos la entrega según el avance de tu obra.
</p>
