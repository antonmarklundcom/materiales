<h2>Diferencias que importan</h2>
<p>
  Si ya decidiste que el techo va con teja, la siguiente pregunta es cuál. En plaza conviven
  dos familias: la <a href="/materiales/teja-espanola/">teja española</a> —también llamada teja
  colonial o teja romana—, de perfil curvo, y la
  <a href="/materiales/teja-francesa/">teja francesa</a> —o teja marsellesa, o teja plana—, de
  perfil recto. Las dos son piezas cerámicas de barro cocido y las dos pesan más que la chapa,
  así que las dos piden una estructura preparada. Lo que las separa es cómo se unen las piezas
  y, con eso, el aspecto final del techo.
</p>
<p>
  La teja española se apoya por superposición curva: cada pieza monta sobre la otra y el techo
  toma ese dibujo ondulado de las casas coloniales y de campo. La francesa encastra: cada pieza
  traba con la de al lado por un borde, lo que da una unión más ajustada, un plano parejo y un
  montaje más ordenado. Es, como resume la ficha de la teja francesa, una decisión de estética y
  de estructura disponible.
</p>
