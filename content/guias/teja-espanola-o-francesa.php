<h2>Cuándo conviene cada una</h2>
<p>
  La teja española es la que corresponde cuando buscás el techo colonial o de campo: viviendas
  con esa terminación clásica, corredores y galerías, y restauraciones de casas antiguas que ya
  tenían este tipo de cubierta. Al ser de barro cocido, además de la estética aporta buena
  inercia térmica: el techo tarda más en calentarse durante el día.
</p>
<p>
  La teja francesa conviene cuando el diseño va por líneas rectas y una terminación más prolija
  y pareja a la vista, típica de construcciones de estilo más moderno o de influencia europea.
  Se usa en vivienda y en techos con pendientes marcadas, y su encastre ordena el montaje pieza
  por pieza.
</p>
<p>
  Un criterio práctico es mirar el resto de la fachada: si la casa tiene galerías y un estilo
  tradicional, la curva de la española acompaña; si tiene volúmenes rectos, la francesa
  se integra mejor. Si todavía estás dudando entre teja y chapa, la guía
  <a href="/guias/chapa-o-teja-que-techo-conviene/">chapa o teja: qué techo conviene</a> compara
  las dos coberturas antes de llegar a esta elección.
</p>

<h2>Estructura, pendiente y piezas especiales</h2>
<p>
  Cualquiera de las dos pesa más que una chapa, así que la estructura tiene que estar calculada
  para eso. Si el techo todavía está por hacerse, contá qué teja vas a usar desde el principio;
  si ya tenés una estructura pensada para chapa, no cambies a teja sin consultar antes si
  soporta el peso extra. Los <a href="/materiales/tirantes/">tirantes</a> y el tirantillo o las
  clavaderas sobre los que se apoya la teja se cotizan aparte.
</p>
<p>
  La pendiente es el otro dato que no se improvisa. Las tejas curvas piden una pendiente
  suficiente para que el agua escurra sin filtrarse entre piezas; consultá la pendiente mínima
  recomendada para la teja que te coticen antes de cerrar la estructura. Con la francesa, pasá
  también la pendiente proyectada al pedir, junto con la superficie. En los dos casos, las
  piezas especiales de remate, cumbrera y limahoya van aparte del cuerpo de teja: pedilas en el
  mismo pedido para comparar el techo completo y no sólo las tejas.
</p>
<p>
  Al recibir, cada una se revisa distinto. En la española, fijate que color y curvatura sean
  parejos y golpeá suavemente algunas piezas: un sonido metálico indica buena cocción, uno opaco
  puede señalar tejas más frágiles y porosas. En la francesa, lo crítico es que las piezas
  calcen entre sí sin forzar y que los bordes de encastre no vengan astillados, porque una
  pequeña diferencia entre partidas deja juntas irregulares.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  Pasá los metros cuadrados de techo, la pendiente proyectada, el tipo de teja y el acabado que
  buscás, y contá si la estructura ya existe o está por hacerse. Pedí que te confirmen el
  rendimiento por metro cuadrado de esa pieza puntual —en la francesa depende del encastre de
  cada fabricante— y sumá algunas piezas de más sobre el cálculo, para tener repuesto del mismo
  lote ante una rotura durante la colocación. El flete también cuenta: son piezas pesadas.
</p>
