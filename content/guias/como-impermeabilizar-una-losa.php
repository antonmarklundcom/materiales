<h2>Por qué una losa necesita impermeabilizarse</h2>
<p>
  El hormigón en sí mismo es un material bastante impermeable, pero una losa terminada no es un
  bloque uniforme y sin defectos: tiene juntas de hormigonado, fisuras de retracción que aparecen
  con el tiempo, y queda expuesta de forma directa al sol y a la lluvia durante años. Cualquiera
  de esos puntos —una fisura fina, una junta mal sellada, un remate contra un parapeto o un
  caño que atraviesa la losa— es una vía de entrada para el agua, aunque el resto de la
  superficie esté en buen estado. Si además la losa no quedó con la <strong>pendiente
  suficiente</strong> hacia los desagües, el agua de lluvia se acumula en vez de escurrir, y una
  superficie con agua estancada exige mucho más de cualquier impermeabilización que una que
  drena rápido.
</p>
<p>
  Por eso una losa expuesta —sea azotea, techo transitable o no, o cualquier superficie
  horizontal de hormigón que recibe lluvia directa— necesita una capa de impermeabilización
  pensada para esa exposición, además del hormigón que ya tiene. Si todavía estás en la etapa de
  construir la losa, con el encofrado y el hierro por definir, conviene
  <a href="/guias/losa-de-hormigon-encofrado-y-hierro/">ver esa guía primero</a>: acá se parte de
  una losa ya hormigonada y curada, y se trata sólo la impermeabilización posterior.
</p>

<h2>Pasos antes de aplicar cualquier producto</h2>
<p>
  Ningún producto impermeabilizante rinde lo que promete si se aplica sobre una superficie que
  no está lista. Lo primero es respetar el <strong>curado completo del hormigón</strong>: una
  losa recién desencofrada todavía sigue ganando resistencia y liberando humedad interna, y
  aplicar una membrana antes de tiempo compromete la adherencia. Después viene la
  <strong>limpieza de la superficie</strong>, sacando polvo, restos de obra, partes flojas o
  cualquier resto de desencofrante que quede pegado al hormigón, porque cualquier producto que
  se aplique necesita apoyarse sobre una superficie firme y limpia para adherir bien.
</p>
<p>
  El paso siguiente es revisar y <strong>sellar las fisuras</strong> visibles, porque una
  fisura que queda debajo de una membrana sigue siendo un punto débil que se puede volver a
  abrir con el movimiento térmico de la losa. Y por último, antes de comprar cualquier producto,
  conviene verificar que la <strong>pendiente hacia los desagües</strong> sea la correcta: si el
  agua no escurre y queda estancada en algún sector, ningún impermeabilizante —por bueno que
  sea— dura lo que debería en ese punto puntual, y ese problema de pendiente hay que corregirlo
  antes, no taparlo con más producto.
</p>

<h2>Qué producto conviene según la superficie</h2>
<p>
  Con la losa lista, la elección del producto depende sobre todo de la geometría de la
  superficie. Para una <strong>losa grande y regular</strong>, sin muchos quiebres ni detalles,
  la <a href="/materiales/membrana-asfaltica/">membrana asfáltica</a> en rollo —colocada con
  soplete o en versión autoadhesiva— cubre metros cuadrados grandes en poco tiempo y da buena
  resistencia a la exposición directa al sol y la lluvia. Cuando la losa tiene muchos quiebres,
  bajadas, encuentros con caños o remates contra parapetos, un rollo no entra cómodo en esos
  puntos, y ahí conviene la <a href="/materiales/membrana-liquida/">membrana líquida</a>, que se
  aplica con rodillo o pincel y se adapta a geometrías complicadas —incluso como complemento de
  la membrana asfáltica en los remates puntuales que el rollo no cubre bien.
</p>
<p>
  El <a href="/materiales/hidrofugo/">hidrófugo</a>, ya sea como aditivo de la mezcla o como
  pintura, trabaja distinto: complementa la impermeabilización pero no la reemplaza en una losa
  expuesta a agua acumulada, porque resuelve lo que pasa dentro de la mezcla y no la superficie
  que recibe la lluvia de forma directa. En una losa que va a quedar expuesta, lo que sostiene la
  estanqueidad frente al agua es la membrana —asfáltica o líquida según la superficie—, y el
  hidrófugo suma una capa adicional de protección, no la reemplaza.
</p>

<h2>Mantenimiento después de aplicada</h2>
<p>
  Una impermeabilización de losa no es un trabajo que se hace una vez y se olvida para siempre:
  conviene revisarla cada cierto tiempo, sobre todo antes de que empiece la temporada de
  lluvias, para detectar a tiempo alguna zona que se haya despegado, una fisura nueva o un
  encuentro que empezó a filtrar. Revisar antes de la temporada de lluvias, y no durante o
  después de la primera filtración, es lo que evita que un problema chico en un remate termine
  afectando el cielorraso de abajo.
</p>
