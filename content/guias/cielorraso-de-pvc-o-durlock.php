<h2>Cuándo conviene cada uno</h2>
<p>
  El PVC conviene donde hay humedad o donde querés un cielo que se limpie con un trapo: baños,
  cocinas, lavaderos, galerías y exteriores cubiertos como aleros, porque a diferencia de un
  cielorraso de madera no se pudre con la humedad. También es la salida cuando lo que más pesa
  es la rapidez de montaje y te sirve el color de la tablilla, sin el masillado y la pintura
  que pide la placa. Si va a quedar expuesto al sol
  directo, aclaralo en el pedido.
</p>
<p>
  La placa de yeso conviene cuando buscás que el cielo se vea como una superficie lisa y
  pintada, igual que las paredes, en ambientes secos como el living o los dormitorios. También es la que
  permite cielorrasos con desniveles, nichos y encuentros con distintas alturas. Si el
  cielorraso de placa va en un baño o una cocina, tiene que ser la placa resistente a la
  humedad —la placa verde—, no la común.
</p>
<p>
  Un punto a tener claro: el cielorraso tapa la estructura, pero el de PVC no reemplaza
  a una <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a> cuando lo que hace
  falta es cortar calor. Si el problema de tu ambiente es el calor que baja del techo,
  planteáselo al proveedor antes de elegir el cielorraso. Y si preferís la estética de la
  madera, está el <a href="/materiales/machimbre/">machimbre de madera</a>, con el mantenimiento
  que la madera pide.
</p>

<h2>Estructura y terminación</h2>
<p>
  En los dos sistemas, la calidad del cielo depende de la estructura que queda arriba. El PVC
  no perdona una base torcida: la perfilería o los listones tienen que estar bien nivelados
  antes de colocar, y una tablilla muy fina se puede curvar o marcar en tramos largos sin apoyo
  intermedio. Revisá también que el color sea parejo entre tablillas de una misma partida y
  pedí los perfiles de arranque y de terminación en el mismo pedido, para no salir después a
  buscar un tono que ya no coincide.
</p>
<p>
  En la placa de yeso, el esqueleto son los
  <a href="/materiales/perfiles-para-durlock/">perfiles para durlock</a>: soleras en el
  perímetro, perfiles que reciben la placa y el ángulo de ajuste que remata el encuentro con la
  pared. La separación entre perfiles es lo que define cuán parejo queda el cielorraso, y el
  espesor de la placa tiene que coincidir con esa estructura. Sin masilla y cinta de juntas la
  placa no queda lista para pintar, así que sumalas desde el principio.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  Para PVC, pasá los metros cuadrados y las medidas de cada ambiente, el ancho de tablilla que
  preferís —define cuántas uniones quedan a la vista— y si necesitás perfil U de arranque y
  perfiles de remate. Para placa de yeso, pasá los metros cuadrados, el perímetro del
  cielorraso, si hay zonas húmedas y si va con desniveles; con eso el proveedor calcula placas,
  perfiles y tornillos, y conviene que en la misma cotización venga la masilla y la cinta. Así
  comparás el metro cuadrado de cielorraso terminado y no sólo el de la pieza.
</p>
