<h2>Diferencias que importan</h2>
<p>
  Para cerrar por dentro un techo de chapa o una losa y tapar la estructura, las dos opciones
  que más se piden hoy son el <a href="/materiales/cielorraso-de-pvc/">cielorraso de PVC</a> y el
  cielorraso de <a href="/materiales/placa-de-yeso/">placa de yeso</a>, el que todos llaman
  cielorraso durlock. Resuelven lo mismo —un cielo terminado debajo de la cubierta—, pero con
  sistemas y resultados distintos. El PVC viene en tablillas, también llamadas machimbre de
  PVC, que encastran una con otra sobre una estructura simple: es liviano, lavable, no se mancha
  con la humedad y es el cielorraso más rápido de montar. La placa de yeso se atornilla sobre
  una estructura de perfiles y después se masillan y encintan las juntas para que desaparezcan
  bajo la pintura: el resultado es una superficie lisa y continua, como la de una pared.
</p>
<p>
  Dicho de otra forma: con PVC el cielo queda con las uniones de las tablillas a la vista y con
  el color que ya trae la tablilla; con placa de yeso queda un plano liso que se pinta del color
  que quieras. De ahí sale casi toda la decisión.
</p>
