<h2>Qué hace cada piedra</h2>
<p>
  Cuando se habla de "piedra para cimientos" en realidad se está hablando de varios materiales
  distintos que cumplen funciones diferentes en la base de una construcción. La
  <a href="/materiales/piedra-bruta/">piedra bruta</a> —también llamada piedra de campo o
  piedra basa según la zona— se usa históricamente para los cimientos corridos y las bases de
  mampostería, aportando volumen y estabilidad en la parte más profunda de la fundación. La
  <a href="/materiales/piedra-triturada/">piedra triturada</a>, en cambio, tiene un tamaño más
  parejo y se usa más para bases compactadas, capas de asiento o como parte de mezclas de
  hormigón, donde la uniformidad del grano importa más que el volumen bruto. Entender esta
  diferencia te ahorra pedir el material equivocado y tener que reemplazarlo a mitad de obra.
</p>
<p>
  En general, cuando se habla de <a href="/materiales/aridos/">áridos</a> para cimentación se
  agrupan piedra, ripio y arena, aunque cada uno cumple un rol distinto según el tipo de
  fundación que se esté construyendo. Un cimiento corrido de mampostería no pide lo mismo que
  una base de hormigón armado, y esa diferencia también define qué piedra conviene y en qué
  proporción combinarla con los demás áridos.
</p>

<h2>Piedra bruta en cimientos corridos</h2>
<p>
  El cimiento corrido de piedra bruta es una solución tradicional y todavía muy usada en
  construcciones de una o dos plantas, sobre todo en zonas donde el terreno lo permite. Las
  piedras se colocan en la zanja de fundación, trabadas entre sí y asentadas con mortero, formando
  una base ancha que reparte el peso de los muros sobre una superficie mayor de terreno. La
  irregularidad de la piedra bruta, que en otros usos sería una desventaja, acá ayuda: las caras
  angulosas se traban mejor entre ellas y con el mortero, dando firmeza al conjunto.
</p>
<p>
  Este tipo de cimiento se sigue usando en obras donde el estudio de suelo y la práctica local lo
  avalan, pero la decisión final sobre qué tipo de fundación conviene —corrida de piedra,
  platea, zapatas aisladas— depende del calculista o del ingeniero a cargo del proyecto, según el
  tipo de suelo, la carga de la construcción y las normas municipales de tu zona. La piedra bruta
  es un material, no una decisión de ingeniería: la decisión de qué fundación usar siempre le
  corresponde al profesional que firma el cálculo.
</p>

<h2>Cómo calcular el volumen</h2>
<p>
  Para calcular cuánta piedra necesitás, lo primero es tener el largo total de las zanjas de
  fundación, el ancho de base previsto y la profundidad indicada en el plano de fundaciones. Con
  esos tres datos se llega al volumen en metros cúbicos que hay que rellenar, aunque conviene
  restar el volumen que va a ocupar el mortero de asiento entre piedra y piedra, porque la piedra
  bruta no rellena el 100% del espacio disponible al estar apilada de forma irregular. Un
  calculista o un maestro con experiencia en este tipo de cimiento suele aplicar un coeficiente de
  ajuste sobre el volumen teórico para compensar esos huecos.
</p>
<p>
  Si en cambio vas a usar piedra triturada como base compactada o como parte de una mezcla de
  hormigón para zapatas o platea, el cálculo cambia: ahí lo que importa es el volumen de la capa
  de asiento o la proporción que indique la dosificación del hormigón que te pase el calculista,
  nunca una proporción fija de memoria. En cualquiera de los dos casos, contanos el largo de tus
  zanjas, el ancho y la profundidad de proyecto y te ayudamos a estimar el volumen de piedra que
  necesitás pedir. <a href="/cotizar/">Pedí tu cotización</a> y coordinamos la entrega según el
  avance de tu obra.
</p>
