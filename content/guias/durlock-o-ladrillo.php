<h2>Cuándo conviene cada uno</h2>
<p>
  El tabique de placa de yeso conviene cuando pesa más no ensuciar ni mojar la obra: dividir un
  dormitorio en una casa ya habitada, armar un ambiente nuevo dentro de un local, sumar una
  pared en un piso superior donde no querés cargar la losa, o resolver nichos y revestimientos
  de columnas, que también se arman con placa. Para baños y cocinas va la
  placa resistente a la humedad —la placa verde—, no la común, y donde se exige resistencia al
  fuego hay otra placa específica.
</p>
<p>
  El ladrillo conviene cuando la pared tiene que integrarse con el resto de una obra de
  mampostería que ya se está levantando y revocando, o cuando preferís la terminación de una
  pared revocada. Para tabiques livianos se usa el ladrillo de 8 y para paredes internas de
  más uso o con instalaciones, el de 12. Si la pared va a llevar carga, ahí no entra ni la placa
  ni el hueco: corresponde el <a href="/materiales/ladrillo-comun/">ladrillo común</a> o la pieza
  que indique el calculista. Si la duda es entre ladrillos, la guía
  <a href="/guias/ladrillo-comun-vs-hueco/">ladrillo común vs hueco</a> compara esos dos.
</p>

<h2>Lo que hay que resolver antes de cerrar la pared</h2>
<p>
  En el tabique en seco, la firmeza no la da la placa sino la estructura. Los
  <a href="/materiales/perfiles-para-durlock/">perfiles para durlock</a> —montantes verticales y
  soleras arriba y abajo— tienen que ir con la separación correcta: perfiles muy separados dejan
  una pared que suena hueca y flexa al apoyarse. Si vas a colgar muebles o
  sanitarios, avisalo antes, porque eso cambia el refuerzo, y los vanos de puertas llevan
  soleras de refuerzo adicionales. El espesor de la placa también cuenta: a mayor espesor, mejor
  comportamiento acústico y más resistencia al impacto, a cambio de más peso para la
  estructura.
</p>
<p>
  En la pared de ladrillo, lo que se define antes es el espesor de la pieza y la mezcla. Revisá
  que los ladrillos no vengan rajados ni con las perforaciones colapsadas, porque un hueco
  débil se rompe al clavar o al enganchar una instalación, y que el espesor sea parejo entre
  piezas para que el revoque quede uniforme. Si nunca hiciste ese paso, la guía
  <a href="/guias/como-revocar-una-pared/">cómo revocar una pared</a> explica qué lleva cada
  capa.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  Para el tabique en seco, pasá los metros cuadrados y la altura de la pared, si es zona húmeda
  y si va a llevar cosas colgadas o puertas. Con eso el proveedor calcula placas, perfiles y
  tornillos; pedí en la misma cotización la masilla y la cinta de juntas, porque sin ellas la
  placa no queda lista para pintar. Para la pared de ladrillo, pasá los metros cuadrados y el
  espesor elegido, y sumá el cemento, la cal y la arena para asentar y revocar, así el flete no
  se fracciona.
</p>
