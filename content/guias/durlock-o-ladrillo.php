<h2>Diferencias que importan</h2>
<p>
  Cuando hay que dividir un ambiente o levantar una pared interior, la duda suele ser entre
  tabique en seco o mampostería de siempre. Del lado de la construcción en seco está la
  <a href="/materiales/placa-de-yeso/">placa de yeso</a>, lo que todo el mundo pide como
  durlock: placas que se atornillan sobre una estructura de perfiles, sin mortero ni revoque.
  Del lado de la mampostería, para un tabique interior lo habitual es el
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a> —el ladrillo de 8 o de 12—, que pesa
  menos que el macizo y se levanta más rápido, pero igual se asienta con mezcla y después se
  revoca.
</p>
<p>
  La diferencia de fondo es cómo se arma cada pared. El tabique en seco no trae la humedad de
  obra ni los tiempos de fragüe del ladrillo revocado, es liviano y, una vez atornillada la
  placa, se masillan las juntas y se pinta. La pared de ladrillo pasa por el asentado, el
  revoque grueso y el fino, con todo lo que eso implica de agua, mezcla y limpieza en un
  ambiente que tal vez ya está habitado. Ninguna de las dos es una pared de carga: la placa es
  un cerramiento liviano y el ladrillo hueco común tampoco está pensado para cargar estructura.
</p>
