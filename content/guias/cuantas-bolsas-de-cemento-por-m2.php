<h2>De qué depende el cálculo</h2>
<p>
  No hay una cifra única de "bolsas por metro cuadrado" que sirva para toda obra, aunque es lo
  primero que se busca cuando hay que presupuestar. La cantidad real depende de varias cosas al
  mismo tiempo: el espesor de la capa que vas a hacer (no es lo mismo un contrapiso de 5 cm que
  uno de 10), la dosificación que uses (una mezcla más rica en cemento rinde distinto que una
  más pobre) y el tipo de trabajo —contrapiso, revoque o mampostería no llevan la misma
  proporción de <a href="/materiales/cemento/">cemento en bolsa</a> por metro cuadrado. Por eso,
  más que memorizar un número, conviene entender qué variables mueven el cálculo para después
  pedirle al proveedor una estimación ajustada a tu obra puntual.
</p>
<p>
  Otro factor que se olvida seguido es la calidad y granulometría de los áridos que vas a
  mezclar. Una <a href="/materiales/arena-lavada/">arena lavada</a> bien graduada, sin barro ni
  materia orgánica, rinde mejor que una arena de mala calidad, porque no hace falta compensar con
  más cemento para lograr la trabajabilidad y la resistencia que buscás. Lo mismo pasa con el
  <a href="/materiales/ripio/">ripio</a> cuando el trabajo lo requiere: un árido limpio y bien
  graduado te da una mezcla más previsible, y eso también repercute en cuánto cemento vas a
  terminar usando en la práctica, más allá de lo que diga la dosificación teórica.
</p>

<h2>Contrapiso, revoque y mampostería</h2>
<p>
  En un <strong>contrapiso</strong>, el consumo de cemento sube o baja principalmente con el
  espesor de la capa y con la dosificación elegida para esa mezcla de contrapiso —hay quienes
  usan mezclas más pobres para rellenar y otras más resistentes cuando el contrapiso va a
  quedar expuesto a tránsito. En un <strong>revoque</strong> el cálculo cambia porque la capa es
  mucho más fina, pero se aplica en dos manos (grueso y fino) y sobre superficies grandes, así
  que el rendimiento por bolsa se termina definiendo por cuántos metros cuadrados de pared o
  cielorraso vas a cubrir y con qué espesor de revoque. En la <strong>mampostería</strong>, en
  cambio, lo que más pesa es la cantidad de juntas: un muro con ladrillos más chicos tiene más
  metros de junta por metro cuadrado que uno con bloques grandes, y eso también cambia cuánto
  cemento se necesita para asentar cada hilada.
</p>
<p>
  En los tres casos, la recomendación es la misma: no traslades de memoria una proporción que
  usaste en otra obra, porque el clima, la humedad de los áridos y la dosificación que decida tu
  maestro o tu calculista pueden mover el número final. Si tenés planos o al menos las medidas de
  las superficies a cubrir, es mucho más fácil llegar a una cantidad ajustada que comprando "de
  más" por las dudas y quedándote con bolsas sin usar, o comprando de menos y frenando la obra a
  mitad de jornada.
</p>

<h2>Cómo pedir la cantidad al proveedor</h2>
<p>
  Para que te ayuden a calcular bien, llevá estos datos a la consulta: los metros cuadrados de
  cada superficie (contrapiso, revoque o pared, por separado), el espesor previsto en cada caso y
  qué tipo de trabajo es. Contá también si ya tenés definida la dosificación con tu calculista o
  maestro mayor de obra, o si necesitás que te orienten según el uso que le vas a dar a esa
  superficie. Un proveedor con experiencia en obra suele tener referencias de consumo por tipo de
  trabajo, pero esas referencias son aproximaciones que después hay que ajustar con la
  dosificación real que se use en el pastón.
</p>
<p>
  Fijate también en la calidad del cemento y de los áridos que vas a combinar, porque una mezcla
  bien proporcionada rinde más que una improvisada, y eso te ahorra bolsas de sobra. Si comprás
  todo junto —cemento, arena y ripio cuando corresponda— es más fácil coordinar la entrega y
  evitar que la obra se frene esperando un material que faltó. Contanos cuántos metros cuadrados
  tenés que cubrir y qué tipo de trabajo es y te ayudamos a armar el pedido. <a href="/cotizar/">Pedí tu cotización</a> y te respondemos con las cantidades ajustadas a tu obra.
</p>
