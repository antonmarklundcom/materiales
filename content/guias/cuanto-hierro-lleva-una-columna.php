<h2>Quién define la cantidad</h2>
<p>
  La cantidad de hierro que lleva una columna —cuántas barras, de qué diámetro y cada cuánto van
  los estribos— no sale de una tabla general ni de "lo que se usa siempre": la define el cálculo
  estructural que hace un ingeniero o calculista para esa obra en particular. Ese cálculo
  considera la carga que va a soportar la columna, la altura del piso, cuántas columnas reparten
  el peso del edificio y las normas de diseño vigentes. Dos columnas que se ven parecidas a
  simple vista, en obras distintas, pueden llevar cantidades de <a href="/materiales/hierro/">hierro</a>
  muy diferentes si las cargas o las luces que cubren no son las mismas. Por eso esta guía no da
  ni va a dar una cifra de "tantas barras" o "tantos kilos" por columna: eso es una decisión de
  ingeniería, no un dato que se pueda publicar como norma general.
</p>
<p>
  Si ya sabés qué diámetro corresponde a cada elemento de tu obra, en
  <a href="/guias/que-diametro-de-hierro-para-que-uso/">qué diámetro de hierro usar para cada uso</a>
  explicamos cómo se elige entre columnas, vigas, losas y estribos. Esta guía va un paso más
  allá: una vez que el calculista ya definió los diámetros, ¿de dónde sale la cantidad exacta de
  <a href="/materiales/varilla-de-hierro/">varilla de hierro</a> que hay que pedir?
</p>

<h2>Qué trae la lista de materiales de una columna</h2>
<p>
  Cuando un calculista termina el armado de una columna, entrega una planilla o un plano de
  armado que desglosa el hierro en partes bien definidas. Por un lado están las
  <strong>barras longitudinales</strong>: el hierro principal que corre a lo largo de toda la
  columna y resiste la carga vertical, en un diámetro determinado y en una cantidad de barras
  fijada por el cálculo. Por otro lado están los <strong>estribos</strong>: varillas más finas
  que envuelven a las barras longitudinales formando anillos, con un espaciamiento propio —que
  suele achicarse cerca de donde la columna se une a la viga o a la losa, porque ahí se
  concentran más esfuerzos. Y por último aparece el <strong>recubrimiento mínimo de hormigón</strong>,
  que no es hierro pero sí un dato del plano: la distancia que tiene que quedar entre el estribo
  y la cara exterior de la columna, para que el hierro quede protegido dentro del hormigón.
</p>
<p>
  Estos tres datos —barras longitudinales, estribos y recubrimiento— salen del mismo cálculo
  estructural y varían según la columna: no es raro que las columnas de planta baja lleven más barras o un diámetro mayor que
  las de planta alta, porque soportan más peso encima. La
  <a href="/materiales/malla-electrosoldada/">malla electrosoldada</a> es otro producto de la
  misma familia, pero se usa en losas y contrapisos: no reemplaza a las barras ni a los estribos
  de una columna.
</p>

<h2>Por qué no hay una cifra general</h2>
<p>
  Preguntar "¿cuánto hierro lleva una columna de tal tamaño?" sin tener el plano ni el cálculo es
  parecido a preguntar cuántas bolsas de cemento lleva un contrapiso sin saber los metros
  cuadrados que hay que cubrir: la pregunta tiene una respuesta real, pero esa respuesta depende
  de datos que todavía no están sobre la mesa. El tamaño de la sección de la columna por sí solo
  no alcanza para saber cuánto hierro lleva; hacen falta la carga que va a resistir, la altura
  libre entre pisos, la cantidad de plantas que tiene encima y el criterio del calculista sobre
  cómo distribuir esa carga entre columnas. Cualquier número que circule como "regla general" para
  una columna de tal medida es, en el mejor de los casos, una aproximación de otra obra con otras
  condiciones, y en el peor, una cifra inventada que puede dejar la estructura mal armada o hacer
  que compres de más o de menos. La cantidad exacta a pedir siempre va a salir de la planilla del
  calculista, nunca de una estimación previa.
</p>

<h2>Cómo pedir la cotización con esa lista</h2>
<p>
  Una vez que tenés la planilla de hierros de tus columnas, pasarla a una cotización es
  simplemente traducir esos datos al pedido: cuántas barras completas (o cuántos kilos en total)
  de cada diámetro necesitás, separando el hierro longitudinal del hierro de los estribos porque
  casi siempre son diámetros distintos. Si la planilla ya viene con las longitudes de corte, el
  proveedor puede calcular el peso total y, en algunos casos, ofrecer el corte y doblado, lo que
  ahorra tiempo en obra. Si tu obra tiene varias columnas con distintos armados, agrupar el pedido
  por diámetro —sumando todas las barras de 10 mm de un lado y todas las de 6 mm de los estribos
  del otro, por ejemplo— ayuda a que el proveedor cotice más rápido y sin errores.
</p>
<p>
  Contanos con qué diámetros y cantidades te dejó la planilla de tu calculista, y si también
  necesitás <a href="/calculadoras/hormigon-por-m3/">hormigón para las columnas</a> —porque el
  hierro y el hormigón casi siempre se piden juntos en esta etapa de la obra—, decinos los metros
  cúbicos que estimás. <a href="/cotizar/">Pedí tu cotización</a> y hasta tres proveedores
  verificados te responden con la disponibilidad y el corte que necesites.
</p>
