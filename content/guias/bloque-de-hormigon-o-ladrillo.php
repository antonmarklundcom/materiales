<h2>Diferencias que importan</h2>
<p>
  La elección entre ladrillo común y ladrillo hueco es una discusión entre dos piezas
  cerámicas; la que hay entre <a href="/materiales/bloque-de-hormigon/">bloque de hormigón</a> y
  ladrillo es otra, porque cambia el material y la forma de armar el muro. El bloque —que en
  obra se pide como bloque de cemento, bloque vibrado o bloquete— es una pieza de hormigón
  vibrado, grande y con huecos que se pueden rellenar con hormigón y hierro. El ladrillo, sea el
  <a href="/materiales/ladrillo-comun/">ladrillo común</a> macizo o el
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a>, es arcilla cocida en olería: una
  pieza más chica que se asienta con mortero en la mampostería de siempre.
</p>
<p>
  Esa diferencia se nota apenas empieza la obra. Cada bloque cubre más superficie de pared que
  un ladrillo, así que el metro cuadrado avanza en menos jornadas y con menos juntas. El
  ladrillo, en cambio, lleva más piezas por metro cuadrado, pero es el material de mampostería
  más usado en obra en Paraguay y se adapta a casi cualquier tipo de pared.
</p>
