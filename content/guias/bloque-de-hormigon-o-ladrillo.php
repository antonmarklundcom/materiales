<h2>Cuándo conviene cada uno</h2>
<p>
  El bloque de hormigón conviene cuando lo que más pesa es levantar mucha pared rápido: muros
  perimetrales y cercos, galpones, depósitos y obras donde el plazo apura. Sirve tanto para
  pared portante como para cerramiento simple, y también se usa en cimientos de poca altura y
  en muros de contención livianos, justamente porque sus huecos se pueden armar. Qué medida de
  bloque va depende del espesor del muro y de si es portante o de cerco: contalo en el pedido.
</p>
<p>
  El ladrillo sigue siendo la opción de la mampostería tradicional de vivienda. El común macizo
  va en paredes portantes, muros divisorios y cerramientos que después se revocan; el hueco es
  el más habitual para tabiques internos y cerramientos sin función portante, porque pesa menos
  y carga menos sobre la losa. Si la pared va a quedar a la vista sin revoque, lo que corresponde
  es el <a href="/materiales/ladrillo-prensado/">ladrillo visto o prensado</a>. Y si tu duda es
  entre esos dos ladrillos, la guía <a href="/guias/ladrillo-comun-vs-hueco/">ladrillo común vs
  hueco</a> los compara en detalle.
</p>
<p>
  No son excluyentes. Una misma obra puede llevar bloque en el cerco perimetral o en el
  depósito del fondo y ladrillo en la vivienda. Lo que sí tiene que confirmar el profesional a
  cargo es qué muros son portantes y qué pieza corresponde en cada uno.
</p>

<h2>Muros armados: cuándo se rellena el bloque</h2>
<p>
  La ventaja propia del bloque es que se puede armar por dentro. Es habitual pasar hierro
  vertical por algunos huecos y llenarlos con hormigón para darle rigidez al muro, sobre todo en
  cercos y muros altos. Para eso se usa bloque estructural, y conviene confirmar que el hueco
  tenga el diámetro adecuado para que la <a href="/materiales/varilla-de-hierro/">varilla de
  hierro</a> pase sin apretarse. Si la pared va a llevar ese relleno, avisalo desde el primer
  pedido, porque cambia el tipo de bloque que corresponde.
</p>
<p>
  Otro punto que se suele pasar por alto es la regularidad de la pieza. En el bloque, una
  diferencia de pocos milímetros entre unidades se acumula rápido en una pared larga, y un
  bloque golpeado en el traslado pierde escuadra y complica el asentado. En el ladrillo, lo que
  hay que mirar es la cocción: uno mal cocido suena hueco al golpearlo y se desarma con el
  tiempo, y la medida exacta varía según la olería. Tampoco confundas el bloque de cemento con el
  <a href="/materiales/adoquines/">adoquín</a>: son productos distintos y no se reemplazan.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  Para bloque, pasá los metros cuadrados de muro, el espesor, si es portante o de cerco y si va
  con relleno de hormigón y hierro, y pedí que te hagan la conversión a unidades o palets.
  Preguntá si cotiza por unidad o por palet antes de comparar dos presupuestos, y tené en cuenta
  que el flete pesa bastante en el total por el peso del material. Para ladrillo, pasá los
  metros cuadrados, el tipo y la medida, y preguntá si el millar es puesto en obra o retirado en
  depósito y cómo se hace la descarga. Para el número rápido de piezas por metro cuadrado, usá la
  <a href="/calculadoras/ladrillos-por-m2/">calculadora de ladrillos o bloques por m²</a>.
</p>
