<h2>Stock real o "te consigo"</h2>
<p>
  Antes de pedir precio, conviene entender con qué corralón estás hablando: hay proveedores que
  tienen el material en su propio depósito, listo para cargar el mismo día, y hay otros que
  trabajan por encargo, es decir, te cotizan y después consiguen el material con un tercero. Las
  dos formas son válidas y se usan todo el tiempo en Paraguay, pero cambian los tiempos de
  entrega y el margen de imprevistos: si el corralón no tiene stock propio de lo que necesitás
  —por ejemplo <a href="/materiales/cemento-y-cal/">cemento o cal</a> en plena temporada alta, o
  algún ítem de <a href="/materiales/aridos/">áridos</a> que depende de una cantera con la que
  no trabajan seguido— el plazo real de entrega puede estirarse más de lo que esperás.
</p>
<p>
  No hace falta descartar a un proveedor solo porque trabaje por encargo, pero sí conviene
  preguntar directamente: "¿esto lo tenés en depósito o lo encargás?". La respuesta te dice qué
  tan firme es la fecha de entrega que te están dando y si conviene dejar margen en el cronograma
  de obra. Lo mismo aplica a materiales que parecen simples pero tienen variantes, como los
  distintos tipos dentro de <a href="/materiales/ladrillos-y-bloques/">ladrillos y bloques</a>:
  fijate que el corralón tenga justo la variante que pediste, no una parecida, porque a veces
  ofrecen "algo similar" para no perder la venta.
</p>

<h2>El flete pesa más de lo que pensás</h2>
<p>
  En materiales de construcción el flete suele influir tanto en el costo final como el material
  en sí, sobre todo en áridos, ladrillos y cualquier cosa que se venda por volumen o por peso. Por
  eso conviene preguntar siempre si la cotización que te están pasando incluye el flete hasta tu
  obra o si es solo el valor del material puesto en el corralón. Es un error común comparar dos
  presupuestos donde uno incluye flete y el otro no: en apariencia uno parece más barato, pero al
  sumar el transporte puede terminar siendo el más caro de los dos.
</p>
<p>
  También conviene preguntar por el tiempo estimado de entrega a tu zona, porque no todos los
  corralones cubren las mismas distancias con la misma rapidez, y algunos cobran distinto según
  la accesibilidad del terreno o si el camión puede entrar hasta el lugar de descarga. Si tu obra
  queda en una zona de acceso complicado —calle de tierra, entrada angosta, poco lugar para
  maniobrar— avisá esto antes de pedir el precio, porque puede cambiar el tipo de vehículo que
  usan y, con eso, el costo del flete.
</p>

<h2>Forma de pago y comprobante</h2>
<p>
  Antes de cerrar una compra grande, preguntá qué formas de pago acepta el corralón y si hacen
  algún descuento por volumen o por pago al contado, porque no todos manejan la misma política y
  a veces conviene reordenar la compra —por ejemplo, juntar en un solo pedido lo que ibas a
  comprar en dos etapas— para acceder a mejores condiciones. También es importante confirmar que
  el proveedor entregue boleta o factura por la compra, tanto para tener respaldo del gasto como
  para cualquier reclamo posterior si el material llega con algún problema.
</p>
<p>
  Otro punto que se suele dejar para el final, y que conviene resolver antes: preguntá si el
  corralón acepta devolución de sobrantes, sobre todo en materiales que se compran por bolsa o
  por unidad, como cemento o cal, o en áridos donde calcular el volumen exacto es difícil y casi
  siempre queda un remanente. Un proveedor que acepta devolución de lo que no se usó —con las
  condiciones que corresponda, como que el envase esté intacto— te da más margen para pedir un
  poco de más sin miedo a perder esa diferencia.
</p>

<h2>Comparar más de un presupuesto</h2>
<p>
  El paso que más tiempo ahorra a la larga es simple: pedí cotización a más de un corralón antes
  de decidir, y compará no solo el precio del material sino el flete, el plazo de entrega, la
  forma de pago y si dan boleta. Un presupuesto que a primera vista parece más caro puede terminar
  siendo el más conveniente si incluye el flete, si el plazo es más corto o si el proveedor tiene
  stock real en vez de trabajar por encargo. Comparar bien también te da una base para negociar:
  si un corralón te da mejores condiciones de pago o de flete, se lo podés mencionar al resto
  antes de decidir.
</p>
