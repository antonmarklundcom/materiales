<h2>Cuándo conviene cada uno</h2>
<p>
  La cerámica sigue siendo el piso más usado en obra paraguaya porque rinde de sobra en
  ambientes de uso normal: dormitorios, baños, cocinas de una casa y rincones con muchos cortes.
  Ahí lo que hay que mirar es el PEI, la escala que indica cuánto tránsito aguanta el esmalte:
  un PEI bajo alcanza para un dormitorio pero se queda corto en un living con mucho paso. En el
  baño, pedí que la pieza sea antideslizante, porque un esmaltado brilloso sin ese tratamiento
  resbala mucho una vez mojado.
</p>
<p>
  El porcelanato es el que conviene cuando el piso va a recibir tránsito constante: living,
  cocinas con derrames y limpieza frecuente, locales comerciales. También es el camino si
  buscás el aspecto de la madera sin su mantenimiento, con el porcelanato símil madera en
  dormitorios o living. Para una galería, un patio o una vereda, algunos porcelanatos sirven si
  son antideslizantes y aptos para intemperie; aclaralo antes de elegir el modelo, porque no
  todos lo son.
</p>
<p>
  No hace falta elegir uno solo para toda la casa. Si el presupuesto de la obra no da para
  porcelanato en toda la superficie, una salida habitual es ponerlo en las zonas de paso y
  resolver con cerámica los ambientes de menor exigencia. El error que sí conviene evitar es el
  contrario: comprar cerámica pensando que va a rendir igual que el porcelanato en un ambiente
  de paso pesado. Si todavía estás comparando con otras opciones para renovar un piso existente,
  la guía <a href="/guias/piso-vinilico-o-porcelanato/">piso vinílico o porcelanato</a> suma esa
  alternativa.
</p>

<h2>Colocación: base, adhesivo y junta</h2>
<p>
  El porcelanato pide el adhesivo reforzado, no el común de cerámica: por su peso y su baja
  absorción necesita mejor agarre, y con el adhesivo equivocado la pieza termina despegándose
  con el tiempo. Si además es rectificado —bordes cortados a escuadra—, permite colocar con
  junta mínima y deja un piso más continuo, pero exige una superficie bien nivelada y un
  colocador con experiencia. Una pieza sin rectificar lleva una junta más ancha para disimular
  la diferencia de medida entre placas.
</p>
<p>
  En la cerámica, el formato también cambia la exigencia sobre la base: las piezas chicas
  disimulan mejor un contrapiso con pequeñas irregularidades, mientras que los formatos grandes
  dan menos juntas pero marcan cualquier desnivel. En el porcelanato, la terminación pulida
  resbala más al mojarse que la mate, y en la cerámica pasa lo mismo con el esmaltado brilloso
  sin tratamiento: en zonas húmedas o de mucho tránsito, priorizá mate o antideslizante. El adhesivo, la pastina y el zócalo se cotizan aparte; mirá el
  <a href="/materiales/adhesivo-para-ceramica/">adhesivo y la pastina</a> que corresponden a
  cada pieza.
</p>

<h2>Qué pedirle al proveedor</h2>
<p>
  Llegá al pedido con los metros cuadrados de cada ambiente y con el uso de cada uno: si es de
  mucho tránsito, si se moja o si es exterior. Con eso, pedí que te confirmen el formato, la
  terminación —pulido, mate o símil madera—, si la pieza es rectificada y, en la cerámica, el
  PEI y si es antideslizante. Preguntá qué adhesivo corresponde a la pieza elegida y sumá en el
  mismo pedido la pastina y el zócalo, así comparás el costo del piso colocado y no sólo el de
  la caja.
</p>
<p>
  Como se vende en caja cerrada, la cantidad siempre se redondea hacia arriba. Pedí además un
  excedente para cortes, roturas y repuestos futuros, así no tenés que salir a buscar la misma
  pieza cuando haga falta cambiar una. Si todavía no sacaste bien los metros, la guía
  <a href="/guias/como-hacer-un-computo-metrico/">cómo hacer un cómputo métrico</a> te ordena la
  medición antes de pedir.
</p>
