<h2>Diferencias que importan</h2>
<p>
  La duda entre <a href="/materiales/porcelanato/">porcelanato</a> y
  <a href="/materiales/ceramica-para-piso/">cerámica para piso</a> aparece en casi toda obra
  nueva y en casi toda reforma, y no se resuelve mirando sólo el diseño de la pieza. Las dos se
  venden por metro cuadrado en caja cerrada y las dos se pegan con adhesivo sobre el
  contrapiso, pero el cuerpo de cada una es distinto. La cerámica —el cerámico esmaltado que en
  obra se pide como piso cerámico o baldosa— tiene un cuerpo más poroso cubierto por una capa
  de esmalte, que es la que le da el color y el brillo. Esa porosidad la hace más liviana y más
  fácil de cortar, pero también más sensible a un golpe fuerte. El porcelanato tiene un cuerpo
  más compacto: absorbe menos agua, es más duro y aguanta mejor el tránsito, las manchas y el
  uso diario sin perder la terminación.
</p>
<p>
  Esa diferencia de cuerpo define a qué ambiente va cada pieza, qué adhesivo lleva y qué tan
  nivelada tiene que estar la base.
</p>
