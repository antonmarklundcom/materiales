<h2>Peso y estructura</h2>
<p>
  Antes de mirar terminación o estética, la primera diferencia entre chapa y teja es el peso
  que cada una pone sobre la estructura. La <a href="/materiales/chapa-de-zinc/">chapa de
  zinc</a> es liviana, por eso se monta rápido y sobre tirantería relativamente simple; es la
  cobertura típica de galpones, depósitos y ampliaciones donde no hace falta sobredimensionar
  nada. La teja, en cambio, es mucho más pesada por unidad de superficie: al ser piezas de
  barro cocido, como la <a href="/materiales/teja-espanola/">teja española</a>, la estructura
  de tirantillo o clavaderas que la sostiene tiene que estar calculada para ese peso adicional,
  y eso normalmente significa más madera o más apoyos que en un techo de chapa equivalente. Si
  ya tenés una estructura liviana pensada para chapa y estás dudando si pasarte a teja,
  conversalo primero con quien calculó los tirantes: cambiar de cobertura sobre una estructura
  ya definida puede exigir refuerzos que no estaban en el presupuesto original.
</p>
<p>
  La pendiente mínima también entra en esta cuenta. La teja necesita una pendiente más
  pronunciada para que el agua escurra bien entre piezas sin filtrarse, mientras que varios
  perfiles de chapa —sobre todo la <a href="/materiales/chapa-trapezoidal/">chapa
  trapezoidal</a>, pensada para salvar luces más grandes entre apoyos— toleran techos algo más
  planos. Si el diseño de tu obra ya definió una pendiente baja, conviene confirmar antes de
  avanzar si esa pendiente alcanza para teja o si el proyecto quedó pensado para chapa desde el
  principio.
</p>

<h2>Estética y estilo de la obra</h2>
<p>
  La elección también depende de qué estilo busca la fachada. La teja —tanto la española de
  perfil curvo como la <a href="/materiales/teja-francesa/">teja francesa</a> de encastre
  plano— se asocia a construcciones de estilo colonial, campo o tradicional, y suele elegirse
  cuando una obra busca esa terminación clásica en corredores, galerías y frentes a la vista. La
  chapa, en cambio, se lee como una solución más utilitaria en galpones y depósitos, aunque en
  viviendas de diseño moderno una chapa bien elegida —sobre todo una
  <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a> con buena terminación— se
  usa también a la vista, sin que eso implique un techo de "obra en construcción". No hay una
  opción más correcta que otra: depende del estilo que ya tenga el resto de la fachada y de qué
  imagen buscás para la casa o el local.
</p>

<h2>Mantenimiento a lo largo de los años</h2>
<p>
  El mantenimiento de cada cobertura tiene una lógica distinta. La teja es un material rígido
  y puede quebrarse con un golpe —una rama caída, un pisotón al subir a limpiar canaletas— y
  ahí el mantenimiento consiste en detectar e ir reponiendo piezas sueltas o trizadas antes de
  que empiecen a filtrar agua entre las juntas. La chapa no se quiebra de esa forma, pero su
  punto débil es la oxidación con el tiempo si el galvanizado se dañó o quedó parejo apenas de
  fábrica: ahí el mantenimiento pasa por revisar el estado de la superficie y, según el caso,
  repintar para frenar el óxido antes de que perfore la chapa. En los dos casos conviene una
  revisión periódica del techo, pero el tipo de problema que hay que buscar —piezas rotas en un
  caso, manchas de óxido en el otro— es distinto según qué cobertura elegiste.
</p>

<h2>Costo de instalación, no sólo de material</h2>
<p>
  A la hora de comparar, el costo que más pesa suele ser el de la mano de obra, no sólo el del
  material en sí. Colocar teja lleva más tiempo por obra: son piezas unitarias que se acomodan
  una por una sobre el tirantillo, respetando el solape entre hileras, mientras que una chapa
  cubre de una sola vez una superficie mucho más grande por pieza y se fija con tornillería
  autoperforante en una fracción del tiempo. Eso hace que, incluso cuando el material en sí
  parezca similar en valor, la instalación de teja demande más jornales de un oficial con
  experiencia en ese tipo de colocación, mientras que una chapa la puede montar una cuadrilla
  más chica en menos días. Sumá también que la estructura de apoyo para teja —más robusta, como
  se vio arriba— implica su propio costo de mano de obra en carpintería antes de que llegue la
  cobertura.
</p>
