<h2>Por qué no hay una cifra única</h2>
<p>
  "Cuánto cuesta construir una casa en Paraguay" es de las preguntas más buscadas del rubro, y
  también de las que menos sirve responder con un número: dos casas de la misma superficie
  pueden costar montos muy distintos según la terminación, el terreno y hasta el momento del
  año en que se compren los materiales. Lo que sí se puede explicar son los factores que mueven
  ese costo, para que cuando pidas cotización sepas qué preguntar y qué comparar entre
  proveedores.
</p>

<h2>Superficie y forma de la construcción</h2>
<p>
  El dato más obvio es cuántos metros cuadrados vas a construir, pero pesa casi tanto la forma:
  una planta muy recortada, con muchos ángulos y desniveles, gasta más material por m² que una
  planta simple y compacta, porque cada esquina y cada cambio de nivel suma
  <a href="/materiales/ladrillo-comun/">ladrillo</a>, hierro y mano de obra que una planta
  rectangular no necesita. Lo mismo pasa con la cantidad de baños y cocinas: cada uno agrega
  cañería, revestimiento y artefactos que no están en un dormitorio o un living. Antes de pedir
  cotización conviene tener al menos un plano aproximado con la superficie por ambiente.
</p>

<h2>Los rubros que se cotizan por separado</h2>
<p>
  Una obra no es un solo pedido: es una sucesión de rubros que se compran en momentos distintos.
  La estructura arranca con <a href="/materiales/varilla-de-hierro/">hierro</a> y
  <a href="/materiales/cemento/">cemento</a> para cimientos, columnas y losas; sigue la
  mampostería con <a href="/materiales/ladrillo-comun/">ladrillo</a> o bloque; después vienen la
  cubierta (chapa, teja o losa), las aberturas, las instalaciones y, al final, los revestimientos
  y terminaciones. Cada rubro tiene su propia lógica de precio —el hierro se mueve con la
  cotización internacional, la chapa con el calibre y la superficie, el revestimiento con la
  categoría del producto— así que sumar todo en una sola cifra desde el inicio es difícil incluso
  para un profesional. Lo que sí se puede hacer es pedir cotización rubro por rubro a medida que
  la obra avanza, con la cantidad real que necesitás en cada etapa.
</p>

<h2>Terminación: la variable que más cambia el total</h2>
<p>
  A igual superficie y misma estructura, la terminación es lo que más mueve el costo final. Un
  piso cerámico y un porcelanato importado no cuestan lo mismo, ni una chapa de zinc simple y una
  <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a> con aislación. Esto no es
  un defecto del rubro: es la misma lógica que en cualquier otra compra grande, donde la
  categoría del producto pesa tanto como la cantidad. Por eso, cuando compares presupuestos de
  distintos proveedores, fijate que estén cotizando la misma categoría de material y no sólo la
  misma cantidad: dos cotizaciones de "revestimiento de piso" pueden estar hablando de productos
  con precios muy distintos.
</p>

<h2>Cómo llegar a un número propio</h2>
<p>
  El primer paso realista es un <a href="/guias/como-hacer-un-computo-metrico/">cómputo
  métrico</a>: pasar el plano a cantidades concretas de cada material, rubro por rubro. Con esas
  cantidades ya definidas, las <a href="/calculadoras/">calculadoras</a> de este sitio ayudan a
  ajustar los números más comunes —cuánto <a href="/calculadoras/hormigon-por-m3/">hormigón,
  cemento y arena</a> por m³, o cuántos <a href="/calculadoras/ladrillos-por-m2/">ladrillos o
  bloques</a> por m² de pared— sin necesidad de memorizar dosificaciones. Con esas cantidades ya
  armadas, pedir cotización a varios proveedores del rubro que corresponda te da un rango real
  para tu obra puntual, que es mucho más útil que cualquier cifra genérica que circule en
  internet.
</p>

<h2>Qué NO define el costo</h2>
<p>
  Una aclaración que conviene hacer: el costo de los materiales no incluye la mano de obra, los
  honorarios profesionales, los trámites municipales ni el terreno. Cuando compares un
  presupuesto "todo incluido" de una constructora contra la suma de materiales que cotizás acá,
  estás comparando cosas distintas. Esta guía y las calculadoras del sitio te ayudan a entender y
  cotizar la parte de materiales; la mano de obra y los honorarios los cotiza por separado quien
  vaya a ejecutar la obra.
</p>
