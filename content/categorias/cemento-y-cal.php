<h2>Qué incluye esta categoría</h2>
<p>
  Acá agrupamos los aglomerantes básicos de cualquier obra: el <a href="/materiales/cemento/">cemento</a>
  para todo lo que es mampostería, contrapisos y estructura, la <a href="/materiales/cal-hidratada/">cal
  hidratada</a> para el revoque fino y la pintura a la cal de siempre, y la <a
  href="/materiales/cal-viva/">cal viva</a> para quien todavía apaga su propia cal en obra. Si lo que
  buscás es no mezclar en el sitio, está el <a href="/materiales/hormigon-elaborado/">hormigón
  elaborado</a>, que llega en mixer listo para volcar en losa, contrapiso o zapata. Y para la terminación
  de pisos y revestimientos, el <a href="/materiales/adhesivo-para-ceramica/">adhesivo para cerámica</a>
  cierra el rubro con lo necesario para pegar cerámica y porcelanato y tomar juntas con pastina. Entre
  cemento y cal de obra hay una diferencia de uso clara: el cemento da resistencia estructural, la cal de
  obra da trabajabilidad y terminación —por eso casi toda mezcla de revoque y pintura a la cal combina
  ambos en distintas proporciones según la etapa.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  El cemento y la cal para construcción se venden por bolsa cuando el volumen es de obra chica, y por
  palet o camión completo cuando el pedido es para una obra en marcha con consumo semanal. El hormigón
  elaborado es la excepción: ahí la unidad es el metro cúbico y el pedido va directo con la planta o el
  distribuidor de mixer, coordinando horario de llegada porque el material tiene un tiempo de trabajabilidad
  limitado una vez cargado. En todos los casos el flete pesa en el presupuesto según la distancia a tu
  zona y la cantidad de viajes que haga falta, así que conviene agrupar en una sola consulta lo que vas a
  necesitar para varias etapas —cemento para mampostería junto con cal para revoque, por ejemplo— y así
  cerrar el flete de una sola vez. Decinos qué material y qué cantidad estimás para cada etapa de tu obra y
  te ayudamos a armar el pedido sin duplicar viajes. Si todavía no elegiste dónde comprar, la
  guía <a href="/guias/como-elegir-un-corralon/">Cómo elegir un corralón</a> repasa qué mirar
  antes de decidirte por un proveedor.
</p>

