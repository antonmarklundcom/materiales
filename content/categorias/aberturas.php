<h2>Qué incluye esta categoría</h2>
<p>
  Acá entran todas las aberturas de una obra o una reforma: las <a href="/materiales/puertas-de-madera/">puertas de madera</a>
  macizas para la entrada, la <a href="/materiales/puerta-placa/">puerta placa</a> liviana para
  interiores, y la <a href="/materiales/puertas-de-chapa/">puerta de chapa</a> cuando el destino
  es un depósito, una sala de máquinas o un acceso de servicio. Del lado de las ventanas, la
  <a href="/materiales/ventanas-de-aluminio/">ventana de aluminio</a> es la que domina la obra
  nueva, con su vidrio y su mosquitero como parte de la misma cotización. Cuando la pieza de
  vidrio va sola —una mampara, un frente, una baranda— entrás a
  <a href="/materiales/vidrio-templado/">vidrio templado</a>. Y para el cerramiento exterior,
  los <a href="/materiales/portones-y-rejas/">portones y rejas</a>
  cubren desde el portón de entrada hasta la reja de una ventana que da a la calle. Ninguna de
  estas piezas se elige por catálogo sola: el material define el uso, pero el vano real de tu
  obra define casi todo lo demás.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  La mayoría de las aberturas paraguayas se hacen sobre <strong>medida de vano</strong>, no se
  compran de un estante: el ancho y el alto tomados en obra, con el tipo de apertura y si va con
  marco o contramarco, son el dato que arranca cualquier cotización seria. Las líneas
  industriales —aluminio, algunas puertas placa— tienen medidas más o menos estandarizadas y por
  eso salen más rápido; los trabajos de herrería y las puertas de madera hechas a pedido llevan
  su propio plazo de fabricación, así que conviene pedir el presupuesto con margen. Cuando la
  obra tiene varios vanos —una casa completa, por ejemplo— conviene armar una lista por ambiente
  con ancho, alto y tipo de apertura de cada uno: así el proveedor cotiza todo junto y vos
  comparás presupuestos que incluyen lo mismo. Aclarar de entrada si buscás sólo el producto o
  también la colocación evita el malentendido más común entre dos presupuestos que, en los
  papeles, no se parecen en nada.
</p>
