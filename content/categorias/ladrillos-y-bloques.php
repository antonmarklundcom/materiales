<h2>Qué incluye esta categoría</h2>
<p>
  Bajo ladrillos y bloques entran varios materiales que no se reemplazan entre sí, aunque a
  veces se confundan en el pedido. El <a href="/materiales/ladrillo-comun/">ladrillo común</a>
  es el de mampostería de todos los días, para paredes que van a llevar revoque. El
  <a href="/materiales/ladrillo-hueco/">ladrillo hueco</a> se usa en tabiques divisorios y
  paredes livianas donde no hace falta la resistencia de un macizo. El
  <a href="/materiales/ladrillo-prensado/">ladrillo prensado</a> —el que la gente pide como
  "ladrillo visto"— va sin revoque, a la vista, en fachadas y cercos. El
  <a href="/materiales/bloque-de-hormigon/">bloque de hormigón</a> arma paredes más rápido con
  menos piezas por metro cuadrado, y se usa mucho en obras que corren contra el tiempo; si dudás
  entre las dos piezas, la guía <a href="/guias/bloque-de-hormigon-o-ladrillo/">bloque de
  hormigón o ladrillo</a> las compara. El
  <a href="/materiales/tejuelon/">tejuelón</a> es otra cosa: no es para pared, sino para armar
  losas junto con las viguetas. Y el <a href="/materiales/ladrillo-refractario/">ladrillo
  refractario</a> es específico para donde hay fuego directo, como parrillas y hornos, porque el
  ladrillo común no aguanta esa temperatura sin rajarse.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Casi todos estos materiales se piden por <strong>millar</strong>, así que el primer dato que
  necesita el proveedor es cuántos millares vas a levantar, calculado sobre el metro cuadrado
  real de pared o losa de tu obra —no sobre una estimación al ojo, porque ahí es donde más se
  desperdicia o falta material. El bloque de hormigón suele cotizarse por unidad o por palet, y
  conviene confirmar cuál de las dos formas usa el proveedor antes de comparar precios entre
  cotizaciones. El flete pesa bastante porque el peso por millar es considerable, así que la
  zona de entrega y el acceso a la obra influyen en el total. Si tu obra necesita más de un tipo
  —por ejemplo ladrillo común para pared y ladrillo hueco para tabiques, o ladrillo prensado
  para el frente y ladrillo común para el resto— conviene pedirlos juntos para no pagar dos
  fletes distintos el mismo día. Antes de pedir, la
  <a href="/calculadoras/ladrillos-por-m2/">calculadora de ladrillos o bloques por m²</a> te da
  una estimación de cuántas piezas necesitás según el metro cuadrado de tu pared.
</p>

