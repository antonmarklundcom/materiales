<h2>Qué incluye esta categoría</h2>
<p>
  Bajo "hierro" o "fierro de construcción" entra todo lo que arma el esqueleto de una obra
  antes del hormigón. La <a href="/materiales/varilla-de-hierro/">varilla de hierro</a> —el
  hierro nervurado de columnas, vigas y losas— es la base de cualquier estructura de hormigón
  armado, y se completa con la <a href="/materiales/malla-electrosoldada/">malla
  electrosoldada</a> cuando el armado es de contrapiso, vereda o losa liviana y no vale la pena
  atar barra por barra. Para sujetar esa armadura antes de hormigonar está el
  <a href="/materiales/alambre-negro/">alambre negro</a>, y para la carpintería de obra —
  encofrados, tablas, listones— los <a href="/materiales/clavos/">clavos</a>. Cuando la
  estructura no es de hormigón sino metálica —techos, entrepisos, galpones— entran los
  <a href="/materiales/perfiles-metalicos/">perfiles metálicos</a>: caños estructurales,
  ángulos y perfiles C o U. Y si lo que buscás es cerrar un perímetro y no levantar una
  estructura, el <a href="/materiales/tejido-de-alambre/">tejido de alambre</a> es el material
  del rubro que corresponde, con su alambre de púas y su alambre galvanizado.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada material de este rubro tiene su propia unidad de venta —barra, kilo, tonelada, paño,
  rollo, metro lineal— y mezclarlas en el mismo pedido no es un problema: el proveedor las
  convierte. Lo que sí conviene poner siempre es la <strong>zona de entrega</strong>, porque el
  flete de hierro y perfiles pesa en el costo final y varía según distancia y acceso a la obra.
  Si tu compra combina varios de estos materiales —varilla más malla más alambre para atar,
  por ejemplo, o perfiles más chapa—, pedilos juntos en la misma consulta: aparte de ahorrar
  flete, el proveedor puede ofrecerte mejor precio por el volumen conjunto. Y si tenés el plano
  o el cálculo estructural a mano, pasá diámetros, medidas y cantidades tal cual figuran ahí;
  si no lo tenés, contá qué vas a construir y el proveedor te ayuda a definir qué pedir.
</p>
