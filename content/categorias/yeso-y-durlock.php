<h2>Qué incluye esta categoría</h2>
<p>
  La construcción en seco reemplaza el ladrillo y el revoque húmedo por un sistema de capas
  atornilladas, y en esta categoría están todas las piezas de ese sistema. La
  <a href="/materiales/placa-de-yeso/">placa de yeso</a> es la cara visible: arma tabiques
  interiores y cielorrasos suspendidos, con
  variantes para zonas húmedas y para donde se exige resistencia al fuego. Esa placa no se
  sostiene sola: necesita el esqueleto de
  <a href="/materiales/perfiles-para-durlock/">perfiles para durlock</a>, montantes y soleras
  galvanizados que definen la separación de la estructura y, con eso, cuán firme queda el
  tabique o cuán parejo el cielorraso. Para el enlucido de paredes de mampostería tradicional,
  las reparaciones y las molduras interiores está el
  <a href="/materiales/yeso-en-polvo/">yeso en polvo</a>, que es otro producto y otro uso:
  no arma placas, deja lisa la superficie que ya existe. Entre placa y placa van también la
  masilla para juntas y la cinta de papel, que disimulan la unión hasta dejarla invisible bajo
  la pintura.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada material de esta categoría se pide con un dato distinto: la placa por metro cuadrado de
  tabique o cielorraso a cubrir, los perfiles por metro cuadrado y altura (para calcular
  cuántas barras de montante y solera salen), y el yeso en polvo por bolsa según la superficie
  a enlucir. La masilla y la cinta de juntas conviene pedirlas en la misma consulta que la
  placa, porque van de la mano y así el flete no se fracciona en varios envíos. Contanos si es
  tabique o cielorraso, los metros cuadrados aproximados y si hay zonas húmedas de por medio, y
  armamos la cotización con placa, perfilería y terminación juntas.
</p>
