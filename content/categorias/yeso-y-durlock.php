<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada material de esta categoría se pide con un dato distinto: la placa por metro cuadrado de
  tabique o cielorraso a cubrir, los perfiles por metro cuadrado y altura (para calcular
  cuántas barras de montante y solera salen), y el yeso en polvo por bolsa según la superficie
  a enlucir. La masilla y la cinta de juntas conviene pedirlas en la misma consulta que la
  placa, porque van de la mano y así el flete no se fracciona en varios envíos. Contanos si es
  tabique o cielorraso, los metros cuadrados aproximados y si hay zonas húmedas de por medio, y
  armamos la cotización con placa, perfilería y terminación juntas.
</p>
<h3>Un ejemplo con números</h3>
<p>
  Un tabique divisorio de <strong>5 m de largo por 2,60 m de alto</strong>, con placa de los dos
  lados y montantes cada 40 cm. Con placas de 1,20 × 2,40 m, barras de 2,60 m (los largos son
  sólo de ejemplo: confirmá los de tu proveedor) y 10 % de desperdicio de placa, la
  <a href="/calculadoras/durlock-por-m2/">calculadora de placas de yeso y perfiles</a> da
  <strong>26 m²</strong> de placa, <strong>10 placas</strong>, <strong>14 montantes</strong> de
  una barra cada uno y <strong>4 barras de solera</strong> para arriba y abajo. Con esos 26 m²
  pedí también la masilla, la cinta y los tornillos, que la calculadora no cuenta.
</p>

