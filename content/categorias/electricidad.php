<h2>Qué incluye esta categoría</h2>
<p>
  La instalación eléctrica de una obra se arma con tres piezas que trabajan juntas, y cada una
  se pide por separado. El <a href="/materiales/cable-electrico/">cable eléctrico</a> es lo que
  lleva la corriente desde el tablero hasta cada toma, luz y artefacto: se elige por la sección
  del conductor y por el circuito que alimenta, así que un mismo pedido suele mezclar secciones
  distintas para iluminación, tomas y equipos más exigentes. El
  <a href="/materiales/tablero-electrico/">tablero eléctrico</a> es el punto donde entra la
  energía y se reparte en circuitos, con sus protecciones: ahí se decide cuántos circuitos tiene
  la casa y qué se corta cuando algo falla. Y el
  <a href="/materiales/cano-conduit/">caño conduit</a> —el caño corrugado que va embutido en
  paredes y losa, o el rígido a la vista— junto con la canaleta para cable es el camino por donde el
  cable viaja protegido, embutido en la pared o por fuera cuando no se puede romper.
</p>
<p>
  Qué cable, qué tablero y qué protecciones corresponden a cada circuito lo define el
  electricista que va a hacer o revisar la instalación: esta página te ayuda a ordenar el
  pedido, no a calcular la instalación.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada pieza tiene su forma de pedirse. El cable se cotiza <strong>por metro o por rollo</strong>
  y siempre <strong>por sección</strong>: para una obra completa conviene el rollo, y para un
  arreglo o una ampliación alcanzan los metros sueltos. El tablero se pide según la
  <strong>cantidad de circuitos</strong> que va a manejar, y conviene aclarar si querés el
  tablero armado o los componentes sueltos. El caño conduit y la canaleta se venden
  <strong>por tira</strong>, y varían según el diámetro o el ancho y si el recorrido es
  embutido o a la vista.
</p>
<p>
  Antes de consultar, confirmá las secciones de cable y las protecciones con tu electricista y
  pasale al proveedor su lista tal cual. Pedí todo en la misma consulta —cable, tablero, caños,
  cajas y accesorios de conexión— para que el flete salga en un solo viaje, y aclará tu zona de
  entrega porque el flete se cotiza aparte. Si todavía no tenés las cantidades, la guía
  <a href="/guias/como-hacer-un-computo-metrico/">cómo hacer un cómputo métrico</a> te ayuda a
  ordenar metros y piezas antes de pedir, y si la obra recién empieza, la guía
  <a href="/guias/de-que-depende-el-costo-de-construir-en-paraguay/">de qué depende el costo de
  construir en Paraguay</a> muestra dónde entra esta partida.
</p>
