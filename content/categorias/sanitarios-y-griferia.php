<h2>Qué incluye esta categoría</h2>
<p>
  Los <strong>sanitarios y la grifería</strong> completan los puntos de uso del agua en el
  baño y la cocina. Para el baño, el <a href="/materiales/inodoro/">inodoro</a> se pide con
  su cisterna de baño o mochila: conviene definir el conjunto según el espacio disponible y
  la salida del desagüe; al lado, la <a href="/materiales/ducha-higienica/">ducha higiénica</a>
  cumple la función del bidet cuando no hay lugar para otro artefacto. La
  <a href="/materiales/canilla-de-lavatorio/">canilla de lavatorio</a>
  se elige según la altura de la bacha y las perforaciones donde se monta. Para la pileta,
  la <a href="/materiales/griferia-de-cocina/">grifería de cocina</a> necesita un pico con
  alcance cómodo para lavar y espacio para moverlo. En ambos ambientes podés pedir
  monocomando, siempre que las conexiones correspondan al modelo. La
  <a href="/materiales/llave-de-ducha/">llave de ducha</a> controla el paso del agua y, cuando
  es mezcladora, combina la fría con la caliente de la instalación; la ducha de mano puede
  sumarse como accesorio compatible. Si el calentamiento se resuelve en el propio equipo,
  corresponde una <a href="/materiales/ducha-electrica/">ducha eléctrica</a>. Son productos
  distintos, así que contá cómo llega el agua al baño antes de elegir por apariencia.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Estos productos se cotizan por <strong>unidad</strong>, indicando cantidad, montaje,
  medidas y terminación. Para una renovación, pasá las medidas de las conexiones existentes;
  para obra nueva, coordiná con el instalador qué piezas van antes de cerrar paredes y pisos.
  Armá el listado por ambiente y pedí que cada oferta detalle qué trae: asiento y mecanismo
  de descarga en el inodoro, flexibles y fijaciones en las canillas, o cuerpo y accesorios en
  la ducha. Lo que no venga incluido se cotiza aparte, igual que el flete y la colocación.
  Poné tu ciudad o barrio y aclaración de acceso para que el traslado forme parte de la
  comparación. El modelo, el material del cuerpo, la terminación y los accesorios cambian
  el presupuesto. Pedir juntos los artefactos y sus conexiones ayuda a revisar compatibilidad
  antes de recibirlos; un juego del mismo color no garantiza que coincidan las medidas.
</p>

<h2>Cómo elegir entre sanitarios y grifería</h2>
<p>
  Antes que el modelo, definí dos cosas: dónde va cada pieza y si al baño llega agua caliente
  por cañería. Con eso, cada producto tiene su lugar:
