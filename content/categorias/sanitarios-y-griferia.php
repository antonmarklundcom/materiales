<p>
  La pregunta del agua caliente decide más de una compra: si llega por cañería, la ducha va con
  una mezcladora y la ducha higiénica puede ser de fría y caliente; si no llega, corresponde una
  ducha eléctrica y una ducha higiénica de una sola agua.
</p>
