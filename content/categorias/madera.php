<h2>Qué incluye esta categoría</h2>
<p>
  Para la estructura y la obra gruesa está la madera de escuadría: los
  <a href="/materiales/tirantes/">tirantes</a> que arman la estructura del techo y de
  entrepisos, los <a href="/materiales/puntales/">puntales</a> que sostienen el encofrado
  mientras el hormigón toma resistencia, y la <a href="/materiales/tabla-de-encofrado/">tabla
  de encofrado</a> con la que se arman los moldes de vigas, columnas y losas. Cuando el
  encofrado necesita mejor terminación —una losa que va a quedar vista, o menos trabajo de
  frotachado después— entra la <a href="/materiales/terciada/">terciada</a> en placa,
  fenólica o común según el uso.
</p>
<p>
  Para techos, cielorrasos y terminaciones la selección cambia: el
  <a href="/materiales/machimbre/">machimbre</a> cubre cielorrasos y techos a la vista,
  encastrado tabla con tabla; los <a href="/materiales/listones/">listones</a> hacen de
  clavadera bajo ese machimbre y de refuerzo en marcos y trabajos menores; el
  <a href="/materiales/mdf-fibrofacil/">MDF y fibrofácil</a> resuelve muebles, placares y
  revestimientos con una superficie lisa y sin vetas; y la
  <a href="/materiales/madera-dura/">madera dura</a> —curupay, lapacho y otras especies
  nativas— entra donde la pieza queda expuesta al sol y a la lluvia, o simplemente a la
  vista, como en decks, aberturas y estructuras que no se van a tapar.
</p>

