<h2>Qué incluye esta categoría</h2>
<p>
  Pedir "pintura" a secas es pedir a medias: cada superficie de la casa lleva un producto
  distinto, y elegir mal es la forma más rápida de pintar dos veces. Para paredes de revoque,
  adentro y afuera, va la <a href="/materiales/pintura-para-pared/">pintura para pared</a>, el
  látex de siempre, en versión interior para los ambientes y exterior para frentes y muros que
  reciben sol y lluvia. Antes de esa primera mano, sobre revoque nuevo, yeso o una pared que se
  desgrana, conviene dar el <a href="/materiales/sellador-para-pared/">sellador para pared</a>
  —fijador o fondo blanco—, que es lo que hace que el látex agarre y rinda parejo. Para garajes,
  galerías y patios de cemento está la
  <a href="/materiales/pintura-para-piso/">pintura para piso</a>, hecha para aguantar tránsito.
  La madera a la vista —puertas, aberturas, machimbre, muebles— se protege con
  <a href="/materiales/barniz/">barniz para madera</a>, que deja ver la veta. Y para rejas,
  portones, puertas de chapa y cualquier pieza de metal está el
  <a href="/materiales/esmalte-sintetico/">esmalte sintético</a>, con su fondo antióxido debajo.
  Si lo que tenés es una mancha de humedad o salitre, lo que corresponde no es una mano más de
  látex sino la <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>, que vive en
  <a href="/materiales/impermeabilizantes/">impermeabilizantes</a> junto con las membranas para
  techo.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  La pintura se vende por <strong>lata o balde</strong>, en los litrajes que ofrece cada
  producto, y la cantidad no sale de los metros de pared sino de los m² a pintar multiplicados
  por las manos que pide el envase. El rendimiento figura en el envase y cambia con la
  absorción de la superficie: un revoque nuevo toma mucho más que una pared ya pintada. Por
  eso, para cotizar bien, pasá los m² de cada superficie, si es interior o exterior, si es obra
  nueva o repintado y el color o la terminación que buscás. Pedí en la misma consulta todo lo
  que va con la pintura —sellador, fondo antióxido, aguarrás o diluyente, rodillos, pinceles y
  lijas—, porque son los faltantes que más frenan un trabajo a mitad de camino. El flete suele
  cotizarse aparte y depende de tu zona y del volumen del pedido. Si todavía estás terminando
  el revoque, la guía <a href="/guias/como-revocar-una-pared/">cómo revocar una pared</a>
  explica qué conviene dejar listo antes de la primera mano.
</p>
