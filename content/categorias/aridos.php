<h2>Qué incluye esta categoría</h2>
<p>
  Cuando hablamos de áridos entran varios materiales distintos, cada uno para una etapa
  distinta de la obra. La <a href="/materiales/arena-lavada/">arena lavada</a> es la que va en
  revoques, morteros finos y contrapisos donde importa que no tenga barro ni impurezas. La
  <a href="/materiales/arena-gorda/">arena gorda</a> se usa más para hormigón y contrapisos de
  mayor espesor, donde el grano más grueso da más resistencia. El <a href="/materiales/ripio/">
  ripio</a> —también conocido como canto rodado— entra en bases compactadas, drenajes y como
  parte del hormigón. La <a href="/materiales/piedra-triturada/">piedra triturada</a> (4ta, 5ta
  o 6ta según el uso) se pide para hormigón estructural y bases de pavimento. La
  <a href="/materiales/piedra-bruta/">piedra bruta</a> es la que va directo en cimientos y muros
  de contención, sin procesar. Y para movimiento de tierra y relleno están la
  <a href="/materiales/tierra-gorda/">tierra colorada</a> y el
  <a href="/materiales/escombro-relleno/">escombro para relleno</a>, cada uno según si necesitás
  tierra apta para compactar o simplemente ganar cota con material de relleno.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Los áridos se venden por <strong>metro cúbico</strong> o directamente por
  <strong>camionada</strong> (volquete), y ese dato —cuántos m³ necesitás— es lo primero que te
  va a pedir cualquier proveedor. El flete pesa bastante en el total porque un camión de áridos
  no es liviano, así que la <strong>zona de entrega</strong> y el acceso a la obra (calle
  angosta, terreno en pendiente, portón chico) influyen en cómo se arma la cotización. Si tu
  obra necesita varios áridos —por ejemplo arena y ripio para una misma losa, o piedra
  triturada junto con cemento para el hormigón— conviene pedirlos juntos en la misma consulta:
  se optimiza el flete y evitás pagar dos veces el viaje del camión. Decinos el volumen
  aproximado de cada material y la zona, y armamos la cotización completa.
</p>
