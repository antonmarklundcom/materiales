<h2>Qué incluye esta categoría</h2>
<p>
  Bajo "chapas y techos" entran soluciones bien distintas entre sí, y conviene saber cuál
  corresponde a cada situación antes de pedir presupuesto. Para un galpón, depósito o cochera
  sin uso constante, la <a href="/materiales/chapa-trapezoidal/">chapa trapezoidal</a> o la
  <a href="/materiales/chapa-de-zinc/">chapa de zinc</a> (la típica chapa acanalada o
  galvanizada) suelen alcanzar y son la opción más difundida. Cuando abajo hay un ambiente
  habitable —dormitorio, oficina, un local con gente todo el día— entra la
  <a href="/materiales/chapa-termoacustica/">chapa termoacústica</a>, con núcleo aislante que
  corta calor y ruido de lluvia. Si la idea es un techo de tejas, están la
  <a href="/materiales/teja-espanola/">teja española</a> (la teja colonial curva de siempre) y
  la <a href="/materiales/teja-francesa/">teja francesa</a>, de perfil plano y encastre. El
  <a href="/materiales/fibrocemento/">fibrocemento</a> es otra alternativa liviana y
  resistente para techos y cerramientos. Para luz
  natural sin perder cobertura está el <a href="/materiales/policarbonato/">policarbonato</a>,
  ideal para galerías y claraboyas, y para cielorrasos interiores el
  <a href="/materiales/cielorraso-de-pvc/">cielorraso de PVC</a>. Completan el techo las
  <a href="/materiales/canaletas/">canaletas para techo</a>, que evacuan el agua de lluvia
  hacia la bajada.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada material de esta categoría se cotiza distinto: chapa y fibrocemento por metro lineal o
  por chapa, tejas por unidad o por millar, policarbonato por plancha o m², cielorraso de PVC
  por m² o tablilla, canaletas por metro lineal. Lo que sí es común a todos es que el flete
  pesa en el presupuesto final según la zona de entrega, y que conviene pedir en la misma
  consulta los accesorios de terminación —cumbreras, babetas, tornillería, bajadas de agua—
  para no fraccionar el flete en varios viajes. Pasanos las medidas del techo, la pendiente y
  el material que tenés en mente, y te armamos una cotización que cubra estructura y
  terminación juntas.
</p>
