<h2>Qué incluye esta categoría</h2>
<p>
  "Caños y plomería" junta lo que arma toda la instalación sanitaria de una obra, pero son
  mundos distintos que conviene no confundir al pedir presupuesto. El
  <a href="/materiales/tanque-de-agua/">tanque de agua</a> es el punto de partida: define el
  litraje de reserva de toda la casa y de él sale el resto del cálculo. Para la evacuación de
  aguas servidas está el <a href="/materiales/cano-de-pvc/">caño de PVC</a>, el que trabaja por
  gravedad en cloaca y pluvial. Y para llevar agua fría y caliente con presión a cada artefacto
  está el <a href="/materiales/cano-de-agua/">caño de agua</a>, que se arma roscado o por
  termofusión. A los tres los acompaña una lista larga de accesorios de plomería —codos, tees,
  uniones, cupla, pegamento para PVC, teflón— que cambian según sea cañería de agua o de
  desagüe, así que conviene tenerlos claros antes de armar el pedido.
</p>
<p>
  Si el agua no viene de la red, la <a href="/materiales/bomba-de-agua/">bomba de agua</a> es la
  que la saca del pozo o la sube hasta el tanque, y el
  <a href="/materiales/presurizador-de-agua/">presurizador de agua</a> sirve cuando la presión
  que llega a las canillas es floja. Para cortar el agua de un tramo, un baño o toda la casa sin
  vaciar el tanque, cada ramal necesita su <a href="/materiales/llave-de-paso/">llave de paso</a>.
  Y donde no hay red de cloaca, el desagüe del baño termina en una
  <a href="/materiales/camara-septica/">cámara séptica</a>: confirmá con quien dirige la obra
  dónde va y cómo se conecta antes de pedir los caños.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada rubro de esta categoría se pide distinto: el tanque por unidad y litraje, los caños por
  barra y diámetro, y los accesorios de plomería por unidad, casi siempre en cantidad. La bomba,
  el presurizador, la llave de paso y la cámara séptica también se piden por unidad: pasá la
  fuente de agua o la cantidad de baños, según el caso. Lo que
  comparten es que conviene pedirlos juntos en la misma consulta —tanque, cañería,
  accesorios y, si corresponde, bomba— para que el flete se reparta en un solo viaje y no en varios. Contanos qué
  instalación estás armando, cuántos baños y artefactos alimenta, y si es agua o desagüe, y
  proveedores verificados te arman una cotización completa de cañería y plomería. Si recién
  estás armando el pedido de toda la instalación, la guía
  <a href="/guias/como-hacer-un-computo-metrico/">cómo hacer un cómputo métrico</a> te ayuda a
  ordenar cantidades y metros antes de consultar.
</p>

<h2>Cómo elegir entre los materiales de plomería</h2>
<p>
  La pregunta que ordena todo es qué hace el agua en cada tramo: si se guarda, si llega con
  presión a un artefacto o si se va por gravedad al desagüe.
</p>
