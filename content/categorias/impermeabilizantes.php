<h2>Qué incluye esta categoría</h2>
<p>
  Impermeabilizar no es un solo producto, es elegir cuál va en cada punto de la obra. Para una
  <strong>losa expuesta</strong> o una azotea transitable, la solución clásica es la
  <a href="/materiales/membrana-asfaltica/">membrana asfáltica</a> en rollo, que cubre
  superficies grandes de una sola pasada. Cuando el techo tiene muchos encuentros, bajadas y
  detalles donde el rollo no entra cómodo, entra la
  <a href="/materiales/membrana-liquida/">membrana líquida</a>, que se aplica con rodillo o
  pincel y también funciona como pintura asfáltica de mantenimiento. Si el problema no es el
  techo sino la <strong>humedad ascendente</strong> que sube por la pared —manchas, salitre,
  revoque que se levanta—, ahí trabaja la
  <a href="/materiales/pintura-antihumedad/">pintura antihumedad</a>, que trata la superficie
  interior. El origen de esa humedad, en cambio, se corta desde adentro de la mezcla: el
  <a href="/materiales/hidrofugo/">hidrófugo</a> es el impermeabilizante para losa y para la
  capa aisladora del cimiento, y va mezclado con el mortero antes de que se asiente cualquier
  hilada. Y para las juntas —vidrios, sanitarios, encuentros con movimiento— están los
  <a href="/materiales/selladores-y-siliconas/">selladores y siliconas</a>, que no reemplazan
  a ninguno de los anteriores pero completan cualquier sistema de impermeabilización.
</p>

<h2>Cómo se cotiza en Paraguay</h2>
<p>
  Cada producto de esta categoría se pide distinto: la membrana asfáltica por rollo según los
  metros cuadrados que cubre cada uno, la membrana líquida y la pintura antihumedad por balde
  según el rendimiento por mano, el hidrófugo por balde o bidón según el volumen de mezcla, y
  los selladores por cartucho o pomo según los metros de junta. Lo que comparten todos es que
  conviene resolver primero el diagnóstico —¿es losa expuesta, es filtración puntual, es
  humedad de cimiento?— porque de ahí sale qué producto corresponde y en qué cantidad, no al
  revés. Si vas a impermeabilizar antes de la temporada de lluvias, contanos la superficie, si
  es azotea o pared, y si la humedad viene de arriba o sube desde abajo: con esos datos,
  proveedores verificados te cotizan lo que efectivamente necesitás, sin duplicar producto.
</p>
